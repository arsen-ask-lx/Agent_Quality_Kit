#!/usr/bin/env bash
# Храповик: обёртка вокруг гейта, которая пускает СТАРЫЕ нарушения и не пускает новые.
#
# ЗАЧЕМ. Правило вводят в проект, где старый код ему не соответствует. Вариантов три, и два
# из них не работают. Большая чистка откладывается навсегда, потому что она большая.
# Необязательное предупреждение не блокирует ничего — его листают, и правило не действует.
# Храповик даёт действующее правило СО ДНЯ УСТАНОВКИ, не требуя трогать старый код.
#
# ПРОВЕРКА, ЧТО ЭТО ХРАПОВИК, А НЕ СОВЕТЧИК: «может ли новый код добавить нарушение и пройти?»
# Может — значит гейта нет.
#
#   bash ratchet.sh <реестр> <команда гейта...>

set -uo pipefail
REG="${1:-}"; shift || true
[ -z "$REG" ] || [ $# -eq 0 ] && { echo "нужно: ratchet.sh <реестр> <команда...>"; exit 2; }

# Ключ нарушения обязан переживать правку соседних строк, иначе сдвиг на строку читается
# как новое нарушение. Поэтому номер строки из ключа убирается.
keys() { grep -E '^[^[:space:]].*:' | sed -E 's/:[0-9]+:/:/' | sort -u; }

OUT="$("$@" 2>&1)"
NOW="$(printf '%s\n' "$OUT" | keys)"

if [ ! -f "$REG" ]; then
  echo "нет реестра $REG — сначала: aqk ratchet <гейт>"
  exit 2
fi
WAS="$(grep -vE '^\s*(#|$)' "$REG" | sort -u)"

NEW="$(comm -23 <(printf '%s\n' "$NOW") <(printf '%s\n' "$WAS"))"
GONE="$(comm -13 <(printf '%s\n' "$NOW") <(printf '%s\n' "$WAS"))"

# Исправленное вычёркивается сразу: иначе однажды исправленное нарушение остаётся
# разрешённым навсегда, и храповик перестаёт затягиваться.
if [ -n "$GONE" ]; then
  COUNT=$(printf '%s\n' "$GONE" | grep -c .)
  HEAD="$(grep -E '^[[:space:]]*#' "$REG" || true)"

  # Сначала пишем, потом сообщаем. Обратный порядок однажды напечатал «храповик затянут»,
  # не переписав файл: список стал пустым, grep вернул единицу и отменил запись по &&.
  { [ -n "$HEAD" ] && printf '%s\n' "$HEAD"
    printf '%s\n' "$NOW" | grep -v '^[[:space:]]*$' || true
  } > "$REG.tmp"
  mv "$REG.tmp" "$REG"
  echo "храповик затянут: исправлено $COUNT, вычеркнуто из реестра"
fi

if [ -n "$NEW" ]; then
  echo "новых нарушений: $(printf '%s\n' "$NEW" | grep -c .)"
  printf '%s\n' "$NEW" | sed 's/^/  /'
  echo "  почини их: реестр долга разрешается только укорачивать."
  echo "  старые нарушения из $REG пропущены — они долг, а не разрешение."
  exit 1
fi
exit 0
