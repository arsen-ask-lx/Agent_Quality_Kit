#!/usr/bin/env sh
# Секрет, попавший в историю, из неё уже не убрать: ветку перепишут, а копии останутся у всех,
# кто её тянул. Поэтому проверка стоит до коммита, а не «иногда руками».
DIR="${1:-.}"
# Существование файла проверяется ДО `.`, а не запасной веткой после. Прежняя строка
# `. файл 2>/dev/null || запасной_вариант` выглядела страховкой и ею не была: под `sh` (dash)
# неудачный `.` завершает скрипт немедленно, и ветка после `||` не выполняется никогда; под
# `bash`, которым гейты и запускаются из манифеста, она выполняется, но подставляет только
# ПЕРЕМЕННУЮ — функции обхода остаются неопределёнными, конвейер печатает пустоту, и проверка
# выходит с НУЛЁМ. Замерено 2026-09-08 на файле с настоящим нарушением: гейт сказал «чисто».
SKIP_LIB="$(dirname "$0")/../_skip.sh"
if [ ! -f "$SKIP_LIB" ]; then
  echo "рядом с проверкой нет _skip.sh — обход не собран, проверка не состоялась"
  echo "  почини: скопируй гейт вместе с файлом kit/gates/_skip.sh, он общий на весь каталог"
  exit 2
fi
. "$SKIP_LIB"
# Файл на месте — этого мало: подмена содержимого давала код 0. Метка стоит в КОНЦЕ _skip.sh,
# поэтому проверка ловит и обрыв файла на середине.
if [ "${AQK_SKIP_READY:-}" != 1 ]; then
  echo "_skip.sh есть, но обход не собрался — проверка НЕ СОСТОЯЛАСЬ, а не прошла"
  echo "  почини: замени kit/gates/_skip.sh целым файлом из каталога"
  exit 2
fi
# Красный образец — намеренно сломанный код в репозитории. Сканирующий гейт обязан его
# пропускать, иначе будет вечно краснеть на том, что сам же и положил. Исключение снимается,
# когда проверяют сам образец: тогда каталог red и есть цель проверки.
# Два прохода, а не один, и разница между ними измерена. Живой облачный ключ — находка везде,
# включая тестовые каталоги: он открывает настоящий счёт. Приватный КЛЮЧ в тестовых данных —
# норма: любой проект с проверками TLS кладёт туда сертификат, и Go так делает по соглашению.
# Замер 2026-09-08 по шести чужим репозиториям: gin краснел на testdata/certificate/key.pem,
# положенном туда намеренно. Гейт, краснеющий на нормальном укладе, выключают в первый день —
# и тогда он не ловит уже НИЧЕГО, включая настоящий ключ.
TOKENS='(sk|pk)_(live|test)_[A-Za-z0-9]{16,}|AKIA[0-9A-Z]{16}|ghp_[A-Za-z0-9]{30,}|xox[baprs]-[A-Za-z0-9-]{10,}'
PRIVKEY='-----BEGIN [A-Z ]*PRIVATE KEY-----'
# Каталоги образцов: только те, чьё имя не оставляет сомнений. `data` или `assets` сюда не
# входят — там ключ вполне может оказаться настоящим.
FIXTURES='(^|/)(testdata|fixtures|__fixtures__|test|tests|spec|__tests__)/'

HITS=$(
  { grep -rInE $(skip_grep "$DIR") -e "$TOKENS" "$DIR" 2>/dev/null
    grep -rInE $(skip_grep "$DIR") -e "$PRIVKEY" "$DIR" 2>/dev/null | grep -vE "$FIXTURES"
  } | grep -v '/\.git/' | own_samples_filter "$DIR" | sort -u)
if [ -n "$HITS" ]; then
  echo "$HITS" | cut -c1-160
  echo "  почини: убери значение из файла, положи его в переменную окружения и отзови старый ключ."
  echo "  из истории секрет уже не вычистить — считай его скомпрометированным."
  exit 1
fi
exit 0
