# Общий шов для проверок, судящих ПУТЬ, взятый из текста.
#
# ЗАЧЕМ ЭТОТ ФАЙЛ. Замеры 14-15 сентября 2026 по 290 чужим репозиториям нашли у нас двенадцать
# ложных срабатываний. Разбор показал, что это не двенадцать ошибок, а ОДНА, повторённая
# двенадцатью способами: мы судили строку как путь на диске, не зная, чем она разрешается.
# Разрешало её то, чего у нас нет, — адрес на github.com, переменная окружения, генератор сайта,
# соседний репозиторий вики, проза вокруг.
#
# Чинить такое по одному значит растить в каждом гейте свой список исключений; через три правки
# списки разойдутся, и дважды пойманная беда вернётся через тот гейт, куда её не дописали.
# Поэтому решение одно и здесь.
#
# ТРИ ИСХОДА, А НЕ ДВА — тот же договор, что у всего комплекта:
#   disk        путь ведёт на файл в этом каталоге, судить можно
#   unresolved  разрешается чем-то, чего у нас нет: МОЛЧАТЬ НЕЛЬЗЯ, но и обвинять нельзя
#   skip        не путь вовсе (сеть, почта, якорь) — говорить не о чем

# Якорь и строка запроса — не часть имени файла. `assets/x.gif?raw=1` лежит на диске как
# `assets/x.gif`, `tutorial/#install` — это адрес страницы. Чистится ЗДЕСЬ, а не у зовущего:
# иначе каждый гейт будет чистить по-своему, и один забудет.
clean_target() {
  T="${1%%#*}"
  printf '%s' "${T%%\?*}"
}

# Возвращает слово исхода, а для unresolved — ещё и причину через двоеточие.
classify_target() {
  T="$1"
  case "$T" in
    ""|\#*) echo "skip"; return ;;
    # ЛЮБАЯ СХЕМА, В ЛЮБОМ РЕГИСТРЕ. Замер 2026-09-15: `file://Users/...` и
    # `Https://conventionalcommits.org` с заглавной H объявлены битыми файлами. Раньше узнавались
    # только `http://` и `https://` строчными — и это была догадка о том, как люди пишут.
    *://*|mailto:*|MAILTO:*) echo "skip"; return ;;
    # Адрес почты целью ссылки без «mailto:». Замер: три таких объявлены битыми файлами.
    *@*.*) echo "skip"; return ;;
  esac
  case "$T" in
    # Путь, уходящий выше корня: так сам GitHub предлагает ссылаться на выпуски и задачи —
    # `../../releases` считается от адреса файла в вебе. Проверено: страница отдаёт 200.
    ../*) echo "unresolved:адрес на github.com" ;;
    # Путь от корня САЙТА, а не репозитория.
    /*) echo "unresolved:адрес на github.com" ;;
    # Страница вики живёт в отдельном репозитории `<репо>.wiki`, которого мы не скачиваем.
    wiki/*) echo "unresolved:вики в отдельном репозитории" ;;
    # Путь с косой чертой на конце и страница `.html` — это адрес опубликованного сайта:
    # mkdocs, docusaurus, pkgdown собирают их при публикации. Проверено: 200 на их сайтах.
    */|*.html|*.htm) echo "unresolved:страницу собирает генератор сайта" ;;
    # Нераскрытая переменная: значение задаётся снаружи.
    *'$'*) echo "unresolved:путь зависит от переменной" ;;
    *) echo "disk" ;;
  esac
}
