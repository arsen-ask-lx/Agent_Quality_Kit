#!/usr/bin/env sh
# Объявленный MCP-сервер, которого на деле нет: команда указывает на файл, которого не
# существует, либо версия не закреплена и завтра приедет другая.
#
# ЗАЧЕМ. Сервер, который не поднялся, агенту НИКАК не виден: у него просто нет этих
# инструментов, и он молча работает без них. Ни ошибки, ни строки в журнале — та же тишина,
# что у хука с опечаткой в имени события. Настройка выглядит как возможность и возможностью
# не является.
#
# ПРОВЕРЕНО НА СЕБЕ 2026-09-08. Записали в проект настройку chrome-devtools-mcp, выглядела
# безупречно. Сервер был мёртв: puppeteer подхватывал Windows-овый Chrome из /mnt/c/ и падал
# с «Target closed». Узнали только потому, что запустили руками и прочитали журнал; обычно
# так не делают — записали конфиг, увидели «сохранено», пошли дальше.
#
# ЧТО ЭТА ПРОВЕРКА НЕ ДЕЛАЕТ. Она НЕ запускает серверы. Запуск — это исполнение чужих команд
# на каждый коммит, скачивание пакетов и минуты ожидания; такую проверку выключают в первый
# день. Здесь ловится только то, что видно без запуска, и этого достаточно для двух самых
# частых смертей: файла нет и версия плавает.
DIR="${1:-.}"
SKIP_LIB="$(dirname "$0")/../_skip.sh"
if [ ! -f "$SKIP_LIB" ]; then
  echo "рядом с проверкой нет _skip.sh — обход не собран, проверка не состоялась"
  echo "  почини: скопируй гейт вместе с файлом kit/gates/_skip.sh, он общий на весь каталог"
  exit 2
fi
. "$SKIP_LIB"

OUT=""
for F in "$DIR/.mcp.json" "$DIR/.cursor/mcp.json" "$DIR/.vscode/mcp.json" "$DIR/.claude/mcp.json"; do
  [ -f "$F" ] || continue
  RES=$(awk -v file="$F" -v dir="$DIR" '
    # Номера строк с командой копятся отдельно от текста: разбор идёт в END по всему файлу
    # одной строкой (иначе минифицированный JSON не разобрать), а находку надо привязать к
    # строке — без неё `--since` не сверит путь с дифом и гейт зазеленеет на чужом дифе.
    /"command"[ \t]*:/ { cline[++ci] = NR }
    { buf = buf $0 " " }
    END {
      n = split(buf, part, /"command"[ \t]*:/)
      for (i = 2; i <= n; i++) {
        chunk = part[i]
        if (!match(chunk, /"[^"]*"/)) continue
        cmd = substr(chunk, RSTART + 1, RLENGTH - 2)
        line = cline[i - 1] ? cline[i - 1] : 1

        # 1. Абсолютный путь, которого нет. Самая частая смерть у пакетов, чья версия вшита
        # в имя файла: обновились — старый файл удалён, сервер умер, никто не заметил.
        if (substr(cmd, 1, 1) == "/") {
          if (system("test -e \"" cmd "\"") != 0)
            print file ":" line ": команда сервера не существует: " cmd
          continue
        }

        # 2. Скачивающий запуск без точной версии. `@latest` и голое имя означают «сегодня
        # одно, завтра другое», а для сервера, которому доверен браузер и файлы, это дверь
        # в цепочке поставок. Правило то же, что у нас для зависимостей.
        if (cmd == "npx" || cmd == "uvx" || cmd == "pipx" || cmd == "bunx" || cmd == "pnpm") {
          args = ""
          if (match(chunk, /"args"[ \t]*:[ \t]*\[[^]]*\]/)) args = substr(chunk, RSTART, RLENGTH)
          if (args == "") continue
          if (args ~ /@latest/) {
            print file ":" line ": версия сервера не закреплена (@latest): " cmd
            continue
          }
          # Имя пакета — первый довод, не начинающийся с дефиса. Точная версия пишется как
          # name@1.2.3 (npm) или name==1.2.3 (python); без неё запуск невоспроизводим.
          m = args
          gsub(/"args"[ \t]*:[ \t]*\[/, "", m); gsub(/\]/, "", m)
          k = split(m, tok, ",")

          # СЕРВЕР ИЗ СВОЕГО РЕПОЗИТОРИЯ — не находка. `npx tsx rag/src/index.ts` запускает
          # СВОЙ файл, а npx здесь только запускалка: код сервера лежит в репозитории и уже
          # под версией — той же, что и весь проект. Требовать закрепить `tsx` значит краснеть
          # на нормальном укладе, а такой гейт выключают в первый день. Найдено замером по
          # двадцати чужим настройкам с GitHub 2026-09-08: две из десяти находок были ровно
          # этим. Тот же класс, что четыре ложных срабатывания на чужом коде до этого.
          local_entry = 0
          for (j = 1; j <= k; j++) {
            t = tok[j]; gsub(/^[ \t"]+|[ \t"]+$/, "", t)
            # Признак локального входа — расширение файла или явно относительный путь.
            # Просто «есть слэш» не годится: `@scope/name` — это имя пакета в npm, и первая
            # версия этой проверки съела настоящую находку `npx @meridian/docs-mcp`. Поймано
            # тем же замером по двадцати чужим настройкам: находок стало восемь вместо девяти,
            # и пропажу было видно только построчным сравнением до и после.
            if (t ~ /\.(ts|js|mjs|cjs|py|rb|sh)$/ || t ~ /^\//  || t ~ /^\.\// || t ~ /^\.\.\//) { local_entry = 1; break }
          }
          if (local_entry) continue

          for (j = 1; j <= k; j++) {
            t = tok[j]; gsub(/^[ \t"]+|[ \t"]+$/, "", t)
            if (t == "" || substr(t, 1, 1) == "-") continue
            if (t ~ /@[0-9]/ || t ~ /==[0-9]/) break
            print file ":" line ": версия сервера не закреплена: " cmd " " t
            break
          }
        }
      }
    }
  ' "$F")
  [ -n "$RES" ] && OUT="${OUT}${RES}
"
done

OUT=$(printf '%s' "$OUT" | own_samples_filter "$DIR" | sed '/^$/d')
if [ -n "$OUT" ]; then
  printf '%s\n' "$OUT"
  echo "  почини: закрепи точную версию (пакет@1.2.3) и убедись, что файл команды существует."
  echo "  мёртвый сервер агенту не виден: он просто работает без этих инструментов и молчит."
  exit 1
fi
exit 0
