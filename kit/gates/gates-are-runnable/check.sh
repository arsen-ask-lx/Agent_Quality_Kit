#!/usr/bin/env sh
# Гейт, объявленный в манифесте, но не запускающийся, — худший из возможных: отсутствие
# сигнала неотличимо от успеха. Проверяем не результат работы гейта, а то, что его вообще
# есть чем выполнить: файл скрипта на месте, программа установлена.
DIR="${1:-.}"
MAN="$DIR/.aqk.yml"
[ -f "$MAN" ] || { echo "нет .aqk.yml — проверять нечего"; exit 0; }

# строки вида `  имя: "команда"` внутри блока gates:
LINES=$(awk '/^gates:/{g=1;next} /^[A-Za-z]/{g=0} g && /^[[:space:]]+[A-Za-z0-9_-]+:/{print}' "$MAN")
[ -z "$LINES" ] && { echo "гейтов не объявлено"; exit 0; }

BAD=0
echo "$LINES" | while IFS= read -r L; do
  NAME=$(echo "$L" | sed 's/^[[:space:]]*\([A-Za-z0-9_-]*\):.*/\1/')
  CMD=$(echo "$L" | sed 's/^[[:space:]]*[A-Za-z0-9_-]*:[[:space:]]*//; s/^"//; s/"$//')
  [ -z "$CMD" ] && { echo "гейт «$NAME»: команда пустая"; echo "  почини: впиши команду или убери строку — объявление без команды защиты не даёт"; exit 1; }

  # первое слово — программа; аргумент, похожий на путь, — скрипт
  PROG=$(echo "$CMD" | awk '{print $1}')
  command -v "$PROG" >/dev/null 2>&1 || {
    echo "гейт «$NAME»: программа «$PROG» не установлена"
    echo "  почини: поставь её или замени команду — сейчас гейт молча не выполняется"
    exit 1
  }
  for A in $CMD; do
    case "$A" in
      */*) [ -e "$DIR/$A" ] || { echo "гейт «$NAME»: файл «$A» не существует"; echo "  почини: путь в манифесте указывает в никуда — отсутствие сигнала читается как успех"; exit 1; } ;;
    esac
  done
done || BAD=1
exit $BAD
