#!/usr/bin/env sh
# Набор объявленных гейтов может только РАСТИ. Убрать гейт можно, но не молча.
#
# ЗАЧЕМ. Комплект ловит агента, когда тот выключает сигнал: `# noqa`, `pytest || true`,
# ослабленный тест. А главный рубильник — сам манифест — не сторожил никто. Замер 2026-09-09:
# четыре гейта и настоящий секрет в коде дают код 1; убираешь ОДНУ строку из `.aqk.yml` —
# `Порог AQK-1 пройден`, код 0, секрет на месте, файлы гейта на диске. Ни `doctor`, ни `report`,
# ни `vitals`, ни блок состояния для агента этого не заметили.
#
# Это `pytest || true` этажом выше. И бьёт сильнее обычного обхода: `# noqa` виден в коде, а
# удалённая строка — это ОТСУТСТВИЕ, а отсутствие не рецензируют.
#
# ЧТО ЭТО НЕ ЗАПРЕЩАЕТ. Снять гейт по-прежнему можно — но названно. Причина пишется в реестре
# после `#`, как `deprecated` обязан нести `superseded_by`: решение остаётся за человеком и
# перестаёт быть невидимым.
DIR="${1:-.}"
MAN="$DIR/.aqk.yml"
[ -f "$MAN" ] || { echo "нет .aqk.yml — проверять нечего"; exit 0; }

MANTEXT="$(tr -d '\r' < "$MAN")"

# Имена гейтов из блока gates:. Пустая команда защиты не даёт — такие не считаем объявленными.
DECLARED="$(printf '%s\n' "$MANTEXT" \
  | awk '/^gates:/{g=1;next} /^[A-Za-z]/{g=0} g && /^[[:space:]]+[A-Za-z0-9_-]+:[[:space:]]*[^[:space:]]/{print}' \
  | sed 's/^[[:space:]]*\([A-Za-z0-9_-]*\):.*/\1/' | LC_ALL=C sort -u)"
[ -z "$DECLARED" ] && { echo "гейтов не объявлено — сторожить нечего"; exit 0; }

# Кавычки снимаются, и ПУСТОЕ значение считается отсутствующим. `init` кладёт `ratchets: ""`
# намеренно — пустое поле честнее заглушки, — и без снятия кавычек путь получался «""/…»:
# сообщение с таким путём человек не может выполнить. Найдено первым же прогоном в чужом
# проекте, а не на нашем репозитории, где поле заполнено.
RDIR="$(printf '%s\n' "$MANTEXT" | sed -n 's/^ratchets:[[:space:]]*//p' | head -1 \
  | sed 's/^"//; s/"$//; s/^'"'"'//; s/'"'"'$//; s/[[:space:]]*$//')"
[ -z "$RDIR" ] && RDIR="ratchets"
REG="$DIR/$RDIR/gates-declared.txt"
REL="$RDIR/gates-declared.txt"

# ПРОВЕРКА ТОЛЬКО СРАВНИВАЕТ. Раньше она сама создавала снимок и дописывала в него новые
# гейты — то есть меняла то, о чём судит. Цена измерена опытом 2026-09-09: в мелком клоне, где
# удаление снимка лежит ГЛУБЖЕ выкладки, свидетель (история git) слеп, и проверка записала УЖЕ
# ОСЛАБЛЕННЫЙ набор новым эталоном — «снят снимок: 2 гейтов», код 0, исчезнувший гейт узаконен.
# Храповик крутился назад. Писать снимок — дело явной операции (`aqk add`), а не вердикта.
if [ ! -f "$REG" ]; then
  # Два разных случая, и путать их нельзя: снимка ещё не снимали — или его УДАЛИЛИ, что и есть
  # тот самый обход, только другим файлом. Свидетель — git: если у пути есть история, файл был.
  # В мелком клоне свидетель слеп, и поэтому отсутствие снимка красное в ОБОИХ случаях.
  if git -C "$DIR" log -1 --format=%H -- "$REL" 2>/dev/null | grep -q .; then
    echo "$REL был в истории и удалён — снимок объявленной защиты уничтожен"
    echo "  почини: верни файл (git checkout -- $REL). Удаление снимка снимает и саму проверку —"
    echo "  почини: это тот же обход, что удаление гейта, только через соседний файл."
    exit 1
  fi
  echo "$REL: снимка объявленной защиты нет — без него удаление гейта не видно"
  echo "  почини: заведи файл со списком объявленных сейчас гейтов и закоммить его."
  echo "  почини: содержимое:"
  echo "    # Снимок объявленной защиты. Набор может только РАСТИ."
  echo "    # Убрал гейт — напиши причину после # в его строке, иначе проверка краснеет."
  printf '%s\n' "$DECLARED" | sed 's/^/    /'
  exit 1
fi

# Имя без причины — строка реестра, где после имени НЕТ решётки. Имя с причиной — снятое
# осознанно; печатаем его отдельно, но прогон не роняем.
GONE=""
NAMED=""
while IFS= read -r LINE; do
  case "$LINE" in ''|'#'*) continue ;; esac
  NAME=$(printf '%s' "$LINE" | sed 's/[[:space:]]*#.*//; s/[[:space:]]*$//')
  [ -z "$NAME" ] && continue
  printf '%s\n' "$DECLARED" | grep -qx "$NAME" && continue
  case "$LINE" in
    *'#'*) NAMED="$NAMED $NAME" ;;
    *)     GONE="$GONE $NAME" ;;
  esac
done < "$REG"

[ -n "$NAMED" ] && echo "совет: снято осознанно и названо в $REL:$NAMED"

if [ -n "$GONE" ]; then
  for N in $GONE; do
    echo "$REL: гейт «$N» был объявлен и исчез из .aqk.yml"
  done
  echo "  почини: верни строку в gates: — либо, если снял намеренно, напиши причину в $REL"
  echo "  почини: после имени через #, например «$N  # снят: закрыт гейтом lint»."
  exit 1
fi

# СНИМОК, ОТСТАВШИЙ ОТ МАНИФЕСТА, — ТОЖЕ РАСХОЖДЕНИЕ. Раньше проверка дописывала новые имена
# сама и выходила с нулём. Это удобно и неверно: гейт, добавленный и убранный до того, как
# снимок обновят, уходит незамеченным — а сама проверка при этом молча правит рабочее дерево,
# в том числе в конвейере. Храповик обязан ТРЕБОВАТЬ записи, а не догонять её.
NEW=""
for N in $DECLARED; do
  sed 's/[[:space:]]*#.*//; s/[[:space:]]*$//' "$REG" | grep -qx "$N" || NEW="$NEW $N"
done
if [ -n "$NEW" ]; then
  for N in $NEW; do echo "$REL: гейт «$N» объявлен, но в снимке его нет"; done
  echo "  почини: допиши эти имена в $REL и закоммить — снимок обязан знать всё, что защищает."
  exit 1
fi
exit 0
