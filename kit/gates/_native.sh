#!/usr/bin/env sh
# Запуск РОДНОГО инструмента (ruff, vulture, eslint, jscpd) через тот же фильтр образцов,
# которым пользуются переносимые проверки.
#
# ЗАЧЕМ. Переносимая проверка прячет `gates/<имя>/red|green` — искусственный код, положенный
# самим комплектом. Родной инструмент о них не знает и выдаёт их как находки: в любом проекте,
# куда поставили гейты, `ruff --select T20 .` покажет печать из нашего же красного образца.
# Гейт, который на девять десятых состоит из собственных образцов, читать не будут — его
# выключат целиком. Ровно так же выключают гейт, где 94% находок пришли из чужого кода.
#
# ПОЧЕМУ ФИЛЬТР ВЫВОДА, А НЕ ФЛАГ ИСКЛЮЧЕНИЯ У КАЖДОГО ИНСТРУМЕНТА. Флаг у всех свой
# (`--exclude`, `--ignore-pattern`, `--ignore`), синтаксис шаблона у всех разный, а главное —
# статичный флаг нельзя снять, когда проверяют САМ образец: тогда инструмент спрячет ровно то,
# что должен найти, и запись пройдёт приёмку зелёной на красном образце. Фильтр вывода знает,
# что за каталог ему дали, и снимает исключение сам — та же логика, что в own_samples_filter.
#
# ПОЧЕМУ У РЕЦЕПТОВ ВСЁ-ТАКИ ЕСТЬ ФЛАГИ ПРО ИСКЛЮЧЕНИЯ — И ТОЛЬКО ЭТИ. Фильтр вывода прячет
# лишнее, но он не может ВЕРНУТЬ находку, которую инструмент не сделал. Ruff, pylint и vulture
# читают конфигурацию проекта, и одной строкой в ней (`extend-exclude`, `ignore`,
# `ignore-patterns`, `[tool.vulture] exclude`) путь выпадает из проверки целиком. Замер
# 2026-09-26: пять таких строк дали пять зелёных гейтов при нарушении, лежащем в коде на месте.
# Поэтому рецепты несут `--isolated` (ruff), `--ignore= --ignore-patterns=` (pylint) и непустой
# `--exclude` (vulture): они отменяют ИСКЛЮЧЕНИЕ ПУТИ из конфигурации инструмента. Довод выше
# про статичный флаг это не нарушает — флаг тут не прячет пути, а запрещает их прятать, и на
# самом образце он ведёт себя так же, как везде.
#
# ЧЕГО ЭТИ ФЛАГИ НАМЕРЕННО НЕ ЗАБИРАЮТ. Подавление ПО ИМЕНИ остаётся: `# noqa: T201`,
# `[tool.vulture] ignore_names`, `# pylint: disable=R0801`. Во-первых, `gate-not-weakened`
# краснеет только на БЕЗАДРЕСНОМ подавлении и считает названное правило законным инструментом.
# Во-вторых, замены именам у `.aqkignore` нет: забрав `ignore_names`, мы получим находки на
# каркасных обратных вызовах — то есть гейт, который выключат целиком. Цена названа здесь, а не
# умолчана: подавление по имени видно в дифе, исключение пути в конфиге — нет.
#
# ГДЕ ЖИВУТ ИСКЛЮЧЕНИЯ ПРОЕКТА. В `.aqkignore`, в одном месте, и `aqk report` печатает их
# отдельной графой. Конфигурация инструмента как второй источник той же правды запрещена именно
# потому, что она невидима в отчёте.
#
#   bash gates/_native.sh <каталог> <команда инструмента…>

DIR="${1:-.}"
shift || true
[ "$#" -gt 0 ] || { echo "нечего запускать: не передана команда инструмента"; exit 2; }

. "$(dirname "$0")/_skip.sh" 2>/dev/null || { echo "не найден _skip.sh рядом с _native.sh"; exit 2; }
if [ "${AQK_SKIP_READY:-}" != 1 ]; then
  echo "_skip.sh есть, но обход не собрался — проверка НЕ СОСТОЯЛАСЬ, а не прошла"
  exit 2
fi

. "$(dirname "$0")/_exit.sh" 2>/dev/null && command -v aqk_exit_verdict >/dev/null 2>&1 || {
  echo "не работает _exit.sh — проверка НЕ СОСТОЯЛАСЬ"; exit 2;
}

# Два фильтра, а не один: own_samples_filter прячет образцы гейтов и то, что назвал проект
# в .aqkignore, а skip_paths_filter — общий список каталогов, который переносимые проверки
# получают при обходе. Родному инструменту он не доставался вовсе, и он читал `.aqk/`,
# `node_modules` и `.venv`. На живом проекте это дало 5597 строк вывода, где первой находкой
# были методички самого комплекта.
# Цвет снимается ДО фильтров. Родные инструменты печатают путь внутри escape-последовательности
# («\033[32m.aqk/docs/…»), и тогда имя каталога стоит не после «/» и не с начала строки — фильтр
# по границе пути его не видит. На живом проекте это выглядело как работающая правка: вывод
# сократился с 5597 строк до 5505, то есть не сократился. Заодно лог конвейера читается глазами.
# Код возврата берётся у САМОГО инструмента, до всякой обработки: в конвейере `$?` — это код
# последней команды, и снятие цвета молча делало бы любой прогон успешным.
OUT_RAW="$("$@" 2>&1)"; CODE=$?
aqk_exit_verdict "$1" "$CODE"; VERDICT=$?
# Ошибку процесса нельзя фильтровать по путям: даже скрытый путь не отменяет сбой.
if [ "$VERDICT" -eq 2 ] || { [ "$CODE" -ne 0 ] && [ -z "$OUT_RAW" ]; }; then
  printf '%s\n' "$OUT_RAW"
  echo "инструмент завершился с кодом $CODE — проверка НЕ СОСТОЯЛАСЬ"
  exit 2
fi

# ESC подставляется через printf, а не пишется как \x1b: это расширение GNU sed, а гейты
# обязаны работать на любом sh.
ESC="$(printf '\033')"
OUT="$(printf '%s' "$OUT_RAW" | sed -e "s/${ESC}\[[0-9;]*[a-zA-Z]//g")"
LEFT="$(printf '%s' "$OUT" | skip_paths_filter | own_samples_filter "$DIR")"

# Отказ не выдумываем: если инструмент завершился успешно, результат успешен, что бы ни
# осталось в выводе. Красным делаем только то, что инструмент И счёл отказом, И что пережило
# фильтр — иначе спрятанный образец превратился бы в неустранимый красный.
if [ "$VERDICT" -eq 1 ] && [ -n "$LEFT" ]; then
  printf '%s\n' "$LEFT"
  exit 1
fi
exit 0
