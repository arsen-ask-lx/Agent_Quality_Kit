#!/usr/bin/env sh
# Пределы: прод-код 500 строк, компонент интерфейса 300, тест 800.
#
# ЗАЧЕМ. Агент теряется в больших файлах и начинает переписывать вместо правки. И растут они
# не по замыслу: каждую новую фичу дописывают в тот же файл, потому что агенту так ближе по
# контексту. Числа спорные — важно, что предел существует и его считает машина.
DIR="${1:-.}"
# Существование файла проверяется ДО `.`, а не запасной веткой после. Прежняя строка
# `. файл 2>/dev/null || запасной_вариант` выглядела страховкой и ею не была: под `sh` (dash)
# неудачный `.` завершает скрипт немедленно, и ветка после `||` не выполняется никогда; под
# `bash`, которым гейты и запускаются из манифеста, она выполняется, но подставляет только
# ПЕРЕМЕННУЮ — функции обхода остаются неопределёнными, конвейер печатает пустоту, и проверка
# выходит с НУЛЁМ. Замерено 2026-09-08 на файле с настоящим нарушением: гейт сказал «чисто».
SKIP_LIB="$(dirname "$0")/../_skip.sh"
if [ ! -f "$SKIP_LIB" ]; then
  echo "рядом с проверкой нет _skip.sh — обход не собран, проверка не состоялась"
  echo "  почини: скопируй гейт вместе с файлом kit/gates/_skip.sh, он общий на весь каталог"
  exit 2
fi
. "$SKIP_LIB"
# Файл на месте — этого мало: подмена содержимого давала код 0. Метка стоит в КОНЦЕ _skip.sh,
# поэтому проверка ловит и обрыв файла на середине.
if [ "${AQK_SKIP_READY:-}" != 1 ]; then
  echo "_skip.sh есть, но обход не собрался — проверка НЕ СОСТОЯЛАСЬ, а не прошла"
  echo "  почини: замени kit/gates/_skip.sh целым файлом из каталога"
  exit 2
fi

# Один обход и один wc на все файлы разом: на проекте в 36 тысяч файлов цикл с wc на каждый
# не укладывался в две минуты.
# shellcheck disable=SC2046
find "$DIR" $(skip_find "$DIR") -type f -print 2>/dev/null | only_code | own_samples_filter "$DIR" \
  | drop_generated \
  | xargs -r wc -l 2>/dev/null \
  | awk '
      $2 == "total" { next }
      {
        n = $1; f = $2
        limit = 500; kind = "прод-код"
        if (f ~ /(test|spec)/)        { limit = 800; kind = "тест" }
        else if (f ~ /\.(jsx|tsx|vue)$/) { limit = 300; kind = "компонент" }
        # Число строк стоит в позиции номера строки нарочно: храповик вырезает «:N:» из ключа,
        # и запись о нарушении не меняется от каждой добавленной строки. Иначе рост файла на
        # строку читался бы как новое нарушение, а сокращение — тоже как новое.
        if (n > limit) { print f ":" n ": длиннее предела для «" kind "» — " limit " строк"; bad = 1 }
      }
      END { exit bad ? 1 : 0 }
    ' || {
      echo "  почини: раздели по смыслу, а не пополам. Файл растёт не по замыслу — в него"
      echo "  дописывают каждую новую правку, потому что так ближе по контексту."
      exit 1
    }
exit 0
