#!/usr/bin/env sh
# Коммит без мини-отчёта — риск того же класса, что несоответствие спеки коду: диффом можно
# проверить реализацию, но не то, понял ли автор замысел. Отчёт — дешёвый артефакт, который
# оставляет след для человека, читающего историю позже.
DIR="${1:-.}"

# Образцы (gates.sh) читают тело коммита из `.aqk-commit-msg` — реальный git log там взять неоткуда, а
# вложенный .git внутри каталога комплекта сам по себе создал бы embedded-репозиторий.
# В настоящем проекте такого файла не бывает — читается последний реальный коммит.
# Имя с точкой намеренно: `COMMIT_MSG` в корне проекта — вещь возможная (так зовут заготовку
# сообщения многие обёртки над git), и такой файл молча подменял бы собой настоящий коммит.
# Тот же дефект нашло ревью у `personal-config-not-shared` 2026-09-07; здесь он был с самого
# начала и не всплывал.
if [ -f "$DIR/.aqk-commit-msg" ]; then
  MSG=$(cat "$DIR/.aqk-commit-msg")
else
  if ! (cd "$DIR" 2>/dev/null && git rev-parse --git-dir >/dev/null 2>&1); then
    echo "не git-репозиторий — проверять нечего"
    exit 0
  fi
  # Мелкий клон: у коммита не видно родителя, и git выдаёт всё дерево как изменённое. Состав
  # коммита в этом случае не определить, а требовать отчёт вслепую нельзя — конвейер краснел бы
  # на каждой записи журнала. Пропускаем, назвав причину: гейт этот всё равно местный, чинят его
  # до пуша, а не после. Причина печатается, а не прячется.
  if [ "$(cd "$DIR" && git rev-parse --is-shallow-repository 2>/dev/null)" = "true" ] &&
     ! (cd "$DIR" && git rev-parse -q --verify HEAD^ >/dev/null 2>&1); then
    echo "мелкий клон: состав коммита не определить — проверка пропущена"
    echo "  чтобы она работала в конвейере, дай ему два коммита истории:"
    echo "  actions/checkout@v4 с fetch-depth: 2"
    exit 0
  fi

  # Сообщение слияния сочиняет не автор, а инструмент. GitHub делает это дважды и по-разному:
  # при разборе предложения изменений выкладывает синтетический коммит «Merge <sha> into <sha>»,
  # а кнопка Merge на сайте пишет «Merge pull request #N from …». Первую форму гейт научился
  # различать вчера по словам — и на второй покраснел бы снова.
  #
  # Поэтому смотрим не на слова, а на форму: у слияния два родителя. Если при этом в сообщении
  # нет разделов отчёта — его писал инструмент, и спрашивать надо второго родителя, последний
  # коммит автора. Слияние, которое автор описал сам, проходит по HEAD и ничего не теряет.
  REF=HEAD
  PARENTS=$(cd "$DIR" && git rev-list --parents -n 1 HEAD 2>/dev/null | wc -w)
  HEADMSG=$(cd "$DIR" && git log -1 --format=%B 2>/dev/null)
  if [ "${PARENTS:-0}" -ge 3 ] &&
     ! printf '%s\n' "$HEADMSG" | grep -q "^Сделано:" &&
     ! printf '%s\n' "$HEADMSG" | grep -q "^Не уверен:"; then
    if (cd "$DIR" && git rev-parse -q --verify HEAD^2 >/dev/null 2>&1); then
      REF=HEAD^2
    else
      echo "слияние без отчёта, второго родителя не видно — проверка пропущена"
      echo "  дай конвейеру два коммита истории: actions/checkout@v4 с fetch-depth: 2"
      exit 0
    fi
  fi

  MSG=$(cd "$DIR" && git log -1 --format=%B "$REF" 2>/dev/null)

  # Коммит, который трогает только журнал, отчёта в теле не требует: сама запись и есть отчёт,
  # причём подробнее — и её сторожит `lesson-has-outcome`. Иначе гейт воюет с командой `note`,
  # которая коммитит запись сама. Путь журнала берётся из манифеста, а не угадывается.
  # «#…» режется так же, как это делает сама программа при разборе манифеста
  # (tool/lib/manifest.mjs): один файл обязан читаться по одним правилам.
  LESSONS=$(sed -n 's/^lessons:[[:space:]]*//p' "$DIR/.aqk.yml" 2>/dev/null | head -1 |
    sed 's/#.*$//' | tr -d '"'"'"' \r' | sed 's/[[:space:]]*$//')
  [ -z "$LESSONS" ] && LESSONS="incidents"
  case "$LESSONS" in http*) LESSONS="" ;; esac   # journal по адресу, а не путём — не применимо
  if [ -n "$LESSONS" ]; then
    # СОСТАВ КОММИТА СЧИТАЕТСЯ ДИФФОМ С РОДИТЕЛЕМ, а родителя может не быть видно. При разборе
    # предложения изменений GitHub выкладывает синтетический коммит слияния мелким клоном: сам
    # коммит автора (`HEAD^2`) в клоне есть, а его родителя нет. `git show --name-only` в этом
    # случае считает коммит КОРНЕВЫМ и выдаёт всё дерево — освобождение «трогает только журнал»
    # переставало срабатывать МОЛЧА, и гейт требовал отчёт там, где не должен.
    #
    # Поймано конвейером на записи в собственный журнал 2026-09-09; опыт показал границу точно:
    # глубина 2 — красный, глубина 3 — чисто. Молчать здесь нельзя: пропуск называет себя, иначе
    # выключенная проверка неотличима от работающей.
    if ! (cd "$DIR" && git rev-parse -q --verify "$REF^" >/dev/null 2>&1); then
      echo "мелкий клон: у коммита не видно родителя — состав не определить, проверка пропущена"
      echo "  чтобы она работала на предложении изменений:"
      echo "  actions/checkout@v4 с fetch-depth: 3 (слияние, его родитель и родитель родителя)"
      exit 0
    fi
    FILES=$(cd "$DIR" && git show --pretty=format: --name-only "$REF" 2>/dev/null | grep -v '^$')
    if [ -n "$FILES" ]; then
      OUTSIDE=$(printf '%s\n' "$FILES" | grep -v "^$LESSONS/" | grep -v "^$LESSONS\$")
      if [ -z "$OUTSIDE" ]; then
        echo "коммит трогает только журнал ($LESSONS) — запись и есть отчёт"
        exit 0
      fi
    fi
  fi
fi
[ -z "$MSG" ] && { echo "нет ни одного коммита — проверять нечего"; exit 0; }

MISSING=""
printf '%s\n' "$MSG" | grep -q "^Сделано:" || MISSING="$MISSING «Сделано:»"
printf '%s\n' "$MSG" | grep -q "^Не уверен:" || MISSING="$MISSING «Не уверен:»"

if [ -n "$MISSING" ]; then
  echo "последний коммит без мини-отчёта — не хватает:$MISSING"
  echo "  почини: допиши в тело коммита короткие разделы Сделано: / Не уверен: —"
  echo "  не пересказ диффа, а что понял и в чём сомневаешься."
  exit 1
fi
exit 0
