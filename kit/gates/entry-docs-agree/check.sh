#!/usr/bin/env sh
# Два свода агента в одном репозитории не расходятся: либо один включает другой, либо они
# согласны между собой.
#
# ЗАЧЕМ ИМЕННО ЭТО. `AGENTS.md` читают Codex, Cursor и Copilot, `CLAUDE.md` — Claude Code. Когда
# оба файла лежат в корне и содержат одно и то же своими словами, правка попадает в один, а
# второй продолжает велеть старое. Два агента в одном репозитории работают по разным правилам, и
# по выводу это неразличимо: каждый из них уверен, что прочитал свод проекта.
#
# ЗАМЕР, ИЗ КОТОРОГО ВЗЯЛАСЬ ЗАПИСЬ (2026-09-23, 300 чужих репозиториев со сводом агента):
#   85 репозиториев держат оба файла; 58 из них уже связывают один с другим — это большинство,
#   а не наша выдумка. Из остальных проверка краснеет на четырёх, и все четыре разобраны руками:
#     0x3639/go-syrius   AGENTS.md велит Go 1.25.13 и `znn-sdk-go` v0.3.1, CLAUDE.md в том же
#                        коммите — Go 1.26 и v0.5.0. Один `go.mod`, два разных ответа
#     andrewck24/volleybro  навыки вызываются `$spectra-*` в одном своде и `/spectra-*` в другом
#     bwz96sco/or_llm_agent блок инструкций Trellis есть только в AGENTS.md: Claude Code про
#                        команды `/trellis:*` не узнает никогда
#     amikos-tech/ami-gin   CLAUDE.md получил разделы про CI, стиль кода и CLI, AGENTS.md — нет,
#                        при этом у AGENTS.md есть свои строки, которых нет у соседа
#
# ПОЧЕМУ «ПОЧТИ ОДИНАКОВЫ», А НЕ «ОТЛИЧАЮТСЯ». Два разных документа — законная раскладка: короткий
# свод одному агенту, подробный другому. Красное здесь — след КОПИИ, которая разъехалась: общая
# половина строк доказывает общее происхождение, а расхождение доказывает, что копию не
# обновляли. Обратное правило проверено на чужом инструменте и на живом человеке:
#   · `duke5am/agents-md-check`, правило AGL019, краснеет когда сходство НИЖЕ 55 %. Прогон
#     2026-09-23 на паре близнецов: на `CLAUDE.md` из одной строки `@AGENTS.md` оно даёт HIGH
#     («token overlap 2 %») и советует «сведи второй файл к указателю» — тем, чем файл уже
#     является; на паре с разными версиями Go молчит (сходство 87 %);
#   · та же ошибка вживую: modelcontextprotocol/inspector#2427, 2026-09-18. Человек сообщил о
#     расхождении сводов по статическому чтению; сопровождающий закрыл в тот же день — их
#     `CLAUDE.md` это строка `@./AGENTS.md`, «нечему расходиться».
# Поэтому пара, где один свод называет другой, зелёная всегда и без разбора содержимого.
#
# ЧТО СЧИТАЕТСЯ РАЗНИЦЕЙ. Строки, а не смысл. Имя самого агента — единственное, чему РАЗРЕШЕНО
# отличаться: «this file provides guidance to Claude Code» против «…to Codex» это один и тот же
# свод. Без этого послабления замер дал бы четыре ложных из шести — проверено на той же выборке.
DIR="${1:-.}"

DOCS=$(find "$DIR" -maxdepth 1 -type f \
  \( -iname 'agents.md' -o -iname 'claude.md' -o -iname 'gemini.md' \) 2>/dev/null | LC_ALL=C sort)
COUNT=$(printf '%s\n' "$DOCS" | grep -c '[^[:space:]]' 2>/dev/null || true)
if [ "${COUNT:-0}" -lt 2 ]; then
  echo "сводов агента в корне меньше двух — сверять нечего"
  exit 0
fi

OLDIFS=$IFS
IFS='
'
# shellcheck disable=SC2086
set -- $DOCS
IFS=$OLDIFS

RC=0
while [ $# -gt 1 ]; do
  A="$1"
  shift
  for B in "$@"; do
    NA=$(basename "$A")
    NB=$(basename "$B")
    # Один свод называет другой — включение `@AGENTS.md`, символьная ссылка или просто строка
    # «правила в AGENTS.md». Источник истины назван, расходиться нечему.
    if grep -qiF "$NB" "$A" 2>/dev/null || grep -qiF "$NA" "$B" 2>/dev/null; then
      continue
    fi
    OUT=$(awk -v fa="$NA" -v fb="$NB" '
      function key(l,   k) {
        k = tolower(l)
        sub(/^[ \t]+/, "", k); sub(/[ \t]+$/, "", k)
        # Имя агента и его каталога схлопываются в один знак. Длинные варианты стоят первыми:
        # POSIX-разбор берёт самое длинное совпадение, но порядок дешевле, чем вера в это.
        gsub(/agents\.md|claude\.md|gemini\.md|claude\.ai\/code|codex\.ai\/code|openai[ ]codex|claude[ ]code|\.claude|\.codex|\.gemini|claude|codex|gemini|cursor|copilot|antigravity/, "@", k)
        return k
      }
      function short(l) { return (length(l) > 120) ? substr(l, 1, 117) "..." : l }
      FNR == 1 { side++; fence = 0 }
      {
        if ($0 ~ /^[ \t]*```/) { fence = 1 - fence; next }   # примеры в блоках кода не сверяем
        if (fence) next
        k = key($0)
        if (k == "") next
        if (side == 1) { if (!(k in A)) { A[k] = 1; ai++; ak[ai] = k; ao[ai] = $0 } }
        else           { if (!(k in B)) { B[k] = 1; bi++; bk[bi] = k; bo[bi] = $0 } }
      }
      END {
        min = (ai < bi) ? ai : bi
        if (min == 0) exit 0
        for (i = 1; i <= ai; i++) if (ak[i] in B) shared++
        pct = int(shared * 100 / min)
        if (pct < 50) exit 0            # разные документы, а не разъехавшаяся копия
        for (i = 1; i <= ai; i++) if (!(ak[i] in B)) { da++; if (da <= 2) sa[da] = ao[i] }
        for (i = 1; i <= bi; i++) if (!(bk[i] in A)) { db++; if (db <= 2) sb[db] = bo[i] }
        if (da + db == 0) exit 0        # дословная копия: разойтись ещё не успела
        printf "%s и %s: общих строк %d%%, разошлось строк %d\n", fa, fb, pct, da + db
        for (i = 1; i <= da; i++) printf "  только в %s: %s\n", fa, short(sa[i])
        for (i = 1; i <= db; i++) printf "  только в %s: %s\n", fb, short(sb[i])
        exit 1
      }
    ' "$A" "$B")
    if [ -n "$OUT" ]; then
      echo "своды агента разошлись:"
      echo "$OUT"
      RC=1
    fi
  done
done

if [ "$RC" -ne 0 ]; then
  echo "  почини: оставь один свод источником правды, а второй сведи к строке-включению «@AGENTS.md» — так уже сделаны 58 из 85 чужих репозиториев с двумя сводами"
  exit 1
fi
echo "своды агента согласны между собой"
exit 0
