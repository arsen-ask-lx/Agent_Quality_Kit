#!/usr/bin/env sh
# Тест, который не может провалиться: прогон зелёный, покрытие выросло, проверено ничего.
#
# ЗАЧЕМ ИМЕННО ЭТО. «Почини тесты» агент решает буквально: тело теста пустеет, утверждение
# заменяется тавтологией, тест помечается пропуском. Все три способа дают ровно то, что просили
# — зелёный прогон, — и ни один не виден в сводке. Это тот же класс, что молчащий гейт: сигнал
# исчез, а уверенность осталась.
#
# ГРАНИЦА НАЙДЕНА ЗАМЕРОМ, А НЕ ВЫДУМАНА. Первая версия красила «тест без утверждения» и дала
# 186 находок в двух зрелых проектах — все до одной оказались тестами вида «вызвали и проверили,
# что не упало». Это законный и распространённый стиль: утверждение там в самом отсутствии
# исключения. Гейт, спорящий о стиле, выключают целиком, поэтому здесь остались только
# безусловные случаи — те, где тест не может провалиться ни при каких данных.
DIR="${1:-.}"
. "$(dirname "$0")/../_skip.sh" 2>/dev/null || SKIP_NAMES=".git .aqk node_modules .venv"

# Только файлы тестов. Слово «assert» в обычном коде — не тест, а проверка входа.
FILES=$(find "$DIR" $(skip_find) -type f \( \
    -name 'test_*.py' -o -name '*_test.py' -o -name 'tests.py' \
    -o -name '*.test.js' -o -name '*.test.jsx' -o -name '*.test.ts' -o -name '*.test.tsx' \
    -o -name '*.test.mjs' -o -name '*.spec.js' -o -name '*.spec.jsx' -o -name '*.spec.ts' \
    -o -name '*.spec.tsx' -o -name '*.spec.mjs' \
    -o -name '*_test.go' -o -name '*_test.rb' -o -name '*_spec.rb' \) -print 2>/dev/null)
[ -z "$FILES" ] && { echo "файлов тестов не нашлось — эта проверка не про тебя"; exit 0; }

# Сгенерированный файл правят не руками: тест в нём написал инструмент. Признак проверяется
# внутри awk по первым строкам, а не циклом с `head` на файл.
#
# ПОЧЕМУ БЕЗ ЦИКЛА. Накопление списка строкой («KEEP="$KEEP $F"») — квадрат по длине: оболочка
# копирует растущую строку на каждой итерации. На соседней проверке это дало 44 секунды вместо
# одной на том же репозитории.

# Тройная одинарная кавычка нужна разбору докстрок, но написать её внутри awk-программы нельзя:
# она закроет кавычки самой программы. Передаём переменной.
Q3="'''"

# ОДИН вызов awk на все файлы, а не по вызову на файл: запуск процесса стоит дороже разбора.
# На репозитории в 7128 файлов проверка занимала 49 секунд, и почти всё это были запуски.
# shellcheck disable=SC2086
OUT=$(awk -v q3="$Q3" '
  # --- что считается безусловно сломанным ------------------------------------
  function tautology(l) {
    return l ~ /assert[[:space:]]+(True|true|1)[[:space:]]*($|#)/ ||
           l ~ /assert(True|Equal)\((True|true|1)([[:space:]]*,[[:space:]]*(True|true|1))?\)/ ||
           l ~ /expect\((true|1)\)\.(toBe|toEqual)\((true|1)\)/ ||
           l ~ /assert[[:space:]]+[0-9]+[[:space:]]*==[[:space:]]*[0-9]+/
  }
  # Пропуск без причины. С причиной — законный приём: тест ждёт починки, и это записано.
  # Голый `t.Skip()` из Go сюда НЕ входит: на замере 9 находок из 13 оказались условным
  # пропуском по переменной окружения — это управление прогоном, а не выключенный тест.
  function bareSkip(l) {
    return (l ~ /@(pytest\.mark\.)?skip([[:space:]]*$|\()/ && !reasonNear(l)) ||
           (l ~ /(^|[^a-zA-Z])(x?it|x?describe|test)\.skip\(/ && l !~ /--|TODO|[Ii]ssue|#[0-9]/) ||
           (l ~ /(^|[^a-zA-Z])(xit|xdescribe)\(/) ||
           (l ~ /@Ignore([[:space:]]*$|\(\))/)
  }
  # Строка, которая ничего не делает: заглушка, докстрока, комментарий, хвост из скобок.
  # Сравнением строк, а не регулярным выражением: тройная одинарная кавычка внутри
  # awk-программы закрыла бы кавычки оболочки.
  function isNoop(b,   t) {
    t = b; sub(/^[[:space:]]+/, "", t); sub(/[[:space:]]+$/, "", t)
    if (t == "" || t == "pass" || t == "..." || t == "return") return 1
    if (substr(t, 1, 1) == "#") return 1
    if (substr(t, 1, 3) == "\"\"\"" || substr(t, 1, 3) == q3) return 1
    if (substr(t, 1, 2) == "//" || substr(t, 1, 2) == "/*" || substr(t, 1, 1) == "*") return 1
    if (t ~ /^[])};,[:space:]]+$/) return 1
    return 0
  }
  function trim(x) { sub(/^[[:space:]]+/, "", x); return substr(x, 1, 80) }
  # Причина, записанная комментарием НАД пропуском, — нормальная форма, и она встречается чаще
  # инлайновой: на замере все 4 оставшиеся находки оказались именно такими, с подробным
  # объяснением в трёх строках выше. Требование писать причину в той же строке — придирка к
  # форме, а придирки к форме и есть то, из-за чего гейты выключают.
  # Причина у пропуска может стоять на следующей строке: многострочный декоратор
  # «@pytest.mark.skip(\n  reason="…"\n)» — обычная форма, когда причина длинная.
  function reasonNear(l,   k) {
    if (l ~ /reason[[:space:]]*=/) return 1
    if (l !~ /\($/ && l !~ /\([[:space:]]*$/) return 0
    for (k = cursor + 1; k <= n && k <= cursor + 4; k++) {
      if (line[k] ~ /reason[[:space:]]*=/) return 1
      if (line[k] ~ /^[[:space:]]*\)/) return 0
    }
    return 0
  }
  function explainedAbove(i,   k, t, w) {
    for (k = i - 1; k >= 1 && k >= i - 4; k--) {
      t = line[k]; sub(/^[[:space:]]+/, "", t)
      if (t == "") continue
      if (substr(t, 1, 2) != "//" && substr(t, 1, 1) != "#" && substr(t, 1, 1) != "*") return 0
      w = split(t, _unused, /[[:space:]]+/)
      if (w >= 4) return 1
    }
    return 0
  }
  # Баланс круглых скобок со строки a по строку b, через префиксные суммы. Пересчёт от a при
  # каждом обращении давал кубическую сложность и не укладывался в две минуты на большом
  # репозитории. Приближение: скобки внутри строковых литералов считаются наравне с
  # настоящими — точный ответ требует разбора языка, а его у переносимой проверки нет.
  function bal(a, b) { return pre[b] - pre[a - 1] }
  function balBrace(a, b) { return prb[b] - prb[a - 1] }

  # Границы файла: awk без gawk не знает ENDFILE, поэтому предыдущий файл разбирается на первой
  # строке следующего, а последний — в END. Буферы обнуляются вместе с именем: общий буфер
  # склеил бы скобки соседних файлов и сдвинул все границы.
  FNR == 1 { if (n > 0) report(); n = 0; delete line; delete pre; delete prb; delete tck; cur = FILENAME; skipFile = 0 }
  FNR <= 5 && /@[Gg]enerated|[Dd]o not edit|DO NOT EDIT|[Aa]utogenerated|[Aa]uto-generated|[Gg]enerated by|сгенерирован/ { skipFile = 1 }
  {
    n++; line[n] = $0
    t = $0; o = gsub(/\(/, "(", t); t = $0; c = gsub(/\)/, ")", t)
    pre[n] = pre[n - 1] + o - c
    t = $0; o = gsub(/\{/, "{", t); t = $0; c = gsub(/\}/, "}", t)
    prb[n] = prb[n - 1] + o - c
    # Чётность обратных кавычек. Строка внутри незакрытого шаблонного литерала — это ДАННЫЕ,
    # а не код: проекты, которые проверяют чужой код, держат в таких литералах целые файлы с
    # тестами внутри. Три находки из четырёх на замере пришли ровно оттуда.
    t = $0; tck[n] = tck[n - 1] + gsub(/`/, "`", t)
  }
  END { if (n > 0) report() }

  function report(   i, j, l, t0, e, ind, start, found, hasBody, b, bi) {
    if (skipFile) return
    for (i = 1; i <= n; i++) {
      l = line[i]; cursor = i
      if (l ~ /^[[:space:]]*(#|\/\/|\*)/) continue
      if (tautology(l) && !explainedAbove(i)) {
        printf "%s:%d: утверждение-тавтология: %s\n", cur, i, trim(l); continue
      }
      if (bareSkip(l) && !explainedAbove(i)) {
        printf "%s:%d: тест пропущен без названной причины: %s\n", cur, i, trim(l); continue
      }

      # --- python: тело ограничено отступом -----------------------------------
      if (l ~ /^[[:space:]]*(async[[:space:]]+)?def[[:space:]]+test[_A-Za-z0-9]*[[:space:]]*\(/) {
        # Тело в той же строке — это не тест, а вложенная функция-фикстура: «def test_function():
        # ...» внутри настоящего теста. Настоящий тест так не пишут. Найдено замером на
        # sentry-python, где такая фикстура объявлялась пустым тестом.
        if (bal(i, i) <= 0 && l !~ /:[[:space:]]*(#.*)?$/) continue
        match(l, /^[[:space:]]*/); ind = RLENGTH; found = 0
        # Подпись бывает на несколько строк, и её закрывающая «):» стоит на отступе самого def.
        # Пока тело искали прямо со следующей строки, эта скобка обрывала поиск: тест объявляли
        # пустым, ни разу не заглянув внутрь. 142 ложных в одном pre-commit.
        start = i
        for (j = i; j <= n; j++) { start = j; if (bal(i, j) <= 0 && line[j] ~ /:[[:space:]]*(#.*)?$/) break }

        for (j = start + 1; j <= n; j++) {
          b = line[j]
          if (b ~ /^[[:space:]]*$/) continue
          match(b, /^[[:space:]]*/); bi = RLENGTH
          if (bi <= ind) break
          if (!isNoop(b)) { found = 1; break }
        }
        if (!found) printf "%s:%d: тело теста пустое — он не может провалиться: %s\n", cur, i, trim(l)
        continue
      }

      # --- javascript и typescript: тело ограничено круглой скобкой вызова ----
      # ВЫЗОВ В НАЧАЛЕ СТРОКИ, а не слово «test» где угодно. Пока проверялось вхождение,
      # красным становилось всё подряд: объявление обычной функции с таким именем, тот же текст
      # внутри строковой фикстуры с дифом, он же аргументом в toContain. 51 ложная из 60.
      if (tck[i - 1] % 2 == 1) continue
      t0 = l; sub(/^[[:space:]]+/, "", t0)
      if (t0 ~ /^(await[[:space:]]+)?(it|test)(\.[A-Za-z]+)?[[:space:]]*\(/) {
        # Границей служит КРУГЛАЯ скобка вызова, а не фигурная скобка тела: многострочный вызов
        # с объектом настроек между именем и телом обрывался на этом объекте — скобка
        # открылась и закрылась, тело сочли пустым. 1460 ложных из 1843.
        # Конец вызова — когда закрылись И круглые, И фигурные скобки. По одним круглым
        # строка `for (const p of ["a)b"]) {` закрывала вызов раньше времени: скобка внутри
        # строкового литерала считается наравне с настоящей. Фигурная скобка тела там ещё
        # открыта, и это отличает настоящий конец от мнимого.
        e = i
        for (j = i; j <= n; j++) { e = j; if (bal(i, j) <= 0 && balBrace(i, j) <= 0) break }
        hasBody = 0
        for (j = i; j <= e; j++) if (line[j] ~ /=>|function/) hasBody = 1
        if (!hasBody) continue
        found = 0
        # Однострочная запись: тело живёт на той же строке («it("…", () => expectPass(…));»).
        # Пока сканировали только следующие строки, такой тест объявлялся пустым.
        if (e == i && t0 ~ /=>[^)]*[A-Za-z]/) continue
        # Включая строку e: у стрелочной функции без фигурных скобок тело живёт ровно на ней
        # («it("…", () =>\n  expectPass(…));»). Пока сканировали до e-1, такие тесты объявлялись
        # пустыми — 15 ложных из 21 на замере.
        for (j = i + 1; j <= e; j++) if (!isNoop(line[j])) { found = 1; break }
        if (!found) printf "%s:%d: тело теста пустое — он не может провалиться: %s\n", cur, i, trim(l)
      }
    }
  }
' $FILES 2>/dev/null)

LEFT="$(printf '%s' "$OUT" | grep -v '^$' | own_samples_filter "$DIR")"
[ -z "$LEFT" ] && exit 0
printf '%s\n' "$LEFT"
echo "  почини: тест обязан уметь провалиться. Пропуск — с названной причиной («reason=…», ссылка на задачу)."
echo "  зелёный прогон без проверки — это уверенность без основания, худший из возможных исходов."
exit 1
