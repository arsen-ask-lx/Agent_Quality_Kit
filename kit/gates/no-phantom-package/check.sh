#!/usr/bin/env sh
# Имена пакетов, названные в документации, сверяются с реестром npm.
#
# ЗАЧЕМ. Агент, не знающий инструмента, придумывает правдоподобное имя. Дальше его читает
# другой агент и выполняет `npm install` — и если имя к тому времени кем-то занято, в проект
# приезжает чужой код. Обычные проверки цепочки поставок смотрят на пакеты, которые ЕСТЬ;
# здесь опасен как раз тот, которого пока нет.
#
# Работу делает slopcheck (MIT, ноль зависимостей). Мы отвечаем за три вещи, которых он не
# делает: какие файлы ему дать, что считать браком и что делать, когда ответа не было.
# Каждая ветка «ответа не было» кончается кодом 2 и словами «проверка не состоялась»: у
# инструмента, написанного против молчаливого зелёного, своего молчаливого зелёного быть не может.
DIR="${1:-.}"

# Существование файла проверяется ДО `.`, а не запасной веткой после. В POSIX-оболочке (здесь
# dash) неудачный `.` завершает скрипт немедленно — привычное «. файл || запасной_вариант» не
# выполняется НИКОГДА, и гейт умирает с кодом 2 без единого слова о причине. Проверено прогоном
# 2026-09-08; та же мёртвая ветка стоит ещё в девяти проверках каталога.
SKIP_LIB="$(dirname "$0")/../_skip.sh"
if [ ! -f "$SKIP_LIB" ]; then
  echo "рядом с проверкой нет _skip.sh — обход не собран, проверка не состоялась"
  echo "  почини: скопируй гейт вместе с файлом kit/gates/_skip.sh, он общий на весь каталог"
  exit 2
fi
. "$SKIP_LIB"

# Даже когда файл на месте, нужных функций в нём может не оказаться: без них конвейер ниже не
# напечатает ни одного пути, список окажется пуст, а пустой список — это `exit 0`. Гейт вышел бы
# зелёным, не посмотрев ни в один файл.
if ! command -v own_samples_filter >/dev/null 2>&1; then
  echo "в _skip.sh нет обхода own_samples_filter — проверка не состоялась"
  echo "  почини: обнови kit/gates/_skip.sh до версии, идущей с этим гейтом"
  exit 2
fi

if ! command -v slopcheck >/dev/null 2>&1; then
  echo "не найден slopcheck — эта проверка делегирована ему"
  echo "  почини: npm i -g slopcheck@0.2.0"
  exit 2
fi

# Свой обход, а не встроенный в slopcheck: только так работает own_samples_filter. Без него
# красный образец этой же записи выдаётся за находку, и гейт краснеет на самом комплекте.
LIST=$(mktemp) || exit 2
# shellcheck disable=SC2046
find "$DIR" $(skip_find "$DIR") -type f \
     \( -name '*.md' -o -name '*.mdc' -o -name '*.yml' -o -name '*.yaml' \
        -o -name '*.json' -o -name '.cursorrules' \) -print 2>/dev/null \
  | own_samples_filter "$DIR" > "$LIST"

if [ ! -s "$LIST" ]; then rm -f "$LIST"; exit 0; fi

# Через NUL, а не через $(...): путь с пробелом иначе распадается на два аргумента, slopcheck
# не находит ни одного из них и молча выходит с нулём. Та же ловушка уже стоила нам зелёного
# вердикта в hook-actually-fires.
ERRF=$(mktemp) || { rm -f "$LIST"; exit 2; }
OUT=$(tr '\n' '\0' < "$LIST" | xargs -0 slopcheck --json 2>"$ERRF")
# Код xargs: 0 — все вызовы прошли, 123 — хотя бы один вернул 1..125. Именно 123 приходит и на
# честной находке (slopcheck выходит с 1), поэтому сам по себе он ничего не значит. А вот всё
# остальное — сбой обвязки, и его нельзя принимать за вердикт.
XS=$?
ERR=$(cat "$ERRF" 2>/dev/null)
rm -f "$ERRF" "$LIST"

# Файлов может оказаться больше, чем влезает в одну команду, и тогда xargs зовёт slopcheck
# несколько раз. Упавший вызов пишет в stderr, а уцелевшие всё равно печатают свой JSON —
# счётчики сходятся, и гейт вышел бы с нулём, не проверив целую партию файлов.
if [ -n "$ERR" ] || { [ "$XS" -ne 0 ] && [ "$XS" -ne 123 ]; }; then
  echo "slopcheck не отработал (код $XS) — проверка не состоялась, это не вердикт «чисто»"
  [ -n "$ERR" ] && printf '%s\n' "$ERR" | head -5 | sed 's/^/  /'
  echo "  почини: прогони «slopcheck --json .» руками и посмотри, на чём он споткнулся"
  exit 2
fi

[ -n "$OUT" ] || {
  echo "slopcheck ничего не ответил — проверка не состоялась, это не вердикт «чисто»"
  echo "  почини: прогони «slopcheck --json .» руками и посмотри, на чём он споткнулся"
  exit 2
}

printf '%s\n' "$OUT" | awk '
  function val(s) { sub(/^[^:]*:[[:space:]]*/, "", s); sub(/,$/, "", s); gsub(/^"|"$/, "", s); return s }
  function label(s) {
    if (s == "not_found")     return "в реестре такого пакета нет"
    if (s == "unpublished")   return "пакет был и снят с публикации — имя свободно для захвата"
    if (s == "security_hold") return "реестр пометил пакет как вредоносный"
    return ""
  }
  # xargs может позвать slopcheck несколько раз, если путей слишком много для одной команды.
  # Тогда JSON-документов на входе будет несколько, и счётчики надо складывать, а не брать
  # последний: иначе находки первой партии исчезнут.
  /^  "packages"/            { inpkg = 1; sawpkg = 1; next }
  inpkg && /^  \}/           { inpkg = 0; next }
  inpkg && /"errors"/        { errs += val($0); next }
  inpkg && /"notFound"/      { bad  += val($0); next }
  inpkg && /"unpublished"/   { bad  += val($0); next }
  inpkg && /"securityHold"/  { bad  += val($0); next }
  /^      "package"/         { pkg = val($0); next }
  /^      "status"/          { st  = val($0); next }
  /^          "file"/        { f  = val($0); next }
  /^          "line"/        { ln = val($0); next }
  # Печатаем на «command»: он идёт последним в записи о месте, значит к этому моменту известны
  # и пакет, и состояние, и файл со строкой.
  /^          "command"/ {
    cmd = val($0)
    if (st == "error") next
    # Состояние, которого мы не знаем. Раньше здесь стояло «всё, что не error, — брак», и
    # новое состояние в следующей версии slopcheck превратило бы КАЖДУЮ команду установки в
    # находку с английским словом вместо объяснения. Незнакомое состояние — повод сказать
    # «не разобрали», а не вынести вердикт.
    if (label(st) == "") { unknown = st; next }
    if (shown < 20) print f ":" ln ": «" pkg "» — " label(st) " · " cmd
    shown++
    next
  }
  END {
    if (unknown != "") {
      print "slopcheck вернул незнакомое состояние «" unknown "» — разобрать ответ не вышло"
      print "  почини: сверь версию slopcheck с той, что названа в gate.yml"
      exit 2
    }
    if (shown > 20) print "  … и ещё " (shown - 20)
    if (shown > 0) {
      # Находки и «не проверено» показываются вместе. Свернуть второе в первое значило бы
      # потерять ровно ту разницу, ради которой написана эта обёртка.
      if (errs > 0) print "  кроме того, реестр не ответил по именам: " errs " — они НЕ проверены"
      print "  почини: проверь имя в реестре и впиши настоящее. Если пакета нет, его может"
      print "  зарегистрировать кто угодно — и следующий агент выполнит установку чужого кода."
      exit 1
    }
    # Реестр не ответил. Молчать здесь нельзя: тишина неотличима от «всё хорошо», а именно
    # это наш стандарт и запрещает. Красим отдельным кодом, чтобы вердикт не путали с браком.
    # Причина названа обеими: slopcheck помечает так и недоступную сеть, и ответ 429 «слишком
    # часто», и любой другой не-200 — снаружи они неразличимы, и врать про сеть мы не будем.
    if (errs > 0) {
      print "реестр npm не ответил: не проверено имён — " errs
      print "  проверка не состоялась. Это не вердикт «чисто»."
      print "  почини: если сети нет — прогони гейт там, где она есть. Если сеть есть, реестр"
      print "  мог ограничить частоту запросов: повтори через минуту."
      exit 2
    }
    # Блока со счётчиками не нашлось вовсе. Так будет, если slopcheck начнёт печатать JSON
    # одной строкой: ни одно правило выше не сработает, все счётчики останутся нулями — и
    # проверка выйдет с нулём, ничего не проверив. Нашли это прогоном подставного вывода уже
    # после того, как записали «формат стабилен»: догадка о стабильности стоила бы молчаливого
    # зелёного на каждом прогоне.
    if (!sawpkg) {
      print "ответ slopcheck не разобран: блока «packages» в нём нет"
      print "  почини: сверь версию slopcheck с той, что названа в gate.yml"
      exit 2
    }
    # Счётчик говорит о браке, а печатать нечего — значит мы разучились читать вывод slopcheck
    # (сменился формат). Тоже не вердикт «чисто».
    if (bad > 0) {
      print "slopcheck насчитал находок: " bad ", но разобрать их не вышло — сменился формат"
      print "  почини: сверь версию slopcheck с той, что названа в gate.yml"
      exit 2
    }
    exit 0
  }
'
