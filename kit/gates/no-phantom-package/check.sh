#!/usr/bin/env sh
# Имена пакетов, названные в документации, сверяются с реестром npm.
#
# ЗАЧЕМ. Агент, не знающий инструмента, придумывает правдоподобное имя. Дальше его читает
# другой агент и выполняет `npm install` — и если имя к тому времени кем-то занято, в проект
# приезжает чужой код. Обычные проверки цепочки поставок смотрят на пакеты, которые ЕСТЬ;
# здесь опасен как раз тот, которого пока нет.
#
# Работу делает slopcheck (MIT, ноль зависимостей). Мы отвечаем за три вещи, которых он не
# делает: какие файлы ему дать, что считать браком и что делать, когда реестр недоступен.
DIR="${1:-.}"
. "$(dirname "$0")/../_skip.sh" 2>/dev/null || SKIP_NAMES=".git .aqk node_modules .venv"

if ! command -v slopcheck >/dev/null 2>&1; then
  echo "не найден slopcheck — эта проверка делегирована ему"
  echo "  почини: npm i -g slopcheck@0.2.0"
  exit 2
fi

# Свой обход, а не встроенный в slopcheck: только так работает own_samples_filter. Без него
# красный образец этой же записи выдаётся за находку, и гейт краснеет на самом комплекте.
LIST=$(mktemp) || exit 2
# shellcheck disable=SC2046
find "$DIR" $(skip_find "$DIR") -type f \
     \( -name '*.md' -o -name '*.mdc' -o -name '*.yml' -o -name '*.yaml' \
        -o -name '*.json' -o -name '.cursorrules' \) -print 2>/dev/null \
  | own_samples_filter "$DIR" > "$LIST"

if [ ! -s "$LIST" ]; then rm -f "$LIST"; exit 0; fi

# Через NUL, а не через $(...): путь с пробелом иначе распадается на два аргумента, slopcheck
# не находит ни одного из них и молча выходит с нулём. Та же ловушка уже стоила нам зелёного
# вердикта в hook-actually-fires.
OUT=$(tr '\n' '\0' < "$LIST" | xargs -0 slopcheck --json 2>/dev/null)
rm -f "$LIST"

[ -n "$OUT" ] || { echo "slopcheck ничего не ответил — проверка не состоялась"; exit 2; }

printf '%s\n' "$OUT" | awk '
  function val(s) { sub(/^[^:]*:[[:space:]]*/, "", s); sub(/,$/, "", s); gsub(/^"|"$/, "", s); return s }
  function label(s) {
    if (s == "not_found")     return "в реестре такого пакета нет"
    if (s == "unpublished")   return "пакет был и снят с публикации — имя свободно для захвата"
    if (s == "security_hold") return "реестр пометил пакет как вредоносный"
    return s
  }
  # xargs может позвать slopcheck несколько раз, если путей слишком много для одной команды.
  # Тогда JSON-документов на входе будет несколько, и счётчики надо складывать, а не брать
  # последний: иначе находки первой партии исчезнут.
  /^  "packages"/            { inpkg = 1; sawpkg = 1; next }
  inpkg && /^  \}/           { inpkg = 0; next }
  inpkg && /"errors"/        { errs += val($0); next }
  inpkg && /"notFound"/      { bad  += val($0); next }
  inpkg && /"unpublished"/   { bad  += val($0); next }
  inpkg && /"securityHold"/  { bad  += val($0); next }
  /^      "package"/         { pkg = val($0); next }
  /^      "status"/          { st  = val($0); next }
  /^          "file"/        { f  = val($0); next }
  /^          "line"/        { ln = val($0); next }
  # Печатаем на «command»: он идёт последним в записи о месте, значит к этому моменту известны
  # и пакет, и состояние, и файл со строкой.
  /^          "command"/ {
    cmd = val($0)
    if (st != "error" && shown < 20) { print f ":" ln ": «" pkg "» — " label(st) " · " cmd }
    if (st != "error") shown++
    next
  }
  END {
    if (shown > 20) print "  … и ещё " (shown - 20)
    if (shown > 0) {
      print "  почини: проверь имя в реестре и впиши настоящее. Если пакета нет, его может"
      print "  зарегистрировать кто угодно — и следующий агент выполнит установку чужого кода."
      exit 1
    }
    # Реестр не ответил. Молчать здесь нельзя: тишина неотличима от «всё хорошо», а именно
    # это наш стандарт и запрещает. Красим отдельным кодом, чтобы вердикт не путали с браком.
    if (errs > 0) {
      print "реестр npm недоступен: не проверено имён — " errs
      print "  проверка не состоялась. Это не вердикт «чисто»."
      exit 2
    }
    # Блока со счётчиками не нашлось вовсе. Так будет, если slopcheck начнёт печатать JSON
    # одной строкой: ни одно правило выше не сработает, все счётчики останутся нулями — и
    # проверка выйдет с нулём, ничего не проверив. Нашли это прогоном подставного вывода уже
    # после того, как записали «формат стабилен»: догадка о стабильности стоила бы молчаливого
    # зелёного на каждом прогоне.
    if (!sawpkg) {
      print "ответ slopcheck не разобран: блока «packages» в нём нет"
      print "  почини: сверь версию slopcheck с той, что названа в gate.yml"
      exit 2
    }
    # Счётчик говорит о браке, а печатать нечего — значит мы разучились читать вывод slopcheck
    # (сменился формат). Тоже не вердикт «чисто».
    if (bad > 0) {
      print "slopcheck насчитал находок: " bad ", но разобрать их не вышло — сменился формат"
      print "  почини: сверь версию slopcheck с той, что названа в gate.yml"
      exit 2
    }
    exit 0
  }
'
