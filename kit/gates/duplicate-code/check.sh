#!/usr/bin/env sh
# Ищет одинаковые блоки по восемь строк. Мера грубая — совпадение байт в байт после снятия
# отступов, — но именно так размножается код, который агент копирует из соседнего файла.
#
# ЗАЧЕМ. Дубль опаснее длины: правку вносят в одну копию из четырёх, три остаются со старым
# поведением, и расхождение всплывает через недели в другом месте.
DIR="${1:-.}"
# Существование файла проверяется ДО `.`, а не запасной веткой после. Прежняя строка
# `. файл 2>/dev/null || запасной_вариант` выглядела страховкой и ею не была: под `sh` (dash)
# неудачный `.` завершает скрипт немедленно, и ветка после `||` не выполняется никогда; под
# `bash`, которым гейты и запускаются из манифеста, она выполняется, но подставляет только
# ПЕРЕМЕННУЮ — функции обхода остаются неопределёнными, конвейер печатает пустоту, и проверка
# выходит с НУЛЁМ. Замерено 2026-09-08 на файле с настоящим нарушением: гейт сказал «чисто».
SKIP_LIB="$(dirname "$0")/../_skip.sh"
if [ ! -f "$SKIP_LIB" ]; then
  echo "рядом с проверкой нет _skip.sh — обход не собран, проверка не состоялась"
  echo "  почини: скопируй гейт вместе с файлом kit/gates/_skip.sh, он общий на весь каталог"
  exit 2
fi
. "$SKIP_LIB"
# Файл на месте — этого мало: подмена содержимого давала код 0. Метка стоит в КОНЦЕ _skip.sh,
# поэтому проверка ловит и обрыв файла на середине.
if [ "${AQK_SKIP_READY:-}" != 1 ]; then
  echo "_skip.sh есть, но обход не собрался — проверка НЕ СОСТОЯЛАСЬ, а не прошла"
  echo "  почини: замени kit/gates/_skip.sh целым файлом из каталога"
  exit 2
fi
WIN="${AQK_DUP_LINES:-8}"

# Тесты исключены намеренно. Повтор в тестах часто осознанный: читаемость там важнее сухости,
# и три похожих теста лучше одного хитрого. Случай «три однотипных — свести в один с набором
# входов» решается глазами по правилам тестирования, а не этим гейтом. На живом проекте все
# двадцать находок были в тестах — гейт, который краснеет только на них, выключат.
TESTS="-name test -prune -o -name tests -prune -o -name spec -prune -o -name __tests__ -prune -o"

# shellcheck disable=SC2046
find "$DIR" $(skip_find "$DIR") $TESTS -type f \
     ! -name 'test_*' ! -name '*_test.*' ! -name '*.test.*' ! -name '*.spec.*' \
     -print 2>/dev/null | only_code | own_samples_filter "$DIR" \
  | drop_generated \
  | LC_ALL=C sort \
  | xargs -r env LC_ALL=C awk -v WIN="$WIN" '
      # Строка-объявление ввоза: `import`, `from … import`, `use …;`, путь в кавычках внутри
      # блока `import (…)` в Go, `require(…)`, а также одинокие скобки и точки с запятой.
      # ЗАЧЕМ. Восемь одинаковых строк ввоза подряд — форма языка, а не размноженный код: в Go,
      # Java и Rust список ввоза стоит по одной строке и в соседних файлах одного пакета
      # совпадает целиком. Замер по cobra: обе находки в doc/ были ровно этим — ни одной
      # строки логики. Окно, где нет ни одной строки кроме ввоза, дублем не считается.
      function isimport(s) {
        return s ~ /^(import|from|use|export|require|package|#include|using)([[:space:](]|$)/ ||
               s ~ /^[A-Za-z_][A-Za-z0-9_]*[[:space:]]+"[^"]*"$/ ||
               s ~ /^[_.]?[[:space:]]*"[^"]*"[,;]?$/ ||
               s ~ /^(const|let|var)[[:space:]].*require\(/ ||
               s ~ /^[(){}\[\];,]+$/
      }
      FNR == 1 { n = 0; delete buf; delete imp }
      {
        line = $0
        gsub(/^[[:space:]]+|[[:space:]]+$/, "", line)
        if (line == "" || line ~ /^([#]|\/\/)/) next     # пустые и комментарии не считаем
        buf[++n] = line
        imp[n] = isimport(line)
        if (n >= WIN) {
          # Ключ и признак «есть ли код» собираются ОДНИМ проходом по окну. Разнести их на
          # два цикла выглядело ускорением — окно из одного ввоза отбрасывалось бы до сборки
          # ключа. Замерено 2026-09-08 на uv: стало 2791 мс против 1770. Второй обход окна
          # дороже, чем сборка ключа, которую он экономит; правка откачена по замеру.
          key = ""; code = 0
          for (i = n - WIN + 1; i <= n; i++) { key = key buf[i] "\x1e"; if (!imp[i]) code = 1 }
          if (!code) next                               # окно целиком из ввоза — не дубль
          if (key in seen && seen[key] != FILENAME ":" (FNR - WIN + 1)) {
            print seen[key] " и " FILENAME ":" (FNR - WIN + 1) ": одинаковые " WIN " строк"
          } else if (!(key in seen)) {
            seen[key] = FILENAME ":" (FNR - WIN + 1)
          }
        }
      }
    ' 2>/dev/null | sort -u \
  | LC_ALL=C awk -F' и |: ' '
      # Один повторённый кусок даёт столько сообщений, на сколько окон он делится: восемь
      # строк — восемь почти одинаковых строк отчёта. Схлопываем в одну на пару файлов.
      #
      # Пара упорядочивается лексикографически, а НЕ в порядке обхода. Порядок, в котором
      # find отдаёт файлы, свой на каждой системе (здесь — по хешу имени), и реестр, снятый
      # на одной машине, краснел в конвейере целиком: те же дубли читались как новые, а
      # храповик объявлял их исправленными и вычёркивал. Одной сортировки списка файлов мало:
      # когда кусок лежит в трёх файлах, «первым» становится тот, кого раньше отдал обход.
      { split($1, a, ":"); split($2, b, ":")
        if (a[1] <= b[1]) { pair = a[1] " и " b[1]; loc = $1 " и " $2 }
        else              { pair = b[1] " и " a[1]; loc = $2 " и " $1 }
        if (!(pair in seen)) { seen[pair] = loc }
        cnt[pair]++ }
      END { for (p in seen) print seen[p] ": одинаковый кусок" (cnt[p] > 1 ? " (окон: " cnt[p] ")" : "") }
    ' | sort > /tmp/.dup.$$

if [ -s /tmp/.dup.$$ ]; then
  head -20 /tmp/.dup.$$
  N=$(wc -l < /tmp/.dup.$$); [ "$N" -gt 20 ] && echo "  … и ещё $((N - 20))"
  rm -f /tmp/.dup.$$
  echo "  почини: вынеси общее в одно место. Правку вносят в одну копию из четырёх —"
  echo "  остальные остаются со старым поведением, и это всплывает не сразу и не здесь."
  exit 1
fi
rm -f /tmp/.dup.$$
exit 0
