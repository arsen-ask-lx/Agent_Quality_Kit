#!/usr/bin/env sh
# Грубая мера сложности: глубина вложенности. Это НЕ замена цикломатической сложности —
# готовые правила считают ветвления и инструкции и делают это точнее. Здесь запасной вариант
# для стеков, где готового инструмента нет.
#
# ЗАЧЕМ ВООБЩЕ. 29 ветвлений в одной функции — это код, который никто не держит в голове
# целиком: ни человек, ни агент. Агент в таком месте начинает переписывать вместо правки.
DIR="${1:-.}"
# Существование файла проверяется ДО `.`, а не запасной веткой после. Прежняя строка
# `. файл 2>/dev/null || запасной_вариант` выглядела страховкой и ею не была: под `sh` (dash)
# неудачный `.` завершает скрипт немедленно, и ветка после `||` не выполняется никогда; под
# `bash`, которым гейты и запускаются из манифеста, она выполняется, но подставляет только
# ПЕРЕМЕННУЮ — функции обхода остаются неопределёнными, конвейер печатает пустоту, и проверка
# выходит с НУЛЁМ. Замерено 2026-09-08 на файле с настоящим нарушением: гейт сказал «чисто».
SKIP_LIB="$(dirname "$0")/../_skip.sh"
if [ ! -f "$SKIP_LIB" ]; then
  echo "рядом с проверкой нет _skip.sh — обход не собран, проверка не состоялась"
  echo "  почини: скопируй гейт вместе с файлом kit/gates/_skip.sh, он общий на весь каталог"
  exit 2
fi
. "$SKIP_LIB"
# Файл на месте — этого мало: подмена содержимого давала код 0. Метка стоит в КОНЦЕ _skip.sh,
# поэтому проверка ловит и обрыв файла на середине.
if [ "${AQK_SKIP_READY:-}" != 1 ]; then
  echo "_skip.sh есть, но обход не собрался — проверка НЕ СОСТОЯЛАСЬ, а не прошла"
  echo "  почини: замени kit/gates/_skip.sh целым файлом из каталога"
  exit 2
fi
MAX="${AQK_MAX_DEPTH:-5}"

# Тесты исключены намеренно — тем же списком, что и в duplicate-code. Глубокая вложенность в
# тесте это обход таблицы ожиданий, а не сложная логика: замер по fastapi дал 303 находки, из
# которых 101 в tests/. Гейт, который краснеет в основном на тестах, выключают целиком.
TESTS="-name test -prune -o -name tests -prune -o -name spec -prune -o -name __tests__ -prune -o"

# shellcheck disable=SC2046
find "$DIR" $(skip_find "$DIR") $TESTS -type f \
     ! -name 'test_*' ! -name '*_test.*' ! -name '*.test.*' ! -name '*.spec.*' \
     -print 2>/dev/null | only_code | own_samples_filter "$DIR" \
  | drop_generated \
  | xargs -r awk -v MAX="$MAX" '
        # Один обход на все файлы: процесс на каждый файл дал 19 секунд на 4000 файлов.
        # Разметка вложена по природе: пять уровней тегов — это не сложная логика, а обычная
        # вёрстка. Меряя её тем же пределом, гейт краснеет на нормальном коде и его выключают.
        function limit() { return (wf ~ /\.(jsx|tsx|vue|svelte)$/) ? MAX + 3 : MAX }
        # Шаг отступа берётся ИЗ ФАЙЛА, а не считается равным четырём. Пока он был прибит к
        # четырём, проверка видела ВДВОЕ МЕНЬШУЮ вложенность в javascript и typescript, где
        # общепринятый отступ — два пробела: шесть уровней давали «три» и проходили предел
        # молча. Замечено 2026-09-10, когда в каталог впервые добавили образец на .js: go и
        # python отступают на четыре, и на них дефекта не видно в принципе.
        # Минимум зажат снизу двойкой: файл с одиночным пробелом в продолжении строки иначе
        # вчетверо завысил бы вложенность и дал ложную тревогу.
        function unit() { return (step >= 2 && step <= 8) ? step : 4 }
        function flush() {
          if (wf != "" && int(worstN / unit()) > limit())
            print wf ":" wl ": вложенность " int(worstN / unit()) ", предел " limit()
        }
        FNR == 1 { flush(); worstN = 0; wl = 0; step = 0; wf = FILENAME }
        /^[[:space:]]*$/ { next }
        {
          # ширина отступа: табуляция считается за четыре пробела. Отступ берётся ОДНИМ
          # match, а не посимвольным циклом с substr: цикл выделял новую строку на каждый
          # символ отступа и стоил больше, чем весь остальной разбор. Замер 2026-09-08 на uv.
          match($0, /^[ \t]*/); ind = substr($0, 1, RLENGTH)
          n = gsub(/\t/, "", ind) * 4 + length(ind)
          if (n > 0 && (step == 0 || n < step)) step = n
          if (n > worstN) { worstN = n; wl = FNR }
        }
        END { flush() }
      ' > /tmp/.cplx.$$ 2>/dev/null

if [ -s /tmp/.cplx.$$ ]; then
  cat /tmp/.cplx.$$; rm -f /tmp/.cplx.$$
  echo "  почини: выдели вложенные ветки в отдельные функции или выйди раньше."
  echo "  такой код не держат в голове целиком — ни человек, ни агент; агент начинает"
  echo "  переписывать его вместо правки."
  exit 1
fi
rm -f /tmp/.cplx.$$
exit 0
