#!/usr/bin/env sh
# Отладочная печать переживает задачу и уезжает в прод: она не ошибка сборки и
# не видна в ревью диффа на 400 строк. В проде это либо шум, либо утечка данных
# мимо системы логов.
DIR="${1:-.}"
. "$(dirname "$0")/../_skip.sh" 2>/dev/null || SKIP_NAMES=".git .aqk node_modules .venv"
# Красный образец — намеренно сломанный код в репозитории. Сканирующий гейт обязан его
# пропускать, иначе будет вечно краснеть на том, что сам же и положил. Исключение снимается,
# когда проверяют сам образец: тогда каталог red и есть цель проверки.

# Где печать законна и дефектом не является: вспомогательные скрипты, оснастка, примеры,
# записные книжки. Это НЕ общий список исключений: секрет в scripts/ — такой же секрет,
# а печать там — обычный способ говорить с человеком.
#
# На настоящем проекте без этого различия 285 находок из 330 пришли из scripts/ и оснастки.
# Гейт, который на 86% состоит из ложных сработок, выключают целиком.
TOOLING="--exclude-dir=scripts --exclude-dir=tools --exclude-dir=bin --exclude-dir=examples --exclude-dir=notebooks --exclude-dir=docs --exclude-dir=.claude --exclude-dir=gates --exclude-dir=gates-reference"

# Проект называет СВОИ каталоги, где печать — интерфейс, а не отладка: у программы командной
# строки это её исходники целиком. Объявляется в манифесте, рядом с командой, и потому видно
# глазами: AQK_PRINT_OK_DIRS="tool cli" bash .../check.sh .
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ ХРАПОВИКА. Сначала такие места записали долгом — и каждая новая строка
# вывода красила проверку, требуя переснять реестр. Но долг — это то, что собираются погасить;
# печать из программы командной строки убирать никто не будет. Долг, который нельзя погасить
# работой, — не долг, а неверная мера: журнал, 2026-09-03.
for D in ${AQK_PRINT_OK_DIRS:-}; do
  TOOLING="$TOOLING --exclude-dir=$D"
done
HITS=$(grep -rnE $(skip_grep "$DIR") $(include_code) $TOOLING '(^|[^A-Za-z_.])(print\(|console\.log\(|fmt\.Print|println!|print!|dbg!|System\.out\.print|Console\.Write)' "$DIR" 2>/dev/null | drop_comments | own_samples_filter "$DIR")
if [ -n "$HITS" ]; then
  echo "$HITS"
  echo "  почини: замени на вызов системы логов — тогда запись попадёт в общий журнал и уровень можно приглушить."
  exit 1
fi
exit 0
