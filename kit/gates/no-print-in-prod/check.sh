#!/usr/bin/env sh
# Отладочная печать переживает задачу и уезжает в прод: она не ошибка сборки и
# не видна в ревью диффа на 400 строк. В проде это либо шум, либо утечка данных
# мимо системы логов.
DIR="${1:-.}"
HITS=$(grep -rnE '(^|[^A-Za-z_.])(print\(|console\.log\()' "$DIR" 2>/dev/null)
if [ -n "$HITS" ]; then
  echo "$HITS"
  echo "  почини: замени на вызов системы логов — тогда запись попадёт в общий журнал и уровень можно приглушить."
  exit 1
fi
exit 0
