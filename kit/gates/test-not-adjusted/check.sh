#!/usr/bin/env sh
# Арбитра правит не тот, кто чинит код. Проверку выполняет `checkwash` — готовый инструмент,
# который это умеет лучше, чем сумели бы мы. Здесь только обвязка: выбор диапазона, режим
# образцов и строка совета.
#
# ЗАЧЕМ ЭТО ВООБЩЕ. «Test subversion» — правка теста, чтобы прошёл сломанный код, — один из
# приёмов, которые практики называют поимённо в разборе 1154 обсуждений с Reddit и Hacker News
# (Baltes, Cheong, Treude, «An Endless Stream of AI Slop», arxiv 2603.27249). Наше собственное
# правило `kit/rules/testing.md` требует того же и сторожа не имело.
#
# ПОЧЕМУ НЕ `--fail-on warn` И НЕ ПОРОГ ПО УМОЛЧАНИЮ. Измерено 2026-09-07 на живой истории
# `httpx`, последние 40 коммитов:
#   порог по умолчанию (high) — блокирует 2.5% коммитов, и та единственная блокировка настоящая;
#   `--fail-on warn`          — блокирует 15%, и восемь из одиннадцати находок уровня warn это
#                               `CI_WORKFLOW_TOUCHED`, то есть «диф трогает конвейер» вообще.
# Поднять порог целиком значит красить любую правку конвейера. Поэтому отбор идёт ПО ПРАВИЛУ:
# всё, что high и выше, плюс подгонка арбитра уровня warn. Именно её инструмент понижает по
# признаку REPAIR_EVIDENCE — «в дифе есть и правка кода, значит похоже на настоящую починку», —
# а это ровно тот случай, ради которого запись и заведена: код сломали, тест подогнали.
# Конвейер здесь не наш предмет: его стерегут `ci-actually-fails` и `gates-run-in-ci`.
#
# ОТБОР ИДЁТ ПО ИМЕНИ ПРАВИЛА, А НЕ ПО УРОВНЮ. Первая версия блокировала всё уровня high и выше
# «на всякий случай» — и ловила `GUARDRAIL_TOUCHED`, который инструмент поднимает до critical на
# ЛЮБУЮ правку `AGENTS.md`, `CLAUDE.md`, `.claude/**`. Для нас это худшее из возможных ложных
# срабатываний: свод правил — ровно тот файл, ради правки которого комплект и существует, его
# пишет `aqk init`. Найдено код-ревью 2026-09-07; замер по `httpx` этого показать не мог —
# там нет файлов инструкций агенту вовсе.
#
# ALWAYS — подгонка арбитра: красим на любом уровне. Именно её инструмент понижает до `warn`
# по признаку REPAIR_EVIDENCE, и именно она предмет этой записи.
ALWAYS='ASSERT_REMOVED|ASSERT_WEAKENED|ASSERT_SUBSTITUTED|TEST_PATCHES_SUBJECT|SUBJECT_NORMALIZED|CONFTEST_PATCHES_PROD'
#
# HIGH_ONLY — тест исчез. Инструмент сам различает: вместе с правкой кода — `warn` (обычно
# законная уборка при снятии возможности, так было в коммите `httpx` «Graceful upgrade path for
# 0.28»); без правки кода — `high` («NO_PROD_CHANGE_IN_DIFF»), и это чистое снятие сигнала.
# Поднимать первое значит красить каждую депрекацию: замер давал 5% заблокированных коммитов
# вместо 2.5%, и лишняя половина была именно такой.
HIGH_ONLY='TEST_DISABLED'
#
# Всё остальное — не наш предмет. `CI_WORKFLOW_TOUCHED` стерегут `ci-actually-fails` и
# `gates-run-in-ci`; `GUARDRAIL_TOUCHED` не стережёт никто, и это правильно: правка свода
# правил — обычная работа, а не подгонка арбитра.

DIR="${1:-.}"

# Режим образца: рядом лежат before/ и after/. Настоящей истории git внутри каталога комплекта
# взять неоткуда, а вложенный .git создал бы embedded-репозиторий. Собираем одноразовый.
if [ -d "$DIR/before" ] && [ -d "$DIR/after" ]; then
  T=$(mktemp -d) || exit 2
  cp -R "$DIR/before/." "$T/" 2>/dev/null
  ( cd "$T" && git init -q . && git config user.email aqk@example && git config user.name aqk &&
    git add -A && git commit -qm "before" ) >/dev/null 2>&1
  find "$T" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} + 2>/dev/null
  cp -R "$DIR/after/." "$T/" 2>/dev/null
  ( cd "$T" && git add -A && git commit -qm "after" ) >/dev/null 2>&1
  REPO="$T"; RANGE="HEAD~1..HEAD"
else
  if ! (cd "$DIR" 2>/dev/null && git rev-parse --git-dir >/dev/null 2>&1); then
    echo "не git-репозиторий — проверять нечего"
    exit 0
  fi
  # Диапазон: по умолчанию последний коммит. Проект может назвать свой — так же, как это
  # делает `doctor --since`.
  RANGE="${AQK_TEST_RANGE:-HEAD~1..HEAD}"
  # Проверяем ТОТ диапазон, который сейчас используется, а не всегда `HEAD~1`. Проект, назвавший
  # `AQK_TEST_RANGE=origin/main..HEAD`, получал бы «меньше двух коммитов» на клоне без `HEAD~1`,
  # хотя его диапазон полностью разрешим. Найдено код-ревью 2026-09-07.
  BASE="${RANGE%%..*}"
  if ! (cd "$DIR" && git rev-parse -q --verify "$BASE" >/dev/null 2>&1); then
    echo "$BASE не разрешается — сравнивать не с чем, проверка пропущена"
    echo "  почини: дай конвейеру историю глубже одного коммита —"
    echo "  actions/checkout@v4 с fetch-depth: 2, либо назови свой диапазон в AQK_TEST_RANGE."
    exit 0
  fi
  REPO="$DIR"
fi

if ! command -v checkwash >/dev/null 2>&1; then
  [ -n "${T:-}" ] && rm -rf "$T"
  echo "checkwash не установлен — проверять нечем"
  echo "  почини: pip install checkwash — запись делегирует ему целиком, своей проверки у неё нет."
  exit 2
fi

# `--fail-on info` — чтобы инструмент отдал ВСЁ, что нашёл; решение принимаем сами, ниже.
JSON=$(checkwash check "$RANGE" --repo "$REPO" --format json --fail-on info 2>/dev/null)
[ -n "${T:-}" ] && rm -rf "$T"

if [ -z "$JSON" ]; then
  echo "checkwash не дал разбора для $RANGE"
  echo "  почини: запусти команду руками и посмотри, почему она молчит."
  echo "  «не смогли проверить» и «нарушений нет» дают одинаково пустой список и разные выводы."
  exit 2
fi

# Разбор вывода: json печатается по полю на строку, поэтому пары «rule/severity» собираются
# построчно. Своего разбора json мы не пишем — нужны два поля, а не структура.
# Ошибки разбора самого инструмента — это «не смогли проверить», а не «нарушений нет».
if printf '%s\n' "$JSON" | grep -q '"config_errors": \[$' &&
   printf '%s\n' "$JSON" | sed -n '/"config_errors": \[/,/\]/p' | grep -q '"'; then
  printf '%s\n' "$JSON" | sed -n '/"config_errors": \[/,/\]/p'
  echo "  почини: у checkwash ошибка в настройке — запусти его руками и прочти вывод."
  exit 2
fi

# Разбор вывода: json печатается по полю на строку, поэтому поля находки собираются построчно.
# Своего разбора json мы не пишем — нужны пять полей, а не структура.
FOUND=$(printf '%s\n' "$JSON" | awk -v always="$ALWAYS" -v highonly="$HIGH_ONLY" '
  /"allowlisted":/ { al = ($0 ~ /true/) }
  /"rule":/     { r = $0; sub(/.*"rule":[[:space:]]*"/, "", r); sub(/".*/, "", r) }
  /"severity":/ { s = $0; sub(/.*"severity":[[:space:]]*"/, "", s); sub(/".*/, "", s) }
  /"path":/     { p = $0; sub(/.*"path":[[:space:]]*"/, "", p); sub(/".*/, "", p) }
  /"message":/  { m = $0; sub(/.*"message":[[:space:]]*"/, "", m); sub(/".*/, "", m) }
  # Печатаем на `unit` — ПОСЛЕДНЕМ поле находки. Поля идут по алфавиту, и `message` стоит
  # РАНЬШЕ `rule` и `severity`: печать по сообщению подписывала правило от предыдущей находки.
  /"unit":/     {
    u = $0
    sub(/.*"unit":[[:space:]]*/, "", u)      # значение бывает и `null` без кавычек
    gsub(/^[",[:space:]]+|[",[:space:]]+$/, "", u)
    if (u == "null") u = ""
    if (r != "") {
      # Разрешённое исключение уже разобрано человеком и записано в реестр инструмента со
      # сроком. Красить его значит не оставить выхода, кроме как выключить проверку целиком.
      blocking = !al && (r ~ ("^(" always ")$") ||
                         ((s == "high" || s == "critical") && r ~ ("^(" highonly ")$")))
      if (blocking) printf "%s:%s: %s — %s [%s]\n", p, (u == "" ? "0" : u), r, m, s
    }
    r = ""; s = ""; p = ""; u = ""; m = ""; al = 0
  }
')

[ -z "$FOUND" ] && exit 0
printf '%s\n' "$FOUND"
echo "  почини: верни утверждение на место, а код приведи в соответствие с ним."
echo "  тест, подогнанный под сломанный код, — это зелёный прогон без основания."
exit 1
