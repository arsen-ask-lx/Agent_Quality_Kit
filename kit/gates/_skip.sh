#!/usr/bin/env sh
# Что сканирующие проверки не читают. Общий список: разъехавшись по шести проверкам, он
# однажды окажется полным в одной и дырявым в другой.
#
# ПОЧЕМУ ЭТО ВАЖНЕЕ, ЧЕМ КАЖЕТСЯ. На настоящем проекте из 36 тысяч файлов 1722 находки из 1831
# пришли из чужого кода в окружении. Гейт, который на 94% состоит из чужих нарушений, читать
# никто не будет — его выключат.

SKIP_NAMES=".git .aqk node_modules .venv venv env __pycache__ .mypy_cache .pytest_cache
.tox .ruff_cache site-packages dist build target out .next .nuxt .svelte-kit coverage
htmlcov staticfiles vendor bower_components .gradle .idea .vscode
playwright-report test-results storybook-static .turbo .cache .parcel-cache
migrations"

# Образцы гейтов — искусственный код по построению: красный сломан нарочно, зелёный бывает
# вырожденным (двести одинаковых строк, чтобы показать предел размера). Сканировать их — значит
# ловить то, что положил не человек. Исключение снимается, когда цель проверки — сам образец.
#
# ПОЧЕМУ ПО ПУТИ, А НЕ ПО ИМЕНИ. `--exclude-dir=red`/`-name red -prune` совпадают с ЛЮБОЙ папкой
# red в проекте — а это имя не выдуманное: реальный секрет в пользовательской папке `red/`
# (red-team тесты, что угодно) становился невидим для secrets-not-in-code во всех проектах,
# куда ставили гейт. Фильтр ниже смотрит на путь целиком: только `gates/<имя>/red|green/`,
# а не голое имя каталога.
# Список исключений САМОГО ПРОЕКТА: файл .aqkignore в корне, по шаблону на строку, «#» —
# комментарий. Нужен для кода, который лежит в репозитории, но написан не здесь: референс,
# вендоринг, сгенерированные клиенты. Без него единственным способом настройки была правка
# КОПИИ этого файла в проекте — то есть настройка правкой чужого файла, которую затирает
# следующий `aqk add`. Найдено первым чужим прогоном.
#
# Шаблон — фрагмент пути: `vendor/`, `apps/legacy`, `*.generated.js`. Звёздочка не переходит
# через «/», как в .gitignore, — иначе «src/*» прятало бы весь проект.
aqkignore_re() {
  F="${1:-.}/.aqkignore"
  [ -f "$F" ] || return 1
  sed -e 's/#.*$//' -e 's|/*[[:space:]]*$||' -e 's/^[[:space:]]*//' "$F" |
    grep -v '^$' |
    sed -e 's/[][(){}.^$+?|\\]/\\&/g' -e 's/\*/[^\/]*/g' |
    tr '\n' '|' | sed 's/|$//'
}

# Один фильтр на два дела, и это осознанно: его зовут все семь сканирующих проверок, а их
# копии уже лежат в чужих проектах. Добавить сюда — значит, что обновление комплекта включает
# .aqkignore и у тех, кто ставил гейты раньше, без перекопирования их check.sh.
own_samples_filter() {
  DIR0="${1:-}"
  RE="$(aqkignore_re "$DIR0")"
  case "$DIR0" in
    # Цель проверки — сам образец: тогда прятать его нельзя, иначе гейт «пройдёт» на красном.
    */red|*/red/|*/green|*/green/) SAMPLES="cat" ;;
    # «(^|/)» обязательно: переносимые проверки печатают «./gates/…», а родной инструмент —
    # «gates/…» без точки. Пока шаблон требовал ведущий «/», образцы прятались только от
    # первых, и родной рецепт выдавал их как находки.
    *) SAMPLES="grep -vE (^|/)gates/[^/]+/(red|green)(/|\$)" ;;
  esac
  if [ -n "$RE" ]; then
    $SAMPLES | grep -vE "(^|/)($RE)(/|:|\$)"
  else
    $SAMPLES
  fi
}

# Расширения, где `print` и маркеры долга — конструкции языка, а не текст. Проверять по ним
# файлы настроек, разметку и отчёты бессмысленно: там те же слова означают другое.
# Модульные варианты перечислены наравне с обычными: без .mjs проверки молча не смотрели
# в программу самого aqk, целиком написанную в этом расширении.
CODE_EXT="py js jsx mjs cjs ts tsx mts cts vue go rb java cs php rs kt swift scala"

include_code() {
  for E in $CODE_EXT; do printf -- '--include=*.%s ' "$E"; done
}

# Сгенерированный файл не правят руками — предъявлять его размер или сложность человеку
# бессмысленно и вредно: он выключит проверку целиком.
# Опознаём по общепринятой шапке в первых пяти строках.
# Регистр кириллицы `grep -i` сворачивает НЕ ВЕЗДЕ: на linux сворачивает, в Git Bash под
# Windows — нет. Шапка `// СГЕНЕРИРОВАН` там не находилась никогда, и узнали мы об этом только
# 2026-09-08, когда нарочный набор впервые прогнали на windows-задании. Это не регрессия правки,
# а старая дыра, которую нечем было увидеть: на живых шести проектах таких шапок не было.
# Поэтому кириллица перечисляется явно, а не доверяется флагу: три написания, которые бывают
# на деле, — строчное в комментарии, с заглавной в начале фразы и капсом в баннере.
GENERATED_MARKERS='@generated|do not edit|autogenerated|auto-generated|generated by|сгенерирован|Сгенерирован|СГЕНЕРИРОВАН'

# Один файл: сгенерирован ли он. Осталось для тех, кто спрашивает про ОДИН файл
# (gate-not-weakened сверяет строку находки, а не список путей).
is_generated() {
  head -5 "$1" 2>/dev/null | grep -qiE "$GENERATED_MARKERS"
}

# СПИСОК файлов на stdin (по пути в строке) → тот же список без сгенерированных.
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ is_generated. Цикл `while read; do is_generated; done` запускает ДВА
# процесса на каждый файл — head и grep. Замерено 2026-09-08 на 748 файлах проекта uv:
# обход и отбор 12 мс, подсчёт строк одним wc 37 мс, а этот цикл — 3862 мс. Сто крат от
# всего остального, и ни микросекунды из них не потрачено на сравнение строк: платили за
# fork+exec. Медленным был не язык — медленным было количество запусков.
#
# ПОЧЕМУ ИМЕННО grep, А НЕ awk. Соблазн был собрать всё одним awk с `nextfile`. Отвергнуто:
# `nextfile` — расширение, а `tolower` на кириллице врёт в mawk и busybox-awk, и «сгенерирован»
# перестал бы находиться там, где сейчас находится. Здесь ТОТ ЖЕ grep с ТЕМИ ЖЕ флагами, что
# и в is_generated, — значит совпадение считается ровно так же, как раньше, и меняется только
# число запусков. Равенство вывода проверено на шести чужих проектах: 0 расхождений.
#
# `-m1` останавливает grep на первом совпадении в файле, `/dev/null` заставляет его печатать
# имя файла даже когда xargs передал ровно один путь.
drop_generated() {
  LIST=$(mktemp) || { cat; return; }
  GEN=$(mktemp) || { rm -f "$LIST"; cat; return; }
  cat > "$LIST"
  # Пути передаются через НОЛЬ-разделитель: xargs по умолчанию рвёт по пробелам, и файл
  # «src/my component.tsx» уехал бы в grep двумя несуществующими путями. Поймано нарочным
  # набором до выпуска: старый цикл `while read` пробелы держал, и потерять это было нельзя.
  tr '\n' '\0' < "$LIST" \
    | xargs -0 -r grep -niE -m1 -e "$GENERATED_MARKERS" /dev/null 2>/dev/null \
    | awk -v list="$LIST" '
        # Строка вывода grep — «путь:номер:текст», и разобрать её по первому двоеточию нельзя:
        # в пути тоже бывает двоеточие, а в тексте находки — тем более. Поэтому путь не
        # угадывается, а СВЕРЯЕТСЯ со списком, который мы сами и передали: идём по двоеточиям
        # слева направо, пока префикс не совпадёт с известным путём. Двоеточие в имени файла
        # редкость, но «редко» и «никогда» — разные вещи, а тихо оставленный сгенерированный
        # файл даёт находки на чужом коде.
        BEGIN { while ((getline l < list) > 0) known[l] = 1 }
        {
          rest = $0; prefix = ""
          while ((i = index(rest, ":")) > 0) {
            prefix = prefix substr(rest, 1, i - 1)
            rest = substr(rest, i + 1)
            if (prefix in known) {
              if (match(rest, /^[0-9]+:/) && substr(rest, 1, RLENGTH - 1) + 0 <= 5) print prefix
              break
            }
            prefix = prefix ":"
          }
        }
      ' | sort -u > "$GEN"
  if [ -s "$GEN" ]; then grep -vxF -f "$GEN" "$LIST"; else cat "$LIST"; fi
  rm -f "$LIST" "$GEN"
}

# Для grep: --exclude-dir на каждое имя. Образцы гейтов сюда не входят — см. own_samples_filter:
# у --exclude-dir нет способа смотреть на путь целиком, только на голое имя папки.
skip_grep() {
  for N in $SKIP_NAMES; do printf -- '--exclude-dir=%s ' "$N"; done
}

# Для вывода родного инструмента: отбрасывает строки, чей путь лежит внутри пропускаемого
# каталога. Переносимые проверки получают этот список при обходе (skip_grep/skip_find), а
# родному инструменту он не доставался вовсе: на живом проекте первой находкой duplicate-code
# оказались методички самого комплекта в `.aqk/docs`, которые туда положил `init`.
#
# По сегменту пути, а не по подстроке — тот же урок, что с папкой `red`: имя «build» встречается
# и внутри слова, и файл `src/rebuild.py` прятать нельзя.
skip_paths_filter() {
  RE_SKIP="$(printf '%s' "$SKIP_NAMES" | tr '\n' ' ' | sed -e 's/^ *//' -e 's/ *$//' \
    -e 's/\./\\./g' -e 's/  */|/g')"
  [ -n "$RE_SKIP" ] || { cat; return; }
  # Граница слева — начало строки, «/» или любой символ, которого не бывает внутри имени пути.
  # Родные инструменты печатают путь не с начала строки: у jscpd это « - путь». Пока требовалось
  # начало строки или «/», такие строки не отсеивались вовсе. Буквы, цифры, «_», «.» и «-»
  # границей не считаются — иначе «build/» отсеяло бы и «rebuild/».
  grep -vE "(^|/|[^[:alnum:]_.-])($RE_SKIP)/"
}

# Для find: -name X -prune -o …
skip_find() {
  for N in $SKIP_NAMES; do printf -- '-name %s -prune -o ' "$N"; done
}

# Отбрасывает находки, сделанные в строках-комментариях. Вход — вывод `grep -rn` в виде
# «файл:строка:код». Комментарий не выполняется: находка в нём означает, что проверка читает
# текст, а не код. Найдено прогоном по audit_project: семь находок из JSDoc и закомментированных
# строк. Проверкам, которые ищут ИМЕННО в комментариях (маркеры долга), этот фильтр не нужен.
drop_comments() { grep -vE '^[^:]*:[0-9]+:[[:space:]]*(//|\*|#|/\*|--)' ; }

# Отбор файлов кода из потока путей. Один список на все проверки: раньше каждая несла свой,
# переписанный заново, и они разошлись — четыре проверки, четыре разных набора, и `.mjs` не было
# ни в одном. Программа самого комплекта целиком в `.mjs`: предел размера файла молчал на ней
# при 1366 строках и пределе 500.
#
# Почему фильтром потока, а не выражением для find: набор `-name *.py` пришлось бы подставлять
# без кавычек, и оболочка развернула бы звёздочку по файлам текущего каталога.
#
# `sh` в списке нет намеренно: печать в скрипте — его способ говорить с человеком, и запрет
# отладочной печати покрасил бы каждый из них.
only_code() { grep -E "\.($(printf '%s' "$CODE_EXT" | tr ' ' '|'))$"; }

# Метка собранности. Ставится ПОСЛЕДНЕЙ строкой намеренно: она подтверждает, что файл дочитан
# до конца, а не только начат. Подключающий обязан её проверить — до 2026-09-10 он проверял
# лишь НАЛИЧИЕ файла, и подмена содержимого давала код 0: гейт печатал «command not found» и
# объявлял проект чистым. Библиотеку подключает каждая запись каталога, то есть одним
# испорченным файлом гасился весь набор защит.
AQK_SKIP_READY=1
