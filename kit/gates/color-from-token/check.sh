#!/usr/bin/env sh
# Цвет приходит из токена темы, а не из литерала в компоненте.
#
# ЗАЧЕМ. Литеральный цвет тема не перекрашивает. Проект с несколькими темами получает экран,
# который в тёмной теме остаётся светлым пятном, — и это видно не автору, а пользователю,
# который переключил тему. Дефект тихий: в теме автора всё выглядит правильно.
DIR="${1:-.}"
# Существование файла проверяется ДО `.`, а не запасной веткой после. Прежняя строка
# `. файл 2>/dev/null || запасной_вариант` выглядела страховкой и ею не была: под `sh` (dash)
# неудачный `.` завершает скрипт немедленно, и ветка после `||` не выполняется никогда; под
# `bash`, которым гейты и запускаются из манифеста, она выполняется, но подставляет только
# ПЕРЕМЕННУЮ — функции обхода остаются неопределёнными, конвейер печатает пустоту, и проверка
# выходит с НУЛЁМ. Замерено 2026-09-08 на файле с настоящим нарушением: гейт сказал «чисто».
SKIP_LIB="$(dirname "$0")/../_skip.sh"
if [ ! -f "$SKIP_LIB" ]; then
  echo "рядом с проверкой нет _skip.sh — обход не собран, проверка не состоялась"
  echo "  почини: скопируй гейт вместе с файлом kit/gates/_skip.sh, он общий на весь каталог"
  exit 2
fi
. "$SKIP_LIB"

# Расширения, где живёт ТЕМИЗИРУЕМЫЙ интерфейс. Своё, а не общий CODE_EXT: там нет ни css, ни
# vue — они не код в смысле «отладочная печать», но именно в них живёт цвет.
#
# `.html` в списке НЕТ, и это измерено, а не выбрано на вкус. Первый прогон по живому проекту
# (React, 12 тем) дал 20 находок, и ВСЕ 20 — в отдельных html-документах внутри `.claude/`:
# отчёты и справочники оснастки агента. Во фронтенде — ноль. Отдельный html-документ не имеет
# темы и не может её иметь: литерал там законен, как печать в скрипте. Гейт, на 100%
# состоящий из чужих находок, выключают в первый день — см. шапку `_skip.sh`.
COLOR_EXT="css scss sass less styl ts tsx js jsx mjs cjs vue svelte astro"

# Файлы-ИСТОЧНИКИ значений: там литерал законен, иначе токену неоткуда взяться. Имя источника
# проект называет сам — как и каталоги с законной печатью в no-print-in-prod. По умолчанию
# общепринятые имена; свои задаются переменной, рядом с командой в манифесте.
SOURCE_RE="${AQK_COLOR_SOURCE:-tokens|theme|themes|palette|colors|colours|variables|design-system}"

EXT_RE="$(printf '%s' "$COLOR_EXT" | tr ' ' '|')"

# shellcheck disable=SC2086
HITS=$(find "$DIR" $(skip_find "$DIR") -type f -print 2>/dev/null \
  | grep -E "\.($EXT_RE)$" \
  | grep -viE "(^|/)[^/]*($SOURCE_RE)[^/]*\.($EXT_RE)$" \
  | drop_generated \
  | LC_ALL=C sort \
  | xargs -r awk '
      # Блочные комментарии вырезаются ПО СОСТОЯНИЮ, а не построчно. Однострочный фильтр
      # смотрит только на начало строки, и цвет, упомянутый в середине многострочного
      # пояснения, читался как находка: на живом проекте так и вышло — единственное
      # ложное срабатывание пришло из строки внутри /* … */. Тот же класс, что запись
      # журнала «печать внутри комментария считалась печатью».
      FNR == 1 { inblock = 0 }
      {
        line = $0
        if (inblock) {
          i = index(line, "*/")
          if (i == 0) next
          line = substr(line, i + 2); inblock = 0
        }
        # Вырезаем закрытые /* … */ внутри строки, затем открытый хвост.
        while ((s = index(line, "/*")) > 0) {
          rest = substr(line, s + 2)
          e = index(rest, "*/")
          if (e == 0) { line = substr(line, 1, s - 1); inblock = 1; break }
          line = substr(line, 1, s - 1) substr(rest, e + 2)
        }
        # Хвост — «не буква, не цифра, не дефис», а не просто «не шестнадцатеричный символ».
        # Якорь ссылки «#defining-entry-points» начинается с «#def», за которым идёт «i»: по
        # прежнему правилу это был цвет. Замер 2026-09-08 по шести чужим репозиториям: в uv
        # ложным оказалось именно это, в docs/js/extra.js.
        # Цвет выписан поразрядно: mawk (умолчание Debian и Ubuntu) не понимает повторители
        # {3},{6},{8}, и это условие не срабатывало никогда — гейт молчал на красном образце.
        # Поймано сборкой docker-образа 2026-09-08, а не прогоном: на хосте gawk.
        if (line ~ /#[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]([^0-9a-zA-Z_-]|$)|#[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]([^0-9a-zA-Z_-]|$)|#[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]([^0-9a-zA-Z_-]|$)/)
          print FILENAME ":" FNR ":" $0
      }
    ' 2>/dev/null \
  | drop_comments \
  | own_samples_filter "$DIR")

if [ -n "$HITS" ]; then
  printf '%s\n' "$HITS" | head -20
  N=$(printf '%s\n' "$HITS" | grep -c .); [ "$N" -gt 20 ] && echo "  … и ещё $((N - 20))"
  echo "  почини: замени литерал на токен темы — var(--color-…), theme('colors.…'), \$color-…"
  echo "  литеральный цвет тема не перекрашивает: в другой теме экран останется чужим пятном."
  echo "  файл-источник значений называется сам: AQK_COLOR_SOURCE='tokens|brand' перед командой."
  exit 1
fi
exit 0
