#!/usr/bin/env sh
# Гейт без образцов — непроверенное утверждение. Красный образец доказывает, что гейт ловит
# брак; зелёный — что он молчит на исправном коде. Зелёный важнее: именно он ловит гейт,
# который ругается на предписанное им же написание.
#
# ЧТО ИМЕННО ТРЕБУЕТ ОБРАЗЦЫ. Только записи-сканеры: те, чья команда запускает проверку из
# каталога образцов. У прогона с собственным арбитром — `pytest`, `node --test`, `go test` —
# образцы уже внутри него, и требовать их отдельно значит требовать работу, которой нет.
# Первая редакция этого не различала и записала долгом четыре собственных прогона комплекта:
# проверка мерила не то, что называла.
#
# ЧЕГО НЕ ЛОВИТ. Прогон, объявленный в манифесте и не ссылающийся на каталог, этой записью не
# проверяется вовсе. Что его арбитр настоящий, а не `echo ok`, показывает только красный прогон:
# сломай проверяемое — конвейер обязан покраснеть.
DIR="${1:-.}"
MAN="$DIR/.aqk.yml"
[ -f "$MAN" ] || { echo "нет .aqk.yml — проверять нечего"; exit 0; }

SAMPLES=$(sed -n 's/^samples:[[:space:]]*"\{0,1\}\([^"#]*\)"\{0,1\}[[:space:]]*$/\1/p' "$MAN" | head -1)
KEYS=$(awk '/^gates:/{g=1;next} /^[A-Za-z]/{g=0} g && /^[[:space:]]+[A-Za-z0-9_-]+:/{sub(/:.*/,"");gsub(/[[:space:]]/,"");print}' "$MAN")

[ -z "$KEYS" ] && { echo "гейтов не объявлено — проверять нечего"; exit 0; }

if [ -z "$SAMPLES" ]; then
  # Без каталога образцов проверить нечего ни у одной записи. Одно сообщение, а не по одному
  # на гейт: дефект здесь один, и он в манифесте.
  echo "в .aqk.yml не заполнено поле samples — образцы искать негде"
  echo "  почини: заведи каталог образцов и укажи его в samples"
  exit 1
fi

BAD=0
for K in $KEYS; do
  # Команда записи целиком — по ней видно, сканер это или собственный прогон проекта.
  CMD=$(awk -v k="$K" '/^gates:/{g=1;next} /^[A-Za-z]/{g=0} g && $0 ~ "^[[:space:]]+" k ":" {sub(/^[[:space:]]*[A-Za-z0-9_-]+:[[:space:]]*/,"");gsub(/^"|"$/,"");print;exit}' "$MAN")
  case "$CMD" in
    *"$SAMPLES/"*) ;;                 # сканер из каталога — образцы обязательны
    *) continue ;;                    # свой прогон — арбитр внутри него
  esac
  for KIND in red green; do
    if [ ! -d "$DIR/$SAMPLES/$K/$KIND" ]; then
      echo "гейт «$K»: нет образца $KIND ($SAMPLES/$K/$KIND)"
      echo "  почини: положи код, на котором гейт обязан $( [ $KIND = red ] && echo краснеть || echo молчать )"
      BAD=1
    fi
  done
done
exit $BAD
