#!/usr/bin/env sh
# Подавление проверки без адреса: «выключено всё» вместо «выключено вот это».
#
# ЗАЧЕМ ИМЕННО ЭТО. Когда проверка краснеет, у пишущего два выхода: починить код или заглушить
# проверку. Второй дешевле и с виду неотличим от первого — конвейер зелёный, диф маленький.
# Для агента это выход по умолчанию: ему поставлена задача «сделай, чтобы прошло».
#
# ГРАНИЦА НАМЕРЕННО УЗКАЯ. Красным делается не всякое подавление, а безадресное: `# noqa` без
# кода, `eslint-disable` без имени правила, `@SuppressWarnings("all")`. Точечное подавление с
# названным правилом — законный инструмент, и требовать объяснения от каждого значит получить
# гейт, который выключат. Одно исключение — `@ts-ignore`: у него есть строго лучший брат
# `@ts-expect-error`, который сам краснеет, когда становится не нужен.
DIR="${1:-.}"
. "$(dirname "$0")/../_skip.sh" 2>/dev/null || SKIP_NAMES=".git .aqk node_modules .venv"

OUT=""
add() { [ -z "$1" ] || OUT="$OUT$1
"; }

# --- безадресные подавления в коде -------------------------------------------
# `# noqa` без двоеточия с кодом; `type: ignore` без [кода]; файловые выключатели целиком.
add "$(grep -rnE '(^|[^A-Za-z0-9_])#[[:space:]]*(noqa|type:[[:space:]]*ignore)([[:space:]]*$|[[:space:]]+[^:[])' \
  $(skip_grep) $(include_code) "$DIR" 2>/dev/null)"
add "$(grep -rnE '#[[:space:]]*(flake8:[[:space:]]*noqa[[:space:]]*$|ruff:[[:space:]]*noqa[[:space:]]*$|mypy:[[:space:]]*ignore-errors|pylint:[[:space:]]*(skip-file|disable=all))' \
  $(skip_grep) $(include_code) "$DIR" 2>/dev/null)"

# eslint-disable без имени правила: голая директива гасит ВСЁ в файле или на строке.
#
# ВЕДУЩИЙ КОММЕНТАРИЙ ОБЯЗАТЕЛЕН — «(//|/\*|\*)[^\"']*». Замер по пятнадцати чужим
# репозиториям показал целый класс ложных: строка ПРО подавление внутри кавычек
# («title: 'No @ts-ignore'», текст правила в наборе тестов) читалась как подавление.
# Директива живёт в комментарии; упоминание в строковом литерале — не она.
add "$(grep -rnE '(//|/\*|\*)[^\"'"'"']*eslint-disable(-next-line|-line)?[[:space:]]*(\*/|$|--)' \
  $(skip_grep) $(include_code) "$DIR" 2>/dev/null)"

# @ts-ignore и @ts-nocheck. Первый гасит ошибку молча и остаётся, когда ошибки уже нет;
# @ts-expect-error на его месте краснеет, как только становится лишним.
add "$(grep -rnE '(//|/\*|\*)[^\"'"'"']*@ts-(ignore|nocheck)' \
  $(skip_grep) $(include_code) "$DIR" 2>/dev/null)"

# Остальные экосистемы — только безадресная форма.
add "$(grep -rnE '#!?\[allow\((warnings|unused)\)\]|@SuppressWarnings\((\{[^}]*)?"all"|//[[:space:]]*nolint[[:space:]]*($|//)|rubocop:disable[[:space:]]+all|shellcheck[[:space:]]+disable[[:space:]]*($|[^=])' \
  $(skip_grep) $(include_code) "$DIR" 2>/dev/null)"

# --- обход самого конвейера ---------------------------------------------------
# `--no-verify` пропускает хуки коммита. В committed-скрипте или конфиге конвейера это не
# настройка, а выключенная защита: смотрим шире кода — в оболочечные скрипты и конфиги.
# `-e`, а НЕ `--`. Двойное тире завершает разбор опций, и все флаги `--include` после него
# grep считает именами файлов: проверка читала весь репозиторий вместо оболочечных скриптов и
# конфигов. Нашлось замером — в выдаче оказались CHANGELOG чужих проектов.
add "$(grep -rnE -e '--no-verify' $(skip_grep) \
  --include=*.sh --include=*.yml --include=*.yaml --include=*.json --include=*.toml \
  --include=*.mk --include=Makefile "$DIR" 2>/dev/null)"

# Собственное определение записи — не подавление, а перечень того, что ищется. Без этого
# проверка находит сама себя в любом проекте, куда её поставили: `check.sh` содержит все
# образцы разом. Тот же класс, что образцы red/green, только файл другой.
SELFDIR="$(basename "$(dirname "$0")")"
LEFT="$(printf '%s' "$OUT" | grep -v '^$' | own_samples_filter "$DIR" \
  | grep -vE "(^|/)$SELFDIR/(check\.sh|README\.md)")"
# Сгенерированные файлы правят не руками: подавление в них поставил инструмент.
LEFT="$(printf '%s\n' "$LEFT" | while IFS= read -r L; do
  F="${L%%:*}"
  [ -n "$F" ] || continue
  is_generated "$F" || printf '%s\n' "$L"
done | grep -v '^$')"

[ -z "$LEFT" ] && exit 0
printf '%s\n' "$LEFT"
echo "  почини: назови, ЧТО подавляешь и зачем — «# noqa: E501», «eslint-disable-next-line no-console -- причина»,"
echo "  «@ts-expect-error» вместо «@ts-ignore». Безадресное подавление гасит и то, что сломается завтра."
exit 1
