#!/usr/bin/env sh
# Журнал без отметки о решении — это дневник, а не журнал. Разница видна не сразу: обе формы
# читаются одинаково, но по дневнику нельзя ответить на вопрос «что мы после этого поменяли».
#
# Отметка обязана быть одной из трёх, и третья — тоже решение:
#   ✅ стало сторожем   🔧 стало правкой оснастки   👤 гейтом не станет, и вот почему
# Отказ, названный вслух, стоит дороже молчания: он не даёт вернуться к тому же спору.
DIR="${1:-.}"
MAN="$DIR/.aqk.yml"

# Где журнал — говорит манифест. Своего мнения у проверки быть не должно: путь у каждого свой.
# Перевод строк из windows-чекаута снимается ДО разбора. Жадный захват в sed («[^"#]*») и
# якорь конца строки («s/"$//») проглатывают \r: путь получался с кавычкой на хвосте, а
# красный образец переставал краснеть. Найдено мутационной проверкой
# (tool/selfcheck/mutation.sh), а не на Windows-машине — её у нас до сих пор нет.
MANTEXT="$(tr -d '\r' < "$MAN" 2>/dev/null)"
LESSONS=$(printf '%s\n' "$MANTEXT" | sed -n 's/^lessons:[[:space:]]*"\{0,1\}\([^"#]*\)"\{0,1\}[[:space:]]*$/\1/p' 2>/dev/null | head -1)
case "$LESSONS" in
  "" ) echo "в .aqk.yml не указано поле lessons — журнала нет"; exit 0 ;;
  http*://* ) echo "журнал вынесен наружу ($LESSONS) — здесь не проверить"; exit 0 ;;
esac
[ -d "$DIR/$LESSONS" ] || { echo "каталога журнала нет: $LESSONS"; exit 0; }

FILES=$(find "$DIR/$LESSONS" -type f -name '*.md' 2>/dev/null)
[ -z "$FILES" ] && { echo "в журнале нет записей"; exit 0; }

# Шишка — раздел верхнего уровня, чей заголовок начинается с даты (YYYY-MM-DD — …). Оглавления
# и вводные разделы-контейнеры («Перенесённое из…», «Открытые работы…») дате не соответствуют
# и решением кончаться не обязаны. Отметка ищется где угодно в разделе, не только в цитате:
# старые записи несут её строкой ">", новые — абзацем "**Вывод.**"; оба варианта законны.
printf '%s\n' $FILES | while read -r F; do
  awk -v FILE="$F" '
    # Дата выписана поразрядно, а не как [0-9]{4}: mawk — умолчание Debian и Ubuntu — не понимает
    # повторители в регулярках, и такая строка не совпадала НИКОГДА. Гейт молча выходил с нулём
    # на собственном красном образце. Поймано сборкой образа 2026-09-08: на хосте gawk, в образе
    # mawk, и приёмка каталога внутри образа отклонила две записи из двадцати.
    /^## [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]/ { flush(); title = $0; sub(/^## /, "", title); is_entry = 1; has_mark = 0; next }
    /^## / { flush(); is_entry = 0; next }
    (/✅/ || /🔧/ || /📜/ || /👤/) { has_mark = 1 }
    END { flush() }
    function flush() {
      if (is_entry && title != "" && !has_mark)
        print FILE ": «" title "» — нет отметки о решении"
      title = ""
    }
  ' "$F"
done > /tmp/.lesson.$$ 2>/dev/null

if [ -s /tmp/.lesson.$$ ]; then
  cat /tmp/.lesson.$$
  echo "  почини: припиши строку-цитату сразу под заголовком —"
  echo "    > ✅ **Стало гейтом:** <имя записи каталога>"
  echo "    > 🔧 **Стало правкой оснастки:** <что именно изменено>"
  echo "    > 👤 **Гейтом не станет:** <почему — правило дисциплины, решение человека, разовый случай>"
  rm -f /tmp/.lesson.$$
  exit 1
fi
rm -f /tmp/.lesson.$$
exit 0
