#!/usr/bin/env sh
# Каждая ссылка на локальный файл из markdown-файлов каталога обязана вести на
# существующий файл. Ссылка в никуда — это документ, утверждающий защиту,
# которой нет: планирование опирается на неё и ломается молча.
DIR="${1:-.}"
MISS=0
for MD in "$DIR"/*.md; do
  [ -f "$MD" ] || continue
  # вытащить цели ссылок вида [текст](путь)
  # Строки со вставками в обратных кавычках чистятся ДО разбора: «`[name](url)`» — это пример
  # оформления ссылки, а не ссылка. Замер 2026-09-08: в uv/STYLE.md именно так и было, и гейт
  # требовал создать файл с именем «url».
  TARGETS=$(sed 's/`[^`]*`//g' "$MD" | sed -n 's/.*](\([^)]*\)).*/\1/p')
  for T in $TARGETS; do
    # автоссылки бывают обёрнуты как <(https://...)> — искать http где угодно внутри,
    # не только в начале строки.
    case "$T" in *http://*|*https://*|\#*|mailto:*) continue ;; esac
    T=${T%%#*}
    # Строка запроса — не часть имени файла. `assets/demo.gif?raw=1` лежит на диске как
    # `assets/demo.gif`. Найдено замером 2026-09-14 по `bwz96sco/or_llm_agent`: гейт объявил
    # битой ссылку на существующую картинку, и письмо по такой находке было бы неправдой.
    T=${T%%\?*}
    [ -z "$T" ] && continue
    # ПУТЬ, УХОДЯЩИЙ ВЫШЕ КОРНЯ, — адрес на github.com, а не файл. Так сам GitHub предлагает
    # ссылаться на выпуски и задачи: `../../releases/latest` считается от адреса файла в вебе
    # (`github.com/владелец/репозиторий/blob/ветка/README.md`) и раскрывается в
    # `github.com/владелец/репозиторий/releases`. Замер 2026-09-14 по
    # `AndreaGriffiths11/annotation-overlay`: пять таких ссылок объявлены битыми, все пять живые
    # (страница отдаёт 200). Мы смотрим только файлы в каталоге, поэтому здесь молчим: обвинение
    # по догадке выключает гейт целиком.
    case "$T" in ../*) continue ;; esac
    # ПУТЬ ОТ КОРНЯ САЙТА — тоже не файл в каталоге. `/issues`, `/CONTRIBUTING.md` раскрываются
    # от `github.com`, а не от корня репозитория. Замер 2026-09-15 по `dwebagents/AgentPipe`:
    # четыре такие ссылки объявлены битыми. Судить о них мы не можем — смотрим только диск.
    case "$T" in /*) continue ;; esac
    # СТРАНИЦА, КОТОРУЮ СОБИРАЕТ ГЕНЕРАТОР САЙТА. Ссылка из markdown на `.html` почти всегда
    # ведёт на собранную страницу, а не на файл в дереве: разметка ссылается на разметку.
    # Замер 2026-09-15 по `hughjonesd/huxtable`: `articles/huxtable.html` объявлена битой, а
    # страница отдаёт 200 на их сайте — её собирает pkgdown при публикации. Тот же довод, что
    # абзацем выше про путь с косой чертой на конце: проверять адреса умеют lychee и
    # markdown-link-check, они ходят в сеть, а мы смотрим только на диск.
    case "$T" in *.html|*.htm) continue ;; esac
    # СТРАНИЦА ВИКИ ЛЕЖИТ В ДРУГОМ РЕПОЗИТОРИИ — `<репозиторий>.wiki`. Мы его не скачиваем и
    # судить о нём не можем. Замер 2026-09-15 по `00PrabalK00/OpenRosWarehouse`: четырнадцать
    # ссылок на `wiki/Developer-Manual-*.md` объявлены битыми, при том что вики у проекта
    # включена. Молчание честнее обвинения по догадке.
    case "$T" in wiki/*) continue ;; esac
    # Путь, кончающийся косой чертой, — адрес страницы опубликованного сайта, а не файл на
    # диске. Так ссылаются mkdocs, docusaurus и jekyll: `[руководство](tutorial/#install)`
    # работает у читателя и не существует в репозитории. Найдено замером по fastapi — гейт
    # объявлял битой рабочую ссылку из их README. Проверять такие адреса умеют lychee и
    # markdown-link-check: они ходят в сеть, а мы смотрим только на диск.
    case "$T" in */) continue ;; esac
    if [ ! -e "$DIR/$T" ]; then
      echo "$MD: ссылка в никуда — $T"
      echo "  почини: создай файл или убери ссылку. Документ, обещающий несуществующее, хуже отсутствующего."
      MISS=1
    fi
  done
done
exit $MISS
