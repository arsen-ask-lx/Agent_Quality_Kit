#!/usr/bin/env sh
# Каждая ссылка на локальный файл из markdown-файлов каталога обязана вести на
# существующий файл. Ссылка в никуда — это документ, утверждающий защиту,
# которой нет: планирование опирается на неё и ломается молча.
DIR="${1:-.}"
MISS=0
for MD in "$DIR"/*.md; do
  [ -f "$MD" ] || continue
  # вытащить цели ссылок вида [текст](путь)
  TARGETS=$(sed -n 's/.*](\([^)]*\)).*/\1/p' "$MD")
  for T in $TARGETS; do
    # автоссылки бывают обёрнуты как <(https://...)> — искать http где угодно внутри,
    # не только в начале строки.
    case "$T" in *http://*|*https://*|\#*|mailto:*) continue ;; esac
    T=${T%%#*}
    [ -z "$T" ] && continue
    # Путь, кончающийся косой чертой, — адрес страницы опубликованного сайта, а не файл на
    # диске. Так ссылаются mkdocs, docusaurus и jekyll: `[руководство](tutorial/#install)`
    # работает у читателя и не существует в репозитории. Найдено замером по fastapi — гейт
    # объявлял битой рабочую ссылку из их README. Проверять такие адреса умеют lychee и
    # markdown-link-check: они ходят в сеть, а мы смотрим только на диск.
    case "$T" in */) continue ;; esac
    if [ ! -e "$DIR/$T" ]; then
      echo "$MD: ссылка в никуда — $T"
      echo "  почини: создай файл или убери ссылку. Документ, обещающий несуществующее, хуже отсутствующего."
      MISS=1
    fi
  done
done
exit $MISS
