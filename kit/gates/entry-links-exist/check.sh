#!/usr/bin/env sh
# Каждая ссылка на локальный файл из markdown-файлов каталога обязана вести на
# существующий файл. Ссылка в никуда — это документ, утверждающий защиту,
# которой нет: планирование опирается на неё и ломается молча.
#
# СУДИМ ТОЛЬКО ТО, ЧТО МОЖЕМ РАЗРЕШИТЬ. Решение о том, путь ли это вообще, вынесено в общий
# `_target.sh`: замеры по 290 чужим репозиториям дали двенадцать наших ложных, и все они об
# одном — строка разрешалась тем, чего у нас нет. Список исключений внутри гейта разошёлся бы
# с таким же списком в соседнем.
#
# И НЕРАЗРЕШЁННОЕ НЕ ПРЯЧЕТСЯ. Раньше такие цели молча пропускались, то есть «не смогли
# проверить» выдавалось за «чисто» — ровно то, за что мы ругаем чужие инструменты. Теперь их
# число печатается отдельной строкой, с причинами.
DIR="${1:-.}"
TARGET_LIB="$(dirname "$0")/../_target.sh"
if [ ! -f "$TARGET_LIB" ]; then
  echo "рядом с проверкой нет _target.sh — разбор путей не собран, проверка не состоялась"
  echo "  почини: скопируй гейт вместе с файлом kit/gates/_target.sh, он общий на весь каталог"
  exit 2
fi
. "$TARGET_LIB"
MISS=0
UNRES=""
for MD in "$DIR"/*.md; do
  [ -f "$MD" ] || continue
  # вытащить цели ссылок вида [текст](путь)
  # Строки со вставками в обратных кавычках чистятся ДО разбора: «`[name](url)`» — это пример
  # оформления ссылки, а не ссылка. Замер 2026-09-08: в uv/STYLE.md именно так и было, и гейт
  # требовал создать файл с именем «url».
  TARGETS=$(sed 's/`[^`]*`//g' "$MD" | sed -n 's/.*](\([^)]*\)).*/\1/p')
  for T in $TARGETS; do
    T=$(clean_target "$T")
    VERDICT=$(classify_target "$T")
    case "$VERDICT" in
      skip) continue ;;
      unresolved:*) UNRES="$UNRES${VERDICT#unresolved:}
"; continue ;;
    esac
    if [ ! -e "$DIR/$T" ]; then
      echo "$MD: ссылка в никуда — $T"
      echo "  почини: создай файл или убери ссылку. Документ, обещающий несуществующее, хуже отсутствующего."
      MISS=1
    fi
  done
done
# «Не смогли разрешить» печатается ВСЕГДА, даже когда находок нет: молчание тут означало бы, что
# мы посмотрели всё, а мы посмотрели не всё.
if [ -n "$UNRES" ]; then
  N=$(printf '%s' "$UNRES" | grep -c .)
  echo "  не проверено: $N — цели, которые мы не можем разрешить:"
  printf '%s' "$UNRES" | sort | uniq -c | sed 's/^/   /'
fi
exit $MISS
