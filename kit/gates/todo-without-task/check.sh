#!/usr/bin/env sh
# Маркер «доделать потом» — это задача, спрятанная от очереди работ. Её не видно при
# планировании, о ней не знает никто, кроме того, кто её оставил, и она переживает автора.
DIR="${1:-.}"
# Существование файла проверяется ДО `.`, а не запасной веткой после. Прежняя строка
# `. файл 2>/dev/null || запасной_вариант` выглядела страховкой и ею не была: под `sh` (dash)
# неудачный `.` завершает скрипт немедленно, и ветка после `||` не выполняется никогда; под
# `bash`, которым гейты и запускаются из манифеста, она выполняется, но подставляет только
# ПЕРЕМЕННУЮ — функции обхода остаются неопределёнными, конвейер печатает пустоту, и проверка
# выходит с НУЛЁМ. Замерено 2026-09-08 на файле с настоящим нарушением: гейт сказал «чисто».
SKIP_LIB="$(dirname "$0")/../_skip.sh"
if [ ! -f "$SKIP_LIB" ]; then
  echo "рядом с проверкой нет _skip.sh — обход не собран, проверка не состоялась"
  echo "  почини: скопируй гейт вместе с файлом kit/gates/_skip.sh, он общий на весь каталог"
  exit 2
fi
. "$SKIP_LIB"

# shellcheck disable=SC2086
# Маркер обязан стоять В КОММЕНТАРИИ. Иначе гейт краснеет на имени переменной с таким же
# названием и на собственном шаблоне поиска — на том, что дефектом не является.
# Сами эти слова здесь не пишем: гейт нашёл бы себя. Проверено — находил.
HITS=$(grep -rnE $(skip_grep "$DIR") $(include_code) \
  '(#|//|/\*|--|<!--)[^"'"'"']*(^|[^A-Za-z])(TODO|FIXME|HACK|XXX)([^A-Za-z]|$)' "$DIR" 2>/dev/null | own_samples_filter "$DIR")
if [ -n "$HITS" ]; then
  echo "$HITS"
  echo "  почини: заведи задачу в очереди работ, маркер убери."
  echo "  спрятанная в коде задача не видна при планировании и переживает автора."
  exit 1
fi
exit 0
