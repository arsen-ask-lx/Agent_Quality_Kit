#!/usr/bin/env sh
# Конфигурация конвейера не отдаёт чужому коду права и секреты.
#
# ЗАЧЕМ. Конвейер выполняется с правами репозитория и с доступом к его секретам. Три способа
# отдать их постороннему живут не в коде, а в двадцати строках yaml: триггер `pull_request_target`
# вместе с выкачиванием ветки автора PR; действие, закреплённое подвижной МЕТКОЙ, которую владелец
# действия может перевести на другой код; права `write-all`, выданные всему рабочему потоку.
# Ни одну из трёх обычная проверка кода не увидит: это не код, это настройка.
#
# Работу делает zizmor (MIT, 6459 звёзд, статический разбор GitHub Actions). Мы отвечаем за
# порог и за то, чтобы «не проверено» не выдавалось за «чисто».
#
# ПОЧЕМУ ПОРОГ ИМЕННО ТАКОЙ. Замер 2026-09-08 по шести настоящим репозиториям: express, flask и
# uv держат НОЛЬ находок высокой и средней строгости; gin (18), ripgrep (19) и httpx (4) — нет.
# Порог взят с тех, кто его держит, а не выдуман: он достижим, и это доказано чужой практикой.
# Мы сами на момент заведения записи были на неправильной стороне — 13 высоких и 5 средних.
DIR="${1:-.}"
WF="$DIR/.github/workflows"

# Нет конвейера — нечего проверять. Это не успех и не провал, это отсутствие предмета.
[ -d "$WF" ] || exit 0

if ! command -v zizmor >/dev/null 2>&1; then
  echo "не найден zizmor — эта проверка делегирована ему"
  echo "  почини: pipx install zizmor  (или uv tool install zizmor)"
  exit 2
fi

# --no-exit-codes разводит два разных события, которые иначе слиплись бы в один ненулевой код:
# «нашлись находки» и «инструмент не отработал». Первое читается из вывода, второе — из кода.
# NO_COLOR и снятие управляющих последовательностей — вместе, а не по отдельности. Внутри
# GitHub Actions zizmor КРАСИТ вывод (там цвет поддержан), и итоговая строка начинается с
# escape-последовательности: правило «^[0-9]+ findings» её не видит, и гейт объявлял, что формат
# сменился. Локально этого не воспроизвести — вне конвейера цвет выключается сам. Поймано
# прогоном в конвейере 2026-09-08; тот же класс уже записан у нас в scope.mjs: «цвет снимается ДО
# поиска». NO_COLOR — соглашение, его может не знать следующая версия; sed — страховка, которая
# в отличие от NO_COLOR ни от кого не зависит.
ESC=$(printf '\033')
OUT=$(NO_COLOR=1 zizmor --no-online-audits --no-exit-codes --min-severity medium --format plain "$WF" 2>&1 \
      | sed "s/${ESC}\[[0-9;]*[a-zA-Z]//g")
CODE=$?
if [ "$CODE" -ne 0 ]; then
  echo "zizmor не отработал (код $CODE) — проверка не состоялась, это не вердикт «чисто»"
  printf '%s\n' "$OUT" | grep -iE "error:|panic|not found" | head -3 | sed 's/^/  /'
  echo "  почини: прогони «zizmor .github/workflows» руками и посмотри, на чём он споткнулся"
  exit 2
fi

# Итоговая строка — единственное место, где сказано, сколько чего нашлось. Её отсутствие значит,
# что формат сменился; молчать об этом нельзя, иначе смена формата станет вечным зелёным.
SUM=$(printf '%s\n' "$OUT" | grep -E "^(No findings to report|[0-9]+ findings)" | tail -1)
if [ -z "$SUM" ]; then
  echo "ответ zizmor не разобран: итоговой строки в нём нет"
  # Печатаем то, что пришло на самом деле. Без этого причина видна только тому, у кого есть та
  # же машина: первый отказ этой ветки случился в конвейере, а локально не воспроизводился, и
  # разбирать пришлось догадками. Сообщение, не показывающее свой ввод, лечится вторым прогоном.
  echo "  вот последнее, что он напечатал:"
  printf '%s\n' "$OUT" | tail -3 | sed 's/^/    /'
  echo "  почини: сверь версию zizmor с той, что названа в gate.yml"
  exit 2
fi

case "$SUM" in
  "No findings to report"*) exit 0 ;;
esac

printf '%s\n' "$OUT" | grep -E "^(error|warning)\[" | head -20
N=$(printf '%s\n' "$OUT" | grep -cE "^(error|warning)\[")
[ "$N" -gt 20 ] && echo "  … и ещё $((N - 20))"
echo "  почини: закрепи действия по SHA вместо метки, сузь permissions до нужного задания,"
echo "  замени pull_request_target на pull_request там, где выполняется код автора PR."
echo "  подробности по каждой находке: https://docs.zizmor.sh/audits/"
exit 1
