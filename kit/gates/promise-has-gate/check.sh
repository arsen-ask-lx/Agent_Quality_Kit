#!/usr/bin/env sh
# Обещание в точке входа подкреплено командой с кодом возврата — или честно помечено как
# исполняемое человеком.
#
# ЗАЧЕМ. Это центральный вопрос всего комплекта. `AGENTS.md` — обычный текст: «никогда не
# коммитим секреты» и «мы очень стараемся» выглядят одинаково и стоят одинаково, пока никто не
# спросил, чем первое отличается от второго. Осенью 2026 появился целый класс линтеров обвеса
# (agnix — 455 правил, agents-lint), и все они проверяют ДОКУМЕНТ: формат, живые ли ссылки,
# существуют ли скрипты. Ни один не спрашивает, ИСПОЛНИМО ли обещание.
#
# ПОЧЕМУ ЯВНАЯ ПОМЕТКА, А НЕ УГАДЫВАНИЕ. Сопоставлять обещание с гейтом по совпадению слов —
# значит выдавать вердикт по догадке. Пометка ставится один раз и делает документ честнее:
# у каждого правила видно, кто его сторожит — машина или человек.
#
#   - **Секреты не в коде.** <!-- aqk: secrets-not-in-code -->
#   - **План до кода.**      <!-- aqk: человек -->
DIR="${1:-.}"
MAN="$DIR/.aqk.yml"
[ -f "$MAN" ] || { echo "нет .aqk.yml — проверять нечего"; exit 0; }
MANTEXT="$(tr -d '\r' < "$MAN")"

ENTRIES=$(printf '%s\n' "$MANTEXT" | awk '
  /^entry:/ { if ($0 ~ /\[/) { s=$0; sub(/^entry:[[:space:]]*\[/,"",s); sub(/\].*$/,"",s);
                gsub(/[[:space:]]/,"",s); n=split(s,a,","); for(i=1;i<=n;i++) print a[i]; next }
              g=1; next }
  /^[A-Za-z]/ { g=0 }
  g && /^[[:space:]]*-[[:space:]]/ { s=$0; sub(/^[[:space:]]*-[[:space:]]*/,"",s);
                gsub(/^["\x27]|["\x27]$/,"",s); print s }')
[ -z "$ENTRIES" ] && { echo "точка входа не объявлена — проверять нечего"; exit 0; }

# Объявленные гейты: их имена и есть словарь допустимых пометок.
GATES=$(printf '%s\n' "$MANTEXT" | awk '/^gates:/{g=1;next} /^[A-Za-z]/{g=0}
  g && /^[[:space:]]+[A-Za-z0-9_-]+:/ { sub(/^[[:space:]]*/,""); sub(/:.*$/,""); print }')

OUT=""
for E in $ENTRIES; do
  F="$DIR/$E"
  [ -f "$F" ] || continue
  R=$(tr -d '\r' < "$F" | awk -v file="$E" -v gates="$GATES" '
    # Внутри блока кода правил не бывает — там примеры.
    /^[[:space:]]*```/ { code = !code; next }
    code { next }
    {
      # Обещание — пункт списка, который либо выделен жирным (обычная форма правила), либо
      # содержит слово долженствования или запрета. Пункт-перечисление файлов обещанием не
      # считается: он ничего не утверждает о поведении.
      # Только маркированный пункт. Нумерованный список — это шаги или пояснения, а не свод
      # правил: «три вещи, которые надо понимать» в нашем же шаблоне выглядели обещаниями и
      # требовали сторожа для утверждения о том, как устроен инструмент.
      if ($0 !~ /^[[:space:]]*[-*][[:space:]]+/) next
      body = $0; sub(/^[[:space:]]*[-*][[:space:]]+/, "", body)
      isRule = (body ~ /^\*\*/) ||
               (body ~ /никогда|всегда|обязан|обязательн|запрещ|нельзя|не должн|каждый|каждая|каждое/) ||
               (body ~ /(^|[^a-z])(must|never|always|required|forbidden|shall)([^a-z]|$)/)
      # Пункт-команда — не обещание. «обязательный минимум проекта прогоном: `aqk doctor`»
      # содержит слово долженствования, но ничего не обещает: это строка справочника.
      if (body ~ /`(node|bash|sh|npx|npm|aqk|make|python|go|cargo) /) next
      if (!isRule) next

      # Пометка: <!-- aqk: имя-гейта --> или <!-- aqk: человек -->
      # Берём всё до закрывающей скобки комментария и уже потом обрезаем. Класс символов
      # с исключением «-» съедал имя гейта на первом же дефисе: «deps-are-pinned» читалось
      # как «deps», и верная пометка объявлялась ведущей в никуда.
      if (match($0, /<!--[[:space:]]*aqk:[^>]*-->/)) {
        tag = substr($0, RSTART, RLENGTH)
        sub(/^<!--[[:space:]]*aqk:[[:space:]]*/, "", tag)
        sub(/[[:space:]]*-->$/, "", tag)
        sub(/[[:space:]]+$/, "", tag)
        if (tag == "человек" || tag == "human") next
        n = split(gates, G, "\n")
        for (i = 1; i <= n; i++) if (G[i] != "" && G[i] == tag) next
        printf "%s:%d: пометка ведёт в никуда — гейта «%s» нет в манифесте\n", file, FNR, tag
        next
      }
      t = body; sub(/[[:space:]]+$/, "", t)
      printf "%s:%d: обещание ничем не подкреплено: %s\n", file, FNR, substr(t, 1, 90)
    }' 2>/dev/null)
  [ -z "$R" ] || OUT="$OUT$R
"
done

LEFT="$(printf '%s' "$OUT" | grep -v '^$')"
[ -z "$LEFT" ] && exit 0
printf '%s\n' "$LEFT"
echo "  почини: у каждого правила должен быть виден сторож."
echo "  машина: <!-- aqk: имя-гейта -->    человек: <!-- aqk: человек -->"
echo "  правило, за которым не следит никто, через месяц отличается от лозунга только длиной."
exit 1
