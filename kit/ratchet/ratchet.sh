#!/usr/bin/env bash
# Храповик: обёртка вокруг гейта, которая пускает СТАРЫЕ нарушения и не пускает новые.
#
# ЗАЧЕМ. Правило вводят в проект, где старый код ему не соответствует. Вариантов три, и два
# из них не работают. Большая чистка откладывается навсегда, потому что она большая.
# Необязательное предупреждение не блокирует ничего — его листают, и правило не действует.
# Храповик даёт действующее правило СО ДНЯ УСТАНОВКИ, не требуя трогать старый код.
#
# ПРОВЕРКА, ЧТО ЭТО ХРАПОВИК, А НЕ СОВЕТЧИК: «может ли новый код добавить нарушение и пройти?»
# Может — значит гейта нет.
#
#   bash ratchet.sh <реестр> <команда гейта...>

set -uo pipefail
REG="${1:-}"; shift || true
[ -z "$REG" ] || [ $# -eq 0 ] && { echo "нужно: ratchet.sh <реестр> <команда...>"; exit 2; }

# Ключ нарушения обязан переживать правку соседних строк, иначе сдвиг на строку читается
# как новое нарушение. Поэтому номер строки из ключа убирается.
#
# Два шаблона, а не один: у гейта duplicate-code строка несёт ДВА места — «a:171 и b:188: …»,
# и за номером первого идёт не двоеточие, а пробел. Шаблон с двоеточием убирал номер только
# у второго файла пары, и сдвиг кода в первом читался как новое нарушение — ровно то, от чего
# храповик защищает.
keys() { grep -E '^[^[:space:]].*:' | sed -E 's/:[0-9]+:/:/g; s/:[0-9]+( |$)/:\1/g' | LC_ALL=C sort -u; }

# ЦЕЛЬ И СРОК. Реестр долга, который может только сокращаться, всё равно не знает, когда он
# кончится, — и потому не кончается. У betterer у каждого долга есть `goal` (значение, при
# котором он закрыт) и `deadline`. Берём обе идеи, но с машинным последствием: срок, который
# ничего не делает, — это украшение, а не срок.
#
#   # aqk-goal: 0            долг считается погашенным, когда осталось не больше стольких
#   # aqk-deadline: 2026-12-31   после этой даты непогашенный долг красит гейт
#
# Строки живут в шапке реестра и переживают затягивание: шапка переписывается целиком.
directive() { sed -n "s/^[[:space:]]*#[[:space:]]*$1:[[:space:]]*\([^[:space:]]*\).*/\1/p" "$REG" | head -1; }

OUT="$("$@" 2>&1)"
NOW="$(printf '%s\n' "$OUT" | keys)"

if [ ! -f "$REG" ]; then
  echo "нет реестра $REG — сначала: aqk ratchet <гейт>"
  exit 2
fi
# Та же сортировка, что в keys(): comm сравнивает построчно и требует, чтобы оба входа были
# упорядочены одинаково. Разная локаль у двух сторон — это тихо разъехавшееся сравнение.
WAS="$(grep -vE '^\s*(#|$)' "$REG" | LC_ALL=C sort -u)"

NEW="$(comm -23 <(printf '%s\n' "$NOW") <(printf '%s\n' "$WAS"))"
GONE="$(comm -13 <(printf '%s\n' "$NOW") <(printf '%s\n' "$WAS"))"

# Исправленное вычёркивается сразу: иначе однажды исправленное нарушение остаётся
# разрешённым навсегда, и храповик перестаёт затягиваться.
if [ -n "$GONE" ]; then
  COUNT=$(printf '%s\n' "$GONE" | grep -c .)
  HEAD="$(grep -E '^[[:space:]]*#' "$REG" || true)"

  # Сначала пишем, потом сообщаем. Обратный порядок однажды напечатал «храповик затянут»,
  # не переписав файл: список стал пустым, grep вернул единицу и отменил запись по &&.
  #
  # В реестр идёт ПЕРЕСЕЧЕНИЕ старого списка с текущим, а не текущий список целиком. Разница
  # решает: записывая текущий, храповик вместе с исправленными вычёркиваниями молча вносил в
  # долг и НОВЫЕ нарушения — один красный прогон, дальше зелено навсегда. Ответ на главный
  # вопрос «может ли новый код добавить нарушение и пройти?» был «да, если заодно что-то
  # починить». Найдено разделением программы: правки переехали в другие файлы.
  { [ -n "$HEAD" ] && printf '%s\n' "$HEAD"
    comm -12 <(printf '%s\n' "$NOW") <(printf '%s\n' "$WAS") | grep -v '^[[:space:]]*$' || true
  } > "$REG.tmp"
  mv "$REG.tmp" "$REG"
  echo "храповик затянут: исправлено $COUNT, вычеркнуто из реестра"
fi

if [ -n "$NEW" ]; then
  echo "новых нарушений: $(printf '%s\n' "$NEW" | grep -c .)"
  printf '%s\n' "$NEW" | sed 's/^/  /'
  echo "  почини их: реестр долга разрешается только укорачивать."
  echo "  старые нарушения из $REG пропущены — они долг, а не разрешение."
  exit 1
fi

# Сколько долга осталось ПОСЛЕ затягивания — считаем по файлу, а не по памяти: выше он мог
# быть переписан, и число из переменной врало бы ровно в тот прогон, когда что-то починили.
LEFT_COUNT=$(grep -vcE '^[[:space:]]*(#|$)' "$REG" || true)
GOAL="$(directive 'aqk-goal')"
DEADLINE="$(directive 'aqk-deadline')"

# Цель достигнута — долг кончился. Молчать здесь нельзя: реестр, который никто не убирает,
# остаётся в проекте навсегда и продолжает пропускать нарушения, которых уже нет.
if [ -n "$GOAL" ] && [ "$LEFT_COUNT" -le "$GOAL" ] 2>/dev/null; then
  echo "  почини: долг погашен — осталось $LEFT_COUNT при цели $GOAL."
  echo "  убери обёртку храповика из .aqk.yml и удали $REG: гейт станет обычным."
  exit 0
fi

# Срок вышел. Красим, даже если новых нарушений нет: в этом и весь смысл срока. Сравнение
# строк даты работает без вычислений — формат ГГГГ-ММ-ДД упорядочен лексикографически.
if [ -n "$DEADLINE" ]; then
  TODAY="$(date +%Y-%m-%d)"
  if [ "$TODAY" \> "$DEADLINE" ]; then
    echo "срок долга вышел: $DEADLINE, осталось нарушений $LEFT_COUNT"
    echo "  почини: погаси остаток либо перенеси срок в шапке $REG — но перенос виден в дифе."
    echo "  срок, который можно молча пропустить, — это не срок, а пожелание."
    exit 1
  fi
fi
exit 0
