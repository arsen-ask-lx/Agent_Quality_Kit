// tool/lib/history.mjs — что в ЭТОМ репозитории ломается на самом деле.
//
// ЗАЧЕМ. `doctor` говорит «держит машина 21». Двадцать один из чего? Знаменателя нет: 21 —
// это то, что мы успели написать в каталог, а не то, что важно в конкретном проекте. Каталог
// у нас — наш вкус; история проекта — его факты.
//
// Замер 2026-09-09 на самом комплекте: 45 коммитов-починок из 181, и рейтинг однозначный —
// `tool/selfcheck/smoke.sh` чинили 22 раза, `tool/lib/manifest.mjs` — 5. Это те места, где
// брак возвращается; там и стоит спрашивать, смотрит ли на них хоть одна проверка.
//
// ЧТО ЭТО НЕ ЗНАЧИТ. Часто чинят и то, что часто меняют: рейтинг говорит «сюда возвращаются»,
// а не «здесь плохо». Ответ на «прикрыто ли» даёт не он, а проба — см. probeVerdict.

// Признак починки берётся из ТЕМЫ коммита. Тема — единственное, что пишут все, и единственное,
// что видно в `git log --oneline`.
//
// Три написания, потому что репозитории бывают на двух языках и с conventional commits. Якорь
// на начало обязателен: без него «feat: prefix для путей» попадает в рейтинг из-за подстроки
// «fix», и рейтинг перестаёт что-либо значить.
const FIX_RE = /^\s*(fix|fixes|fixed|bugfix|hotfix|исправ|почин)/i;

function isFix(subject) {
  return FIX_RE.test(String(subject || ""));
}

// Разбор вывода `git log --format=%s --name-only`. Формат снят с живого репозитория, а не
// придуман: ТЕМА, затем ПУСТАЯ строка, затем пути — и сразу следующая тема, без пустой строки
// перед ней.
//
//   fix: разбор манифеста
//   <пусто>
//   tool/lib/manifest.mjs
//   feat: новая запись
//   <пусто>
//   kit/gates/x/check.sh
//
// Отсюда единственный надёжный признак темы: за ней идёт пустая строка. По позиции её не
// отличить — после последнего пути соседнего коммита тема начинается без разделителя.
// Первая версия разбирала по выдуманному формату («пустая строка ПОСЛЕ файлов») и нашла ноль
// починок там, где их сорок пять: ошибка молчала, потому что пустой рейтинг выглядит как
// «история чистая». Тот же класс, что дважды поймал меня в тот же день.
//
// `isCode` передаётся вызывающим, а не берётся отсюда: набор расширений кода живёт в
// evidence.mjs, и второй его список через месяц разошёлся бы с первым.
function fixHotspots(raw, { isCode }) {
  const counts = new Map();
  const lines = String(raw || "").split("\n");
  let inFix = false;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line === "") continue;
    if (lines[i + 1] === "") { inFix = isFix(line); continue; }
    if (!inFix) continue;
    const p = line.trim();
    if (!p || !isCode(p)) continue;
    counts.set(p, (counts.get(p) || 0) + 1);
  }

  return [...counts.entries()]
    .map(([path, fixes]) => ({ path, fixes }))
    // При равном числе починок — по алфавиту: вывод обязан быть одинаковым между прогонами,
    // иначе его нельзя сравнить с прошлым и нельзя проверить машиной.
    .sort((a, b) => b.fixes - a.fixes || a.path.localeCompare(b.path));
}

// Вердикт пробы по кодам возврата объявленных гейтов. ТРИ состояния, и сливать их нельзя.
//
// `2` у наших записей означает «проверка не состоялась» — делегированной программы нет на
// машине. Засчитать это как «прикрыто» значило бы выдать отсутствие сигнала за успех: тот
// самый отказ, против которого написан весь комплект. Засчитать как «не прикрыто» — тоже
// неправда: мы не знаем.
//
// Поймавший гейт сильнее непроверенного: класс закрыт, даже если рядом чего-то не хватает.
function probeVerdict(results) {
  if (results.some((r) => r.code === 1)) return "caught";
  if (results.length === 0) return "unknown";
  if (results.some((r) => r.code !== 0)) return "unknown";
  return "blind";
}

// Итог пробы по всем её исходам. Отдельная функция, а не тернарник на месте: исходов у
// `probeVerdict` три, и пока веток было две, `unknown` молча падал в «поймано всё».
//
// Замер 2026-09-10 на проекте с чужими командами: единственная запись вернула «нечем
// проверить — инструмент делегирован и не установлен», а итог сказал «каждый применимый
// класс кем-то ловится». Ошибка запуска, выданная за чистоту, — то самое, ради чего
// написан стандарт, в его собственной главной команде.
//
// Сочетания названы исчерпывающе. `partial` существует потому, что «поймано три, проверить
// две не смогли» и «поймано три» — разные факты, и сливать их значит округлять в свою пользу.
// `unprobed` — горячие файлы, которым проба не делалась ВОВСЕ: красного образца их расширения
// в каталоге нет. Прогон на самом комплекте 2026-09-10: два `.mjs` из пяти горячих файлов не
// пробовались никак, а итог говорил «каждый применимый класс кем-то ловится». Оговорка «в
// пробованных местах» верна буквально и обманывает по смыслу — она молча сужает утверждение до
// мест, где проба удалась. Поэтому «чисто» отвечается только при нуле пропущенных.
function probeSummary({ caught = 0, blind = 0, unknown = 0, unprobed = 0 } = {}) {
  if (blind) return "blind";
  if (caught && (unknown || unprobed)) return "partial";
  if (caught) return "clean";
  if (unknown) return "nothing-ran";
  return "nothing-probed";
}

export { isFix, fixHotspots, probeVerdict, probeSummary };
