// tool/lib/ask.mjs — КОГДА КОМПЛЕКТ ОБРАЩАЕТСЯ К ЧЕЛОВЕКУ, и как он помнит, что уже обращался.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Знание «мы это показывали» жило в комплекте дважды и по-разному:
//   · `~/.config/aqk/feedback-shown` — файл-флаг, раз на машину: заведён в `core.mjs`,
//     прочитан в `project.mjs`;
//   · `.aqk/advice-shown`, `.aqk/update-checked` — отметка временем плюс `adviceDue()` на
//     сутки: заведены и прочитаны в `brief.mjs`.
// Одно решение — «не долби человека» — в двух местах и в двух форматах. Третье обращение
// завело бы третий формат, и дальше они расходятся молча.
//
// ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ. Здесь только ОГРАНИЧИТЕЛЬ: можно ли сейчас обратиться и чем это
// запомнить. Чего здесь нет — текста обращения и решения, есть ли о чём говорить: текст живёт
// в каталогах строк, решение — у того, кто знает состояние проекта. Иначе модуль про «когда»
// начал бы меняться вместе с каждой правкой формулировки.
//
// ЛИСТ ДЕРЕВА: импортируются только встроенные модули Node. Каталоги передаются вызывающим, а
// не берутся из `core.mjs`, — иначе получилось бы кольцо: `core.mjs` берёт отсюда список
// служебных файлов для `.gitignore`.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";

const DAY = 24 * 60 * 60 * 1000;

// ТАБЛИЦА ВИДОВ. Вид объявляет две вещи, и обе нельзя угадать по имени:
//   where — «project» (отметка про ЭТОТ репозиторий, лежит в его служебном каталоге) или
//           «home» (отметка про ЭТУ МАШИНУ, лежит в доме пользователя);
//   every — через сколько можно повторить; `null` означает «никогда», а не «очень нескоро».
//
// Имена файлов — прежние, до единой буквы: человек, у которого отметка уже лежит, не должен
// получить обращение заново только потому, что мы переставили код.
const ASKS = {
  // Совет про непоставленную запись каталога — в короткой строке хука.
  advice: { where: "project", file: "advice-shown", every: DAY },
  // Проверка свежести версии — единственный исходящий запрос комплекта.
  update: { where: "project", file: "update-checked", every: DAY },
  // Просьба об отзыве после установки — раз на машину: второй `init` в другом репозитории на
  // том же компьютере её не повторяет.
  install: { where: "home", file: "feedback-shown", every: null },
  // Просьба об отзыве ПО ДЕЛУ — раз на проект. Объявлена здесь до первого использования
  // намеренно: строка в `.gitignore` обязана появиться РАНЬШЕ, чем файл будет записан, иначе
  // отметка уедет в чужой коммит у всех, кто поставил комплект между двумя выпусками.
  value: { where: "project", file: "feedback-asked", every: null },
};

// Опечатка в виде обращения обязана падать. Оба молчаливых умолчания неверны в половине
// случаев: «показывать всегда» превращает ограничитель в шум, «не показывать» — выключает
// обращение навсегда, и никто об этом не узнает.
function askKind(kind) {
  const a = ASKS[kind];
  if (!a) throw new Error(`неизвестный вид обращения: ${kind}. Известны: ${Object.keys(ASKS).join(", ")}`);
  return a;
}

// Служебные файлы ЭТОГО проекта — для `.gitignore`. Домашние сюда не идут: их git не видит.
const ASK_FILES = Object.values(ASKS).filter((a) => a.where === "project").map((a) => a.file);

// `project` — служебный каталог репозитория (тот самый `.aqk`), `home` — дом пользователя.
// Каталог передаётся целиком, а не собирается здесь: имя `.aqk` знает `core.mjs`, и второй
// его экземпляр однажды разошёлся бы с первым.
function askFile(kind, { project, home } = {}) {
  const a = askKind(kind);
  return a.where === "home" ? join(String(home ?? ""), ".config", "aqk", a.file) : join(String(project ?? ""), a.file);
}

// Пора ли обращаться. `stamp` — содержимое отметки или null, если её нет.
//
// Разовое обращение: отметка есть — значит было, и повторить нельзя никогда, что бы в ней ни
// лежало. Старый формат хранил слово «shown», а не дату: читать его как испорченную дату и
// показывать заново значило бы повторить просьбу у всех, кто поставил комплект раньше.
//
// Суточное: «не знаем, когда показывали» и «показывали давно» — одно и то же решение, показать.
// Молчать из-за нечитаемого файла состояния значит потерять обращение навсегда и не сказать
// почему.
function askDue(kind, stamp, now = Date.now()) {
  const a = askKind(kind);
  if (stamp === null || stamp === undefined || String(stamp).trim() === "") return true;
  if (a.every === null) return false;
  const t = Date.parse(String(stamp).trim());
  if (!Number.isFinite(t)) return true;
  return now - t >= a.every;
}

// Отметка с диска: строка или null. Файла нет, каталог не читается, прав не хватило — всё это
// «не показывали»: потерять обращение из-за нечитаемой отметки дешевле, чем молчать.
async function readStamp(kind, dirs) {
  try {
    return (await readFile(askFile(kind, dirs), "utf8")).trim();
  } catch {
    return null;
  }
}

// Запомнить обращение. Возвращает true, если записали, — СЛОВО О НЕУДАЧЕ ГОВОРИТ ВЫЗЫВАЮЩИЙ:
// у совета повтор это мелочь, а у разовой просьбы — та же просьба завтра, и человеку надо
// сказать, почему она вернулась. Дом бывает недоступен для записи: в контейнере, запущенном
// `--user 1001:127`, у этого uid нет записи в /etc/passwd, `homedir()` даёт «/», и запись
// падает на `/.config`. До 2026-09-09 это роняло весь `init` — то есть любого, кто набрал
// команду из нашей же документации по docker.
async function markAsked(kind, dirs, now = new Date()) {
  const path = askFile(kind, dirs);
  try {
    await mkdir(join(path, ".."), { recursive: true });
    await writeFile(path, `${now.toISOString()}\n`, "utf8");
    return true;
  } catch {
    return false;
  }
}

// Пора ли обращаться, с чтением отметки. Две трети вызывающих хотят именно этого; чистый
// `askDue` остаётся для перебора случаев, которых на диске не бывает.
async function askAllowed(kind, dirs, now = Date.now()) {
  return askDue(kind, await readStamp(kind, dirs), now);
}

// Наружу — то, что зовут снаружи. `readStamp` внутренний: снаружи спрашивают «пора ли»,
// а не «что лежит в файле», и лишний экспорт читается как часть договора.
export { ASKS, ASK_FILES, askDue, askFile, markAsked, askAllowed };
