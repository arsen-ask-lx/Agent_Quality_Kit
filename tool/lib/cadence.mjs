// tool/lib/cadence.mjs — когда комплект делает работу САМ, не дожидаясь, что о ней вспомнят.
//
// ЗАЧЕМ. Владелец сформулировал точнее, чем было в замысле: «команду, о которой надо вспомнить,
// агент не вспомнит, а человек о ней не узнает». Это тот же класс, что файл, который можно не
// прочитать, — и весь комплект написан против него. Команда `probe`, которую надо запускать
// руками, наполовину бесполезна по построению: она отвечает на важнейший вопрос («что здесь не
// прикрыто ничем») и не задаётся никем.
//
// РЕШЕНИЕ ТО ЖЕ, ЧТО У СОВЕТА И ПРОВЕРКИ ВЕРСИИ: не напоминать, а делать. Разница в единице.
// Совет считает сутки — он про внимание человека. Проба считает КОММИТЫ: репозиторий, в котором
// месяц не работали, перепроверять незачем, а сто коммитов за день перепроверить надо. Время
// здесь не при чём, при чём — сколько кода написано с прошлого раза.
//
// ПОЧЕМУ СТО. Число выбрано так, чтобы проба не мешала: на нашем репозитории это примерно
// две недели работы, а сама проба идёт секунды. Порог виден в выводе и меняется числом, а не
// прячется: правило, которого не видно, через месяц читается как случайность.
const PROBE_EVERY = 100;

// `last` — то, что записала прошлая проба: { at: <число коммитов на тот момент> }.
// `now` — сколько коммитов в репозитории сейчас; null, если счётчик взять не удалось.
//
// Пробы не было ВОВСЕ — она нужна, и нужна сразу, а не на сто первом коммите: молодой проект
// узнал бы о своих дырах позже всех, хотя закрывать их дешевле всего именно в начале.
function probeDue(last, now, every = PROBE_EVERY) {
  if (now === null || now === undefined) return false;
  const at = Number(last?.at);
  if (!Number.isFinite(at)) return true;
  return now - at >= every;
}

// Состояние для человека и для агента. ЧЕТЫРЕ исхода, и сливать их нельзя — по той же причине,
// по которой их четыре у `vitals`: «не делалась» и «свежая» различаются тем, что в первом
// случае мы ничего не знаем, а молчание читается как «всё хорошо».
function probeState(last, now, every = PROBE_EVERY) {
  if (now === null || now === undefined) return { state: "unknown", behind: null };
  const at = Number(last?.at);
  if (!Number.isFinite(at)) return { state: "never", behind: null };
  const behind = now - at;
  return { state: behind >= every ? "stale" : "fresh", behind };
}

// Порог из манифеста: `probe: 250` — раз в двести пятьдесят коммитов, `probe: 0` — не делать
// вовсе. Число выбирается проектом, а не нами: сто коммитов на репозитории с десятком коммитов
// в час — это трижды в день, а на редком проекте они не наберутся никогда.
//
// Неразобранное значение НЕ молчит: строка `probe: часто` означала бы «человек настроил», а
// работал бы умолчательный порог — расхождение между написанным и происходящим, то самое,
// против чего весь комплект. Возвращается null, и вызывающий говорит об этом вслух.
function probeEvery(man) {
  const raw = man?.probe;
  if (raw === undefined || raw === null || String(raw).trim() === "") return PROBE_EVERY;
  const n = Number(String(raw).trim());
  if (!Number.isFinite(n) || n < 0) return null;
  return n;
}

export { probeDue, probeState, probeEvery, PROBE_EVERY };
