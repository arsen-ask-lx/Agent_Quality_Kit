// tool/lib/cadence.mjs — когда комплект делает работу САМ, не дожидаясь, что о ней вспомнят.
//
// ЗАЧЕМ. Владелец сформулировал точнее, чем было в замысле: «команду, о которой надо вспомнить,
// агент не вспомнит, а человек о ней не узнает». Это тот же класс, что файл, который можно не
// прочитать, — и весь комплект написан против него. Команда `probe`, которую надо запускать
// руками, наполовину бесполезна по построению: она отвечает на важнейший вопрос («что здесь не
// прикрыто ничем») и не задаётся никем.
//
// РЕШЕНИЕ ТО ЖЕ, ЧТО У СОВЕТА И ПРОВЕРКИ ВЕРСИИ: не напоминать, а делать. Разница в единице.
// Совет считает сутки — он про внимание человека. Проба считает КОММИТЫ: репозиторий, в котором
// месяц не работали, перепроверять незачем, а сто коммитов за день перепроверить надо. Время
// здесь не при чём, при чём — сколько кода написано с прошлого раза.
//
// ПОЧЕМУ СТО. Число выбрано так, чтобы проба не мешала: на нашем репозитории это примерно
// две недели работы, а сама проба идёт секунды. Порог виден в выводе и меняется числом, а не
// прячется: правило, которого не видно, через месяц читается как случайность.
const PROBE_EVERY = 100;

// `last` — то, что записала прошлая проба: { at: <число коммитов на тот момент> }.
// `now` — сколько коммитов в репозитории сейчас; null, если счётчик взять не удалось.
//
// Пробы не было ВОВСЕ — она нужна, и нужна сразу, а не на сто первом коммите: молодой проект
// узнал бы о своих дырах позже всех, хотя закрывать их дешевле всего именно в начале.
function probeDue(last, now, every = PROBE_EVERY) {
  if (now === null || now === undefined) return false;
  const at = Number(last?.at);
  if (!Number.isFinite(at)) return true;
  return now - at >= every;
}

// Состояние для человека и для агента. ЧЕТЫРЕ исхода, и сливать их нельзя — по той же причине,
// по которой их четыре у `vitals`: «не делалась» и «свежая» различаются тем, что в первом
// случае мы ничего не знаем, а молчание читается как «всё хорошо».
function probeState(last, now, every = PROBE_EVERY) {
  if (now === null || now === undefined) return { state: "unknown", behind: null };
  const at = Number(last?.at);
  if (!Number.isFinite(at)) return { state: "never", behind: null };
  const behind = now - at;
  return { state: behind >= every ? "stale" : "fresh", behind };
}

// Порог из манифеста: `probe: 250` — раз в двести пятьдесят коммитов, `probe: 0` — не делать
// вовсе. Число выбирается проектом, а не нами: сто коммитов на репозитории с десятком коммитов
// в час — это трижды в день, а на редком проекте они не наберутся никогда.
//
// Неразобранное значение НЕ молчит: строка `probe: часто` означала бы «человек настроил», а
// работал бы умолчательный порог — расхождение между написанным и происходящим, то самое,
// против чего весь комплект. Возвращается null, и вызывающий говорит об этом вслух.
function probeEvery(man) {
  const raw = man?.probe;
  if (raw === undefined || raw === null || String(raw).trim() === "") return PROBE_EVERY;
  const n = Number(String(raw).trim());
  if (!Number.isFinite(n) || n < 0) return null;
  return n;
}

// ИМЕНА непойманных классов в отметке. Хранилось одно число, `blind: 1`: агент в `context`
// видел «один класс», человек в `doctor` не видел ничего, и чтобы узнать КАКОЙ, надо было снова
// запускать пробу — ту самую команду, о которой не вспоминают. Находка, которую не показали,
// ни от чего не предостерегает.
//
// Правило то же, что у `countProbe`: класс, слепой хоть где-то, — непокрыт, а «не смогли
// проверить» слепотой не считается. Файл — первый, где слеп: пробы идут от самого горячего.
function blindLines(records) {
  const seen = new Set();
  const out = [];
  for (const { entry, file, verdict } of records || []) {
    if (verdict !== "blind" || seen.has(entry)) continue;
    seen.add(entry);
    out.push(`blind-class: ${entry} ${file}`);
  }
  return out;
}

// Отметка старого формата строк `blind-class:` не несёт — тогда список пуст, и это «имён не
// знаем», а не «слепых нет»: число `blind:` читается отдельно и остаётся правдой.
function parseBlind(text) {
  return [...String(text || "").matchAll(/^blind-class:\s*(\S+)\s+(.+?)\s*$/gm)]
    .map((m) => ({ slug: m[1], file: m[2] }));
}

// Какие гейты проба ПРОГОНЯЛА. Без этого «объявлен сейчас» читалось как «поставлен после
// пробы» — а проба как раз и гоняет объявленные: гейт, стоявший ДО неё и брак пропустивший,
// получал утешительное «поймает ли, покажет следующая» вместо «здесь не ловит». Именно
// прогонявшиеся, а не объявленные: медленные проба пропускает, и про них «не поймал» — ложь.
// Старая отметка строки не несёт — null: «не знаем», а не «ничего не прогонялось».
function parseRan(text) {
  const m = /^ran:[ \t]*(.*)$/m.exec(String(text || ""));
  return m ? new Set(m[1].split(/\s+/).filter(Boolean)) : null;
}

// Запускаться ли пробе САМОЙ внутри `doctor --run`. Не в конвейере: там это +2–3 минуты сюрпризом
// в случайном прогоне (отзыв с живого проекта 2026-09-11), и место пробы — отдельная задача. Не в
// коротком режиме: там хук на воротах коммита. `AQK_PROBE=0` — выключить, `AQK_PROBE=1` — включить
// и в конвейере.
function autoProbeAllowed({ brief = false, env = process.env } = {}) {
  if (env.AQK_PROBE === "0" || brief) return false;
  if (env.AQK_PROBE === "1") return true;
  return !(env.CI || env.GITHUB_ACTIONS || env.GITLAB_CI || env.BUILDKITE || env.JENKINS_URL);
}

// Сколько классов проба поймала и у скольких поимка не доказана. Старая отметка чисел не несёт —
// null: «не знаем», а не «ноль пойманных».
function parseCounts(text) {
  const caught = /^caught:[ \t]*(\d+)/m.exec(String(text || ""));
  const unknown = /^unknown:[ \t]*(\d+)/m.exec(String(text || ""));
  return caught && unknown ? { caught: Number(caught[1]), unknown: Number(unknown[1]) } : null;
}

// Чего уровень НЕ доказывает — строкой под ним. Отзыв с живого проекта 2026-09-11: «AQK-3, All
// levels reached» при конвейере, который ни разу не запускался. Ступени меряют оснащённость:
// гейты показаны на образцах КАТАЛОГА. Ловят ли они брак в файлах ПРОЕКТА, знает только проба —
// и строка говорит ровно то, что знает она. Непойманное идёт первым, даже если пойманного
// больше: «четыре из пяти» глаз читает как «всё хорошо».
//
// Планку ступеней не подняли намеренно: отметка пробы лежит в .gitignore, в конвейере её нет, и
// «AQK-2 только после пробы» уронило бы уровень и `badge --check` у всех разом.
function levelLimits(st) {
  if (st?.state === "off") return { kind: "off" };
  const behind = Number.isFinite(st?.behind) ? st.behind : null;
  if (st?.classes?.length) return { kind: "blind", names: st.classes.map((x) => x.slug), behind };
  if (st?.counts) {
    const { caught, unknown } = st.counts;
    if (unknown > 0) return { kind: "partial", caught, unknown, behind };
    return caught > 0 ? { kind: "caught", caught, behind } : { kind: "nothing", behind };
  }
  if (st?.ran) return { kind: "old", behind };
  return { kind: "never" };
}

export { probeDue, probeState, probeEvery, PROBE_EVERY, blindLines, parseBlind, parseRan, autoProbeAllowed, parseCounts, levelLimits };
