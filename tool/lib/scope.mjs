// tool/lib/scope.mjs — разбор вывода гейта: сужение до дифа и отделение совета от находок.
//
// ЗАЧЕМ. Первый прогон в живом проекте показывает долг, накопленный годами: на репозитории в
// 36 тысяч файлов это тысячи находок. Человек видит стену красного, понимает, что разобрать её
// нельзя, и выключает проверку целиком. Это причина номер один, по которой такие инструменты
// снимают, — и три независимых проекта из нашего разбора умеют показывать только внесённое
// (reviewdog, `--since` у ratchets, четыре режима шума у react-doctor).
//
// ПОЧЕМУ ФИЛЬТР ВЫВОДА, А НЕ СПИСОК ФАЙЛОВ ГЕЙТУ. Гейт — произвольная команда оболочки: у
// каждого инструмента свой способ принять список файлов, а у переносимых проверок его нет
// вовсе. Фильтр вывода работает с любым гейтом, ничего не требуя от записи каталога.
//
// ЧЕГО ЭТОТ ФИЛЬТР НЕ УМЕЕТ И НЕ ДЕЛАЕТ ВИД, ЧТО УМЕЕТ. Он сужает до ФАЙЛА, а не до строки.
// Находка в файле, который диф трогал, показывается целиком, даже если она в нетронутой строке.
// Сужение до строки требует разбора формата каждого инструмента — то есть ровно той привязки
// к инструменту, которой у нас нет.

import { spawnSync } from "node:child_process";

// Один и тот же файл приезжает в трёх видах: `src/a.py`, `./src/a.py` и `src\a.py` на Windows.
function normPath(p) {
  return String(p).replace(/\\/g, "/").replace(/^\.\//, "").replace(/^\/+/, "");
}

// Цвет снимается ДО поиска путей. Родные инструменты печатают путь внутри
// escape-последовательности, и сравнение видит не «src/a.py», а обрывок с управляющими
// символами. На живом проекте это уже стоило одной починки, которая выглядела работающей:
// вывод «сократился» с 5597 строк до 5505, то есть не сократился.
const ANSI = new RegExp(String.fromCharCode(27) + "\\[[0-9;]*[a-zA-Z]", "g");

// Кандидат в путь: слово с расширением, начинающимся с БУКВЫ. Требование буквы отсекает номера
// версий — «0.5.0» иначе читается как файл с расширением «0», и строка итога про версию
// принималась бы за находку и отбрасывалась.
const CANDIDATE = /[\w.@+-]+(?:\/[\w.@+-]+)*\.[A-Za-z][A-Za-z0-9]{0,9}/g;

// Все пути, названные в тексте. Тот же разбор, что при сужении: цвет снимается, вид пути
// нормализуется. Вынесено отдельно, потому что покрытие спрашивает у вывода обратное:
// не «попадает ли находка в диф», а «назвал ли гейт этот файл».
function pathsIn(text) {
  const out = new Set();
  for (const m of String(text).replace(ANSI, "").matchAll(CANDIDATE)) out.add(normPath(m[0]));
  return out;
}

function inScope(candidate, files) {
  const c = normPath(candidate);
  if (files.has(c)) return true;
  // Совпадение по хвосту в обе стороны: инструмент печатает то абсолютный путь, то голое имя
  // файла. Здесь лучше ошибиться в сторону «показать»: спрятанная находка — это тишина,
  // а лишняя показанная — просто шум, который человек отметает глазами.
  for (const f of files) {
    if (c.endsWith(`/${f}`) || f.endsWith(`/${c}`)) return true;
  }
  return false;
}

// Возвращает: что осталось показать, сколько среди этого НАХОДОК и можно ли этот гейт сузить.
//
// `scopable: false` — важнее всего остального. Гейт, который печатает вердикт без путей
// (проверка сообщения коммита, проверка конфига конвейера), сузить дифом нельзя. Признать его
// успешным на этом основании значило бы получить зелёное молчание там, где проверка провалилась,
// — ровно та тишина, против которой построен весь стандарт. Вызывающий обязан оставить такой
// гейт красным и сказать, почему он не сужен.
function scopeOutput(lines, files) {
  const kept = [];
  let findings = 0;
  let scopable = false;

  for (const raw of lines) {
    const plain = String(raw).replace(ANSI, "");
    const candidates = plain.match(CANDIDATE) || [];
    if (!candidates.length) {
      // Строка без пути — это шапка, итог или пояснение. Показываем: без неё находка теряет
      // контекст. Находкой не считаем: иначе гейт никогда не сузился бы до нуля.
      kept.push(raw);
      continue;
    }
    scopable = true;
    if (candidates.some((c) => inScope(c, files))) {
      kept.push(raw);
      findings++;
    }
  }
  return { kept, findings, scopable };
}

// СОВЕТ ПО ПОЧИНКЕ — ЭТО НЕ ХВОСТ ВЫВОДА, А ЕГО ГЛАВНАЯ ЧАСТЬ.
//
// Все записи каталога печатают последней строкой «почини: …». `doctor --run` показывал три
// первые строки и обрезал остальное — то есть ровно эту строку человек не видел никогда.
// Находка без действия закрывает окно, а не дефект. Отделяем совет от находок, чтобы находки
// можно было обрезать, а совет — нет.
//
// Опознаётся по метке в начале строки на любом из двух языков; продолжение совета — все строки
// после метки. Без метки совет не выдумывается: вывод, где не сказано, что делать, — это признак
// записи, которой нечего ответить, и приёмка каталога такую запись отклоняет.
const ADVICE_RE = /^\s*(почини|fix)\s*:/i;

// Находка опознаётся по «путь:строка:» — тем же признаком, что и при сужении по дифу.
// Нужен здесь, чтобы отличить продолжение совета от находки, стоящей сразу за ним.
const FINDING_RE = /:\d+:/;

function splitAdvice(lines) {
  const findings = [];
  const advice = [];
  let inAdvice = false;

  for (const raw of Array.isArray(lines) ? lines : []) {
    const plain = String(raw).replace(ANSI, "");
    if (ADVICE_RE.test(plain)) { inAdvice = true; advice.push(raw); continue; }
    // Продолжение совета — строка с отступом, в которой нет находки. Всё остальное закрывает
    // совет: иначе первая же метка утаскивала бы в жёлтое весь оставшийся вывод, а гейты
    // печатают совет и посреди находок тоже. На живом выводе это давало сорок строк без
    // обрезки — ровно ту стену, против которой написан весь модуль.
    if (inAdvice && /^\s/.test(plain) && !FINDING_RE.test(plain)) { advice.push(raw); continue; }
    inAdvice = false;
    findings.push(raw);
  }
  return { findings, advice };
}

// Файлы, изменённые относительно ссылки. Новые файлы, ещё не добавленные в индекс, тоже входят:
// их код так же нов, как и остальной диф, а из `git diff` они не видны.
function changedFiles(ref, cwd) {
  const git = (args) => {
    const r = spawnSync("git", args, { cwd, encoding: "utf8" });
    return r.status === 0 ? String(r.stdout || "") : null;
  };
  // Точка расхождения, а не сама ссылка: сравнение с веткой, ушедшей вперёд, показало бы
  // чужие изменения как свои. Если базы нет (ссылка — коммит в той же линии), берём её саму.
  const base = (git(["merge-base", ref, "HEAD"]) || "").trim() || ref;
  const diff = git(["diff", "--name-only", base]);
  if (diff === null) return null;
  const untracked = git(["ls-files", "--others", "--exclude-standard"]) || "";
  return new Set(
    `${diff}\n${untracked}`.split("\n").map((l) => normPath(l.trim())).filter(Boolean)
  );
}

export { scopeOutput, splitAdvice, changedFiles, pathsIn, normPath };
