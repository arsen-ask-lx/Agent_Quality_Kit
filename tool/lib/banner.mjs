// Объявленная ширина сверяется с настоящей модульной проверкой: правка рисунка, разъехавшаяся
// с этим числом, роняет её. Иначе число здесь через месяц врёт, как всякая цифра в комментарии.
const BANNER_WIDTH = 27;

// Терминал без UTF-8 превратит Брайль в вопросительные знаки, и человек решит, что инструмент
// сломан. Тогда честнее короткая строка: она несёт то же самое, только буквами.
function canDrawArt(env) {
  if (String(env.AQK_NO_ART || "") === "1") return false;
  const loc = `${env.LC_ALL || ""}${env.LC_CTYPE || ""}${env.LANG || ""}`.toLowerCase();
  // Windows-терминалы локаль обычно не выставляют вовсе, а UTF-8 там с 2019 года есть.
  // Поэтому пусто — рисуем; явно не-UTF-8 — не рисуем.
  if (!loc) return true;
  return loc.includes("utf-8") || loc.includes("utf8");
}

// ВЕРСИИ В ЗАСТАВКЕ НЕТ — решение владельца. Выпуски идут часто, и номер в картинке устаревает
// быстрее всего остального; за версией есть `--version`, где она и печатается отдельной строкой.
function banner(env = process.env) {
  if (!canDrawArt(env)) return "  aqk — agent quality kit";
  // Отступ подписи — шесть, а не три: он посчитан от ВИДИМОГО центра букв (со 2-го знака по
  // 26-й, центр 14), а не подобран на глаз. Подобранный на глаз держался до первой правки
  // рисунка; посчитанный переживёт её, а проверка ниже покажет, если разъедется.
  return `${ART.join("\n")}\n      agent quality kit`;
}

