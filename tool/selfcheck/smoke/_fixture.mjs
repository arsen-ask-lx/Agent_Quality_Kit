// tool/selfcheck/smoke/_fixture.mjs — общая оснастка проверок, гоняющих сам инструмент.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. В `smoke.sh` фикстура «временный проект под git» написана сорок раз
// подряд одними и теми же четырьмя строками. Это не похожие строки, а ОДНО знание в сорока
// местах: меняется устройство подопытного проекта — правится сорок мест, и они расходятся.
//
// ЧТО ЗДЕСЬ ЗАКРЫТО, кроме дублирования (всё — из разборов флейков и из нашего же опыта):
//   · СВОЙ каталог на проверку и уборка после неё — через `t.after`, а не «не забыть rm»;
//   · ТАЙМАУТ на каждый запуск: висящий подпроцесс иначе держит конвейер до его предела;
//   · ГЕРМЕТИЧНОСТЬ: HOME и TMPDIR в песочнице, сеть выключена. Прогон обязан давать один
//     ответ на любой машине и в любой день — иначе зелёное значит «сегодня совпало».
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const CLI = join(ROOT, "tool", "program.mjs");

// Предел на один запуск. Тридцать секунд — с запасом: самый долгий наш прогон в фикстуре
// (`start` со всеми записями) укладывается в единицы секунд. Предел нужен не ради скорости,
// а ради того, чтобы висящий процесс называл себя, а не съедал бюджет задания молча.
const TIMEOUT_MS = 30000;

// Настоящий дом СНИМАЕТСЯ ОДИН РАЗ, до всякой подмены: из него берётся PYTHONUSERBASE.
const REAL_HOME = process.env.HOME || process.env.USERPROFILE || "";

function env(home, dir) {
  return {
    ...process.env,
    // PYTHONUSERBASE — ИЗ-ЗА подмены HOME и до неё. Инструменты, поставленные `pip --user`
    // (`vulture`, `pylint`), это python-скрипты, которые ищут свои модули в
    // $HOME/.local/lib. С песочницей вместо HOME импорт падает, инструмент выходит ненулевым,
    // и обёртка родного рецепта читает это как НАХОДКУ. То есть проверка краснела не на
    // дефекте, а на собственной оснастке. Тот же довод дословно записан в шапке `smoke.sh`;
    // здесь он был потерян при переезде на встроенный раннер.
    PYTHONUSERBASE: process.env.PYTHONUSERBASE || `${REAL_HOME}/.local`,
    HOME: home,
    USERPROFILE: home,
    TMPDIR: join(home, "tmp"),
    // ПОТОЛОК ПОИСКА РЕПОЗИТОРИЯ. Без него `git: false` не означает «вне репозитория»: git
    // идёт вверх по дереву, и если ЛЮБОЙ предок временного каталога окажется репозиторием,
    // подопытный проект молча получит чужую историю. Поймано 2026-09-10: проверка «гейт без
    // репозитория обязан сказать "не смогли"» проходила поодиночке и падала внутри `smoke.sh`,
    // потому что там над TMPDIR оказывался git. Один и тот же тест давал разные ответы в
    // зависимости от того, чем занят каталог этажом выше, — то есть герметичность, ради
    // которой этот файл написан, держалась на случайности.
    //
    // Указывается РОДИТЕЛЬ, а не сам каталог: git не поднимается ВЫШЕ потолка, но от стартового
    // каталога до него доходит. С потолком, равным проекту, репозиторий этажом выше находился
    // по-прежнему — проверено прямым опытом, а не выведено из документации.
    GIT_CEILING_DIRECTORIES: dirname(dir),
    AQK_LANG: "ru",
    // Сеть в тестах — отдельный класс флейков, и у нас она включалась ТОЛЬКО вне конвейера:
    // локально проверки были сетевыми, в конвейере нет. Две разные среды по построению.
    AQK_UPDATE: "0",
    // Вывод — как у пользователя, короткий. `smoke.sh` включает AQK_VERBOSE=1 для СВОИХ
    // проверок, написанных до свёртки, и без сброса здесь проверки свёртки его унаследовали бы.
    AQK_VERBOSE: "",
  };
}

// Подопытный проект: свой каталог, свой git, свой дом. Файлы задаются картой «путь → текст»,
// потому что имя файла в такой проверке — часть утверждения, а не деталь.
function project(t, files = {}, { git = true } = {}) {
  const dir = mkdtempSync(join(tmpdir(), "aqk-smoke-"));
  const home = join(dir, ".home");
  mkdirSync(join(home, "tmp"), { recursive: true });
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  for (const [rel, text] of Object.entries(files)) {
    const full = join(dir, rel);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, text, "utf8");
  }
  const p = { dir, home };
  if (git) {
    run(p, "git", ["init", "-q", "."]);
    run(p, "git", ["config", "user.email", "t@t"]);
    run(p, "git", ["config", "user.name", "t"]);
  }
  return p;
}

// Запуск чего угодно в каталоге проекта. Возвращается И код, И вывод: проверка, смотрящая
// только на код, не умеет объяснить провал, а смотрящая только на вывод — не умеет заметить,
// что команда не роняет прогон.
// `extra` — переменные поверх песочницы, когда проверка про само окружение (GITHUB_ACTIONS).
function run({ dir, home }, cmd, args = [], extra = {}) {
  const r = spawnSync(cmd, args, {
    cwd: dir, encoding: "utf8", timeout: TIMEOUT_MS, env: { ...env(home, dir), ...extra },
  });
  return { code: r.status, out: `${r.stdout || ""}${r.stderr || ""}` };
}

const aqk = (p, ...args) => run(p, process.execPath, [CLI, ...args]);
const aqkEnv = (p, extra, ...args) => run(p, process.execPath, [CLI, ...args], extra);

// ПОЧЕМУ ГЕЙТ ЗОВЁТСЯ ТОЧКОЙ, А НЕ ПУТЁМ, И ПОЧЕМУ ПУТЬ ЧЕРЕЗ КОСУЮ.
// Node на Windows отдаёт `C:\Users\…\Temp\aqk-smoke-x`, а Git Bash живёт в POSIX-мире и
// такого пути не знает: проверка искала спецификации в несуществующем каталоге, не находила
// ничего и выходила с нулём — то есть краснела не на дефекте, а на переносимости. Поймано
// конвейером на windows-задании в тот же день, когда файл был написан.
// Лечится двумя приёмами сразу: каталог отдаётся как «.» вместе с cwd (переводить нечего),
// а путь до самого скрипта — с прямыми косыми, их Git Bash понимает.
const posix = (p) => String(p).replace(/\\/g, "/");
// Подкаталог нужен там, где проверяется не сам проект, а его клон: мелкий клон предложения
// изменений ведёт себя иначе, чем полная история, и это отдельный класс отказов.
const gate = (p, name, sub = ".") =>
  run(p, "bash", [posix(join(ROOT, "kit", "gates", name, "check.sh")), sub]);

// Наружу — только то, что зовут проверки. `ROOT` и `CLI` остаются внутри: экспорт, который
// никто не берёт, читается как часть договора и мешает менять внутренности — поймал наш же
// dead-code через минуту после того, как файл был написан. `run` вернулся, когда появилась
// проверка, которой нужен сырой git: экспорт заводится под потребителя, а не про запас.
export { project, run, aqk, aqkEnv, gate };
