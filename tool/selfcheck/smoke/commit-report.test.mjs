// Мини-отчёт в коммите: где его требовать, а где состав коммита определить нельзя.
//
// НАЙДЕНО КОНВЕЙЕРОМ 2026-09-09. Коммит, трогающий ТОЛЬКО журнал, отчёта не требует — сама
// запись и есть отчёт. Локально так и было. В конвейере тот же коммит покраснел, и причина
// тоньше, чем кажется:
//   · при разборе предложения изменений GitHub выкладывает синтетический коммит слияния,
//     и гейт правильно спрашивает второго родителя — коммит автора;
//   · но выкладка идёт МЕЛКИМ клоном, и родителя второго родителя в нём нет;
//   · `git show --name-only` на коммите без родителя считает его корневым и выдаёт ВСЁ дерево;
//   · значит «трогает только журнал» перестаёт срабатывать — молча, — и гейт требует отчёт там,
//     где не должен.
// Проверено опытом: глубина 2 — красный, глубина 3 — чисто.
import test from "node:test";
import assert from "node:assert/strict";
import { project, run, gate } from "./_fixture.mjs";

function repoWithJournalMerge(t) {
  const p = project(t, {
    "incidents/README.md": "# журнал\n",
    "src/a.py": "код\n",
    ".aqk.yml": "lessons: incidents\n",
  });
  run(p, "git", ["add", "-A"]);
  run(p, "git", ["commit", "-q", "-m", "feat: первый", "-m", "Сделано: завёл", "-m", "Не уверен: ни в чём"]);
  run(p, "git", ["checkout", "-q", "-b", "feature"]);
  run(p, "bash", ["-c", "printf '## запись\\n' >> incidents/README.md"]);
  run(p, "git", ["add", "-A"]);
  // Тело НАРОЧНО без «Сделано:»: если освобождение для журнала перестанет работать, гейт
  // покраснеет — то есть проверка умеет отличить исправное от сломанного.
  run(p, "git", ["commit", "-q", "-m", "docs: урок", "-m", "Не уверен: ничего не сломано"]);
  const main = run(p, "bash", ["-c", "git checkout -q master 2>/dev/null || git checkout -q main; git rev-parse --short HEAD"]);
  run(p, "git", ["merge", "-q", "--no-ff", "feature", "-m", `Merge feature into ${main.out.trim()}`]);
  return p;
}

test("коммит только в журнал не требует отчёта и в мелком клоне слияния", (t) => {
  const p = repoWithJournalMerge(t);
  assert.equal(gate(p, "commit-explains-itself").code, 0, "полная история: журнальный коммит покраснел");

  // Ровно то, что делает конвейер при разборе предложения изменений.
  run(p, "bash", ["-c", "git clone -q --depth 2 file://$PWD shallow2 2>/dev/null"]);
  const r = gate(p, "commit-explains-itself", "shallow2");
  assert.equal(r.code, 0, `мелкий клон: гейт требует отчёт там, где состав определить нельзя:\n${r.out}`);
  // Молчать в этом случае нельзя: пропуск обязан называть себя, иначе выключенная проверка
  // неотличима от работающей — тот самый класс, ради которого весь комплект.
  assert.match(r.out, /не определить|журнал/, `пропуск не назвал причину:\n${r.out}`);
});
