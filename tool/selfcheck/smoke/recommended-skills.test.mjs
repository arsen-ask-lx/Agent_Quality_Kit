// Страница рекомендованных скиллов не имеет права сгнить молча.
//
// ЗАЧЕМ ЭТА ПРОВЕРКА СУЩЕСТВУЕТ. `kit/skills/README.md` — список ссылок на чужие репозитории,
// то есть ровно тот вид текста, который врёт молча: автор переписал скилл, переименовал каталог
// или удалил репозиторий, а наша строка выглядит так же уверенно, как вчера. У комплекта уже
// записана шишка этого класса — три адреса чужих репозиториев, написанные по памяти, дали 404
// (`incidents/README.md`, 2026-09-08). Разница между тем случаем и этим только в том, что здесь
// ложь появится сама, без нашего участия, — значит и сторож нужен не разовый.
//
// ПОЧЕМУ СРОК ГОДНОСТИ, А НЕ ПРОВЕРКА ССЫЛОК. Открывать двадцать чужих ссылок из проверки — это
// сеть в приёмке: локально зелено, в конвейере без сети красно, у пользователя молча. Такой
// прибор мы уже завели один раз сознательно (`ci-not-hijackable`, ему нужен реестр npm) и знаем
// цену. Здесь дешевле и честнее другое: список объявляет дату сверки, и через 180 дней проверка
// краснеет сама. Приём не выдуман — у нашего же храповика есть `aqk-deadline`, срок с машинным
// последствием; срок без последствия это украшение.
//
// ЧТО ЭТА ПРОВЕРКА НЕ ДОКАЗЫВАЕТ. Что ссылки живы и что текст по ним тот же. Это работа того,
// кто ставит скилл, и правило 1 страницы говорит об этом прямо.
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const PAGE = join(ROOT, "kit", "skills", "README.md");
const DAYS = 180;

const text = readFileSync(PAGE, "utf8");

// Строка таблицы рекомендаций: шесть граф. Отказы лежат в другой таблице — у них две графы,
// и общий разбор «любая строка с |» смешал бы их и проверял не то.
function recommendRows() {
  const start = text.indexOf("## Рекомендуем посмотреть");
  const end = text.indexOf("## Ставить НЕ надо");
  assert.ok(start > -1 && end > start, "на странице нет раздела рекомендаций или раздела отказов");
  return text.slice(start, end).split("\n")
    .filter((l) => l.startsWith("|") && !/^\|\s*(Скилл|-)/.test(l))
    .map((l) => l.split("|").slice(1, -1).map((c) => c.trim()));
}

function refuseRows() {
  const start = text.indexOf("## Ставить НЕ надо");
  const end = text.indexOf("## Как это проверяется машиной");
  assert.ok(start > -1 && end > start, "на странице нет раздела отказов или раздела про проверку");
  return text.slice(start, end).split("\n")
    .filter((l) => l.startsWith("|") && !/^\|\s*(Скилл|-)/.test(l))
    .map((l) => l.split("|").slice(1, -1).map((c) => c.trim()));
}

test("у каждой рекомендации есть закреплённый коммит и живая ссылка", () => {
  const rows = recommendRows();
  assert.ok(rows.length > 0, "раздел рекомендаций пуст — тогда страница обещает больше, чем несёт");
  for (const [name, pinned, live] of rows) {
    // Закреплённая ссылка — та, о которой у нас есть суждение. Без коммита в адресе суждение
    // относится к «когда-то», то есть ни к чему.
    assert.match(pinned, /\/blob\/[0-9a-f]{40}\//,
      `${name}: снимок без 40-значного коммита в адресе — судить об изменчивом тексте нельзя`);
    // Живая ссылка обязана вести НЕ на тот же коммит: иначе правило «читай живую версию»
    // отправляет читателя туда же, где он уже был, и перестаёт работать.
    assert.doesNotMatch(live, /\/blob\/[0-9a-f]{40}\//,
      `${name}: «живая» ссылка закреплена за коммитом — она не живая`);
    assert.match(live, /^\[[^\]]+\]\(https:\/\/\S+\)$/, `${name}: живая ссылка не ссылка`);
  }
});

test("каждая рекомендация отвечает на вопрос «ставить или нет»", () => {
  for (const row of recommendRows()) {
    const [name, , , gives, have] = row;
    assert.equal(row.length, 5, `${name}: в строке ${row.length} граф вместо пяти`);
    assert.ok(gives.length > 10, `${name}: не сказано, что скилл даёт`);
    // Главная графа. Рекомендация без ответа «а что у нас уже есть» ведёт к второму пересказу
    // правила, а два пересказа через месяц врут по-разному.
    assert.ok(have.length > 10, `${name}: не сказано, что у нас уже есть — рекомендация неполная`);
  }
});

test("у каждого отказа названа причина", () => {
  const rows = refuseRows();
  assert.ok(rows.length > 0, "раздел отказов пуст — а отказ с причиной здесь важнее рекомендации");
  for (const [name, why] of rows) {
    assert.ok(why && why.length > 20, `${name}: отказ без причины — это вкус, выданный за суждение`);
  }
});

test("страница объявляет дату сверки и не пережила свой срок", () => {
  const m = text.match(/^## Сверено: (\d{4})-(\d{2})-(\d{2})$/m);
  assert.ok(m, "на странице нет строки «## Сверено: ГГГГ-ММ-ДД» — без даты срок годности не считается");
  const when = Date.parse(`${m[1]}-${m[2]}-${m[3]}T00:00:00Z`);
  assert.ok(Number.isFinite(when), `дата сверки не разбирается: ${m[0]}`);
  const now = Date.now();
  // Дата в будущем — не «ещё свежее», а сломанные часы либо опечатка. Сутки допуска на часовые
  // пояса: сверку делает человек по своему календарю, а проверка идёт по UTC.
  assert.ok(when <= now + 86400000, `дата сверки в будущем: ${m[0]}`);
  const age = Math.floor((now - when) / 86400000);
  assert.ok(age <= DAYS,
    `странице ${age} дней, срок ${DAYS}. Ссылки на чужие репозитории столько не живут:\n` +
    "  открой каждую живую ссылку, сверь снимок с текущим текстом, обнови суждения и дату.\n" +
    "  Если сверять некогда — удали раздел рекомендаций: пустой список честнее устаревшего.");
});
