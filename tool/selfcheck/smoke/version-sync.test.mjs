// tool/selfcheck/smoke/version-sync.test.mjs — ВЕРСИЯ ОБЪЯВЛЕНА В ПЯТИ МЕСТАХ, И ОНИ ОБЯЗАНЫ
// СОВПАДАТЬ.
//
// ЗАЧЕМ. Выпуск поднимает номер руками в `package.json`, обоих README (`rev:` для pre-commit и
// `uses: …@vX` для действия), `llms.txt` и манифесте плагина. Пять мест, одно знание, и ни одно
// из них до сегодня не сторожила машина: забытая строка в README означает, что человек закрепит
// `v0.14.0` на день после выхода 0.15.0 и не получит ни одной правки, а забытая строка в манифесте
// плагина — что витрина Claude Code раздаёт версию, которой уже нет.
//
// Ровно тот класс, ради которого написан весь комплект: утверждение («это версия 0.15.0»), которое
// никто не проверяет. Найдено 2026-09-14, когда к четырём местам добавилось пятое.
//
// ПОЧЕМУ НЕ «ЛЮБОЕ ЧИСЛО ВИДА vX.Y.Z». Ищем только строки, которые ОБЕЩАЮТ ТЕКУЩУЮ версию:
// закрепление в примере установки. Номера в журнале изменений — это история, они обязаны
// оставаться прежними, и требовать от них свежести значило бы переписывать прошлое.
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const read = (rel) => readFileSync(join(ROOT, rel), "utf8");

const VERSION = JSON.parse(read("package.json")).version;

// Каждое место — файл и то, чем из него достаётся ОБЕЩАНИЕ версии. Список здесь, а не в коде
// выпуска: список, который знает только тот, кто выпускает, живёт в его памяти, а не в машине.
const PLACES = [
  { file: "README.md", why: "закрепление pre-commit и действия в примере установки" },
  { file: "README.ru.md", why: "то же по-русски" },
  { file: "llms.txt", why: "выжимка для агента: `uses: …@vX.Y.Z`" },
];

test(`версия в package.json — ${VERSION}, и она непустая`, () => {
  assert.match(VERSION, /^\d+\.\d+\.\d+$/, `странный номер версии: ${VERSION}`);
});

for (const { file, why } of PLACES) {
  test(`«${file}» обещает текущую версию (${why})`, () => {
    const text = read(file);
    const pinned = [...text.matchAll(/v(\d+\.\d+\.\d+)/g)].map((m) => m[1]);
    assert.ok(pinned.length, `в ${file} нет ни одного закрепления вида vX.Y.Z — пример установки исчез?`);
    const stale = [...new Set(pinned.filter((v) => v !== VERSION))];
    assert.equal(stale.length, 0,
      `${file} закрепляет ${stale.join(", ")}, а пакет уже ${VERSION}: человек, скопировавший ` +
      `пример, получит старую версию и ни одной правки из новой`);
  });
}

// Манифест плагина — пятое место, и самое тихое: его читает витрина Claude Code, а не человек.
// Расхождение здесь никто не заметит глазами.
test("манифест плагина обещает ту же версию", () => {
  const man = JSON.parse(read("plugin/.claude-plugin/plugin.json"));
  assert.equal(man.version, VERSION,
    `плагин объявляет ${man.version}, пакет ${VERSION}: витрина будет раздавать версию, ` +
    "которой в npm уже нет. Обновления у плагина приходят только по смене этого поля");
});

// Плагин — тонкая обёртка над той же программой, и она не имеет права разойтись с ней. Если
// когда-нибудь здесь появится собственная логика, эта проверка о ней скажет.
test("плагин остаётся обёрткой: команды зовут ту же программу из реестра", () => {
  const hooks = read("plugin/hooks/hooks.json");
  assert.match(hooks, /agent-quality-kit/, "хук плагина зовёт не наш пакет");
  assert.doesNotMatch(hooks, /node\s+\//, "в хук плагина попал абсолютный путь — у чужого его нет");
});

// РАЗМЕР ПАКЕТА — ЧИСЛО, КОТОРОЕ ДО СЕГОДНЯ НЕ СТОРОЖИЛ НИКТО, и оно врало трижды: «230 КБ» в
// core.mjs при настоящих 692, «574.1 kB» в обоих README при тех же 692. В самом README рядом
// стояла честная приписка «это число не сторожит никто» — вот она и есть признание, что
// утверждение без арбитра живёт ровно до первой правки.
//
// СВЕРЯЕТСЯ ОКРУГЛЁННОЕ до десятой доли мегабайта: точный байт меняется от версии npm и от
// сжатия, и требовать его совпадения значило бы получить красное на пустом месте. А вот переход
// через десятую долю — это уже рост, о котором человек обязан узнать и либо признать его в
// тексте, либо остановить.
test("обещанный в README размер пакета совпадает с настоящим", () => {
  // На Windows программа называется `npm.cmd`, и запуск без оболочки падает с ENOENT — ровно
  // тот же класс, что записан у нас про `bash` в execution.mjs. Поймано windows-заданием
  // конвейера в тот же день, когда проверка была написана: на Linux её ничто не тревожило.
  const npm = process.platform === "win32" ? "npm.cmd" : "npm";
  const out = execFileSync(npm, ["pack", "--dry-run", "--json"], { cwd: ROOT, encoding: "utf8" });
  const bytes = JSON.parse(out)[0].size;
  const real = (Math.round(bytes / 1024 / 1024 * 10) / 10).toFixed(1);
  for (const [file, re] of [["README.md", /≈([\d.]+) MB/], ["README.ru.md", /≈([\d,]+) МБ/]]) {
    const m = re.exec(read(file));
    assert.ok(m, `в ${file} нет обещания размера пакета — строка «≈… МБ» пропала`);
    const said = m[1].replace(",", ".");
    assert.equal(said, real,
      `${file} обещает ≈${said} МБ, а пакет весит ${real} МБ (${bytes} байт). ` +
      "Либо поправьте текст, либо остановите рост — молча расходиться этим двум нельзя");
  }
});
