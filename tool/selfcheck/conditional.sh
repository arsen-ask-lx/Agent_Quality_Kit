#!/usr/bin/env bash
# Записи каталога, чьё доказательство не ссылается на журнал шишек.
#
# ЗАЧЕМ ОТДЕЛЬНОЙ ПРОВЕРКОЙ. «Это хорошая практика» — самый частый способ, которым каталог
# набирает пункты, среди которых нельзя выбрать. Условная запись допустима как долг, но их
# число не должно расти: список под храповиком может только укорачиваться.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

for GATE in "$ROOT"/kit/gates/*/; do
  YML="$GATE/gate.yml"
  [ -f "$YML" ] || continue
  PROOF="$(sed -n 's/^proof:[[:space:]]*\(.*\)$/\1/p' "$YML" | head -1)"
  case "$PROOF" in
    *incidents/*) ;;
    *)
      # Ключом служит только имя: правка формулировки доказательства не должна читаться
      # как новое нарушение. Сам текст — отступом, такие строки в ключ не идут.
      echo "$(basename "$GATE"): доказательство не ссылается на журнал шишек"
      echo "    сейчас: $PROOF"
      ;;
  esac
done
exit 0
