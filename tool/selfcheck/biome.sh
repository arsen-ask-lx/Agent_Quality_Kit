#!/usr/bin/env bash
# JavaScript комплекта — под линтером biome.
#
# ЗАЧЕМ. Решение владельца 2026-09-27: всё, что AQK советует ставить, стоит и у нас. Какой
# линтер — выбрано замером на `tool/` того же дня: eslint (рекомендуемые) дал 50 замечаний,
# biome — 88, из них 43 про оформление; по сути оба нашли одно и то же. biome взят потому, что
# это одна программа без пакетов в нашем package.json (у программы AQK зависимостей нет и не
# будет), и его же ставят пользователи. Первый прогон нашёл настоящее: две строки каталога
# вставлены дважды (молча затиралась первая) и отметку итога в `aqk note`, которую обходил любой
# эмодзи (класс символов без флага u).
#
# ПРЕДУПРЕЖДЕНИЯ — ТОЖЕ НАХОДКИ. Без `--error-on-warnings` правило уровня warn не роняет проверку
# никогда — ровно этот способ заглушения записан в kit/tools/biome.json. Группа оформления
# выключена в biome.json: это вкус, а не дефект.
#
# ДОЛГ — ПОД ХРАПОВИКОМ ratchets/biome.txt: 36 старых замечаний проходят, новое нет.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT" || exit 2

command -v npx >/dev/null 2>&1 || { echo "не смогли проверить: нет npx"; exit 2; }

# Формат concise — одна строка на замечание: «× путь:строка:колонка: правило: текст». Значок
# уровня в начале снимается: храповик узнаёт находку по пути, а номер строки из ключа убирает сам.
OUT="$(npx --yes @biomejs/biome@2.5.14 lint --reporter=concise --max-diagnostics=none --error-on-warnings tool evals 2>&1)"
CODE=$?
sed -E 's/^[×!i] //' <<<"$OUT"
case "$CODE" in
  0) exit 0 ;;
  1) echo "  почини: правило в строке замечания; объяснение — https://biomejs.dev/linter/rules/"; exit 1 ;;
  *) echo "не смогли проверить: biome вышел с кодом $CODE"; exit 2 ;;
esac
