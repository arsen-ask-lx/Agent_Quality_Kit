// tool/selfcheck/units-ask.mjs — КОГДА КОМПЛЕКТ ОБРАЩАЕТСЯ К ЧЕЛОВЕКУ: ограничитель обращений.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ И ЭТОТ МОДУЛЬ. Знание «мы это человеку уже показывали» жило в комплекте
// ДВАЖДЫ и по-разному: `~/.config/aqk/feedback-shown` — файл-флаг, раз на машину, заведён в
// core.mjs и прочитан в project.mjs; `.aqk/advice-shown` и `.aqk/update-checked` — отметка
// временем плюс `adviceDue()` на сутки, заведённые в brief.mjs. Одно решение — «не долби» — в
// двух местах с двумя форматами хранения. Третье обращение (просьба об отзыве по делу) завело
// бы третий формат, и дальше они расходятся молча: именно так и умирает ограничитель.
//
// Поэтому здесь один модуль на все обращения и таблица видов. Вид объявляет ДВЕ вещи, и обе
// нельзя угадать по имени: где живёт отметка (проект или дом) и как часто можно повторять.
//
//   node --test tool/selfcheck/units-ask.mjs
import test from "node:test";
import assert from "node:assert/strict";
import { askDue, askFile, ASKS, ASK_FILES } from "../lib/ask.mjs";
import { RUNTIME_FILES } from "../lib/core.mjs";

const NOW = Date.parse("2026-09-14T20:00:00Z");

// --- «раз в сутки»: совет и проверка версии ----------------------------------
// Тот же договор, что был у adviceDue, и он обязан остаться прежним: совет на каждом коммите
// превращается в шум, а шум пролистывают вместе с настоящими находками.
test("суточное обращение: не показывали — пора", () => {
  assert.equal(askDue("advice", null, NOW), true);
});

test("суточное обращение: час назад — рано, сутки назад — пора", () => {
  assert.equal(askDue("advice", "2026-09-14T19:00:00Z", NOW), false);
  assert.equal(askDue("advice", "2026-09-13T19:00:00Z", NOW), true);
});

// Испорченная отметка — это «не знаем, когда показывали». Молчать из-за нечитаемого файла
// состояния значит потерять обращение навсегда и не сказать почему.
test("испорченная отметка читается как «не знаем» и обращение показывается", () => {
  assert.equal(askDue("advice", "не дата", NOW), true);
});

// --- «один раз»: просьба об отзыве -------------------------------------------
// Разовое обращение отличается от суточного не числом, а СМЫСЛОМ: его нельзя повторить никогда,
// сколько бы времени ни прошло. Считать его «раз в очень много часов» — значит однажды получить
// повтор у человека, который поставил комплект год назад.
test("разовое обращение: без отметки — пора, с любой отметкой — никогда", () => {
  assert.equal(askDue("install", null, NOW), true);
  assert.equal(askDue("install", "shown\n", NOW), false);
  assert.equal(askDue("install", "2020-01-01T00:00:00Z", NOW), false);
  assert.equal(askDue("install", "мусор", NOW), false);
});

// --- опечатка в виде обращения -----------------------------------------------
// Неизвестный вид обязан падать, а не превращаться в «показывать всегда» или «не показывать
// никогда». Оба умолчания — молчаливый выбор за человека, и оба неверны в половине случаев.
test("неизвестный вид обращения — отказ, а не тихое умолчание", () => {
  assert.throws(() => askDue("опечатка", null, NOW), /опечатка/);
  assert.throws(() => askFile("опечатка", { project: "/p", home: "/h" }), /опечатка/);
});

// --- где лежит отметка --------------------------------------------------------
// Разовая на машину отметка НЕ ИМЕЕТ ПРАВА лежать в проекте: внутри `.aqk/` она либо уедет в
// чужой git как наш мусор, либо пропадёт при `init --force` — и то и другое врёт о том, видел
// человек обращение или нет. Довод записан в core.mjs с 2026-09; проверки у него не было.
test("разовая на машину отметка лежит вне проекта", () => {
  const p = askFile("install", { project: "/p", home: "/h" });
  assert.ok(!p.startsWith("/p"), `отметка машины уехала в проект: ${p}`);
  assert.ok(p.startsWith("/h"), `отметка машины легла мимо дома: ${p}`);
});

test("отметки про этот проект лежат в проекте", () => {
  for (const kind of Object.keys(ASKS).filter((k) => ASKS[k].where === "project")) {
    const p = askFile(kind, { project: "/p", home: "/h" });
    assert.ok(p.startsWith("/p"), `${kind}: отметка проекта легла мимо проекта: ${p}`);
  }
});

// --- СВЯЗЬ ДВУХ СПИСКОВ, КОТОРУЮ ИНАЧЕ НЕ СТОРОЖИТ НИКТО ----------------------
// Отметка, лежащая в `.aqk/` и не названная в RUNTIME_FILES, не попадёт в .gitignore — и уедет
// в чужой коммит. Это уже случалось с `.aqk/last-run.md` на живом проекте 2026-09-11, и оттуда
// же взялся сам список. Список и таблица видов — два разных файла, и связь между ними держится
// только этой проверкой.
test("каждая отметка проекта названа в RUNTIME_FILES — иначе уедет в чужой git", () => {
  for (const f of ASK_FILES) {
    assert.ok(RUNTIME_FILES.includes(f),
      `«${f}» не назван в RUNTIME_FILES: init не положит его в .gitignore, и отметка уедет в коммит`);
  }
});
