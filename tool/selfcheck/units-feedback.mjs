// tool/selfcheck/units-feedback.mjs — О ЧЁМ комплект просит человека и что кладёт в отчёт.
//
// ЗАЧЕМ ЭТО ВООБЩЕ. Замер 2026-09-14: 1342 скачивания в неделю в npm, из них ни одного
// пользователя — версии качаются равномерно, включая прожившую двадцать пять минут, то есть это
// зеркала и сканеры. На GitHub за две недели семь уникальных посетителей, две звезды, ноль чужих
// комментариев за всё время. Обратной связи нет не потому, что люди молчат, — её не у кого
// просить, и просить мы не умеем: единственная просьба печаталась при `init`, то есть ДО того,
// как комплект сделал хоть что-то полезное.
//
// ПОЭТОМУ ЗДЕСЬ ДВЕ ЧИСТЫЕ ФУНКЦИИ И ДВА ПРАВИЛА.
//   1. Просим, ТОЛЬКО когда есть что рассказать. «Оставьте отзыв» без содержания — шум, а шум
//      выключают вместе с хуком, в котором он приехал. Самое ценное — «AQK не смог»: жалоба
//      даётся людям легче похвалы, и она же говорит нам, где инструмент врёт.
//   2. Отчёт не несёт ни путей, ни кода. Человек отправляет его сам, и он обязан видеть глазами
//      всё, что отправляет, — иначе первый же внимательный читатель назовёт это телеметрией.
//
//   node --test tool/selfcheck/units-feedback.mjs
import test from "node:test";
import assert from "node:assert/strict";
import { feedbackAsk, reportText, issueUrl, askLine, feedbackWanted } from "../commands/feedback.mjs";

// --- о чём просим ------------------------------------------------------------

// Рассказывать нечего — не просим. Это главное правило: просьба без содержания превращает
// ограничитель в шум, а следующую просьбу — в то, что пролистывают не читая.
test("сказать нечего — просьбы нет", () => {
  assert.equal(feedbackAsk({ cannot: [], blind: [], red: [] }), null);
  assert.equal(feedbackAsk({}), null);
});

// «Не смогли проверить» — самое ценное, что у нас бывает: это отказ прибора, а не находка о
// коде. Такое человек рассказывает охотнее, чем похвалу, и чинить надо именно это.
test("«не смогли проверить» важнее всего остального", () => {
  const a = feedbackAsk({ cannot: ["smoke"], blind: ["swallowed-error"], red: ["lint"] });
  assert.equal(a.reason, "cannot");
  assert.deepEqual(a.names, ["smoke"]);
});

test("слепой класс важнее просто красного гейта", () => {
  const a = feedbackAsk({ cannot: [], blind: ["swallowed-error"], red: ["lint"] });
  assert.equal(a.reason, "blind");
  assert.deepEqual(a.names, ["swallowed-error"]);
});

// Красный гейт — это момент, когда комплект принёс пользу: он поймал то, ради чего стоит.
test("пойманное красным — тоже повод, но последний", () => {
  const a = feedbackAsk({ cannot: [], blind: [], red: ["lint", "smoke"] });
  assert.equal(a.reason, "red");
  assert.deepEqual(a.names, ["lint", "smoke"]);
});

// --- что в отчёте ------------------------------------------------------------

// ПУТЕЙ НЕ БЫВАЕТ. Проба знает файл, в который подсаживала брак («blind-class: slug path»), и
// соблазн положить его в отчёт велик — он же объясняет находку. Нельзя: путь внутри чужого
// репозитория рассказывает о чужом проекте больше, чем его владелец собирался рассказать.
test("отчёт называет класс, но не файл, в котором его нашли", () => {
  const text = reportText({
    version: "0.15.0", node: "v22.0.0", platform: "linux", level: 3,
    langs: ["javascript"], gates: 31, red: ["lint"], cannot: [],
    blind: [{ slug: "swallowed-error", file: "src/secret/internal.js" }],
  }).join("\n");
  assert.match(text, /swallowed-error/, "класс не назван — отчёт бесполезен");
  assert.doesNotMatch(text, /src\/secret\/internal\.js/, "в отчёт попал путь из чужого репозитория");
  assert.doesNotMatch(text, /internal/, "в отчёт попал кусок пути из чужого репозитория");
});

// МЕТКА ИСТОЧНИКА. Отзыв в GitHub ничем не связан с просьбой, и понять, работает ли канал,
// иначе нельзя. Метка видна человеку в том же тексте, который он отправляет: это не слежка,
// а подпись. Слежки у комплекта нет и не будет — исходящий запрос ровно один, про версию.
test("отчёт подписан командой и версией — иначе не узнать, работает ли канал", () => {
  const text = reportText({ version: "0.15.0", node: "v22.0.0", platform: "linux" }).join("\n");
  assert.match(text, /aqk feedback/, "нет метки источника");
  assert.match(text, /0\.15\.0/, "нет версии");
});

// Незнание называется словом, а не пропускается: пустая строка в отчёте читается как «всё
// хорошо» — тот же порок, против которого написан весь комплект, только в нашем же письме.
test("чего не знаем — сказано словом, а не пустым местом", () => {
  const text = reportText({ version: "0.15.0", node: "v22.0.0", platform: "linux", level: null }).join("\n");
  assert.doesNotMatch(text, /уровень:\s*$/m, "уровень пропущен молча");
});

// --- ссылка ------------------------------------------------------------------

// Предзаполнение задачи параметрами `title` и `body` описано в документации GitHub (Creating an
// issue from a URL query, сверено 2026-09-14). Кодирование обязательно: в теле переносы строк,
// решётки и пробелы, и незакодированная ссылка обрывается на первом же из них.
test("ссылка предзаполнена и закодирована", () => {
  const u = issueUrl("https://github.com/o/r", "Заголовок про AQK", "строка\nвторая #2");
  assert.ok(u.startsWith("https://github.com/o/r/issues/new?"), `не та ссылка: ${u}`);
  assert.match(u, /title=/);
  assert.match(u, /body=/);
  assert.doesNotMatch(u, /\n/, "перенос строки не закодирован — ссылка оборвётся");
  assert.doesNotMatch(u, /#2/, "решётка не закодирована — всё после неё отвалится как якорь");
});

// --- как это звучит ----------------------------------------------------------
// Строку строит feedback.mjs, а печатают её `context` (агенту) и `doctor` (человеку): один
// текст на два места. Собери его в каждом месте отдельно — и через месяц они разойдутся, как
// разошлись бы `context` и `prompt` без общего `readAdvice`.
test("строка называет причину, имена и команду", () => {
  const s = askLine({ reason: "cannot", names: ["smoke"] }, "npx agent-quality-kit");
  assert.match(s, /smoke/, "не названо, что именно не смогли");
  assert.match(s, /npx agent-quality-kit feedback/, "нет команды — просьбу нечем выполнить");
});

// АГЕНТУ — ОТДЕЛЬНАЯ ОГОВОРКА. Мы кладём строку в контекст ЧУЖОГО агента, и он исполнит то, что
// там написано. Без «не настаивай» это превращается в рекламу в чужом окне — и хук, которым она
// приехала, снесут в первый же день вместе со всей затеей.
test("агенту сказано не настаивать, человеку — как выключить", () => {
  const forAgent = askLine({ reason: "red", names: ["lint"] }, "aqk", { agent: true });
  const forHuman = askLine({ reason: "red", names: ["lint"] }, "aqk", { agent: false });
  assert.notEqual(forAgent, forHuman, "агенту и человеку сказано одно и то же");
  assert.match(forHuman, /AQK_FEEDBACK=0/, "человеку не сказано, как это выключить");
});

test("просить нечего — строки нет, а не пустая", () => {
  assert.equal(askLine(null, "aqk"), null);
});

// У всего, что случается само, обязан быть выключатель — то же правило, что у совета
// (AQK_ADVICE=0), у пробы (AQK_PROBE=0) и у проверки версии (AQK_UPDATE=0).
test("выключатель уважается", () => {
  assert.equal(feedbackWanted({ AQK_FEEDBACK: "0" }), false);
  assert.equal(feedbackWanted({}), true);
});

// ПРОБА НЕ ДЕЛАЛАСЬ — «НЕИЗВЕСТНО», А НЕ «НЕТ». Поймано на первом же живом запуске команды:
// в письме стояло «классы, которые здесь не ловит никто: нет», хотя проба не запускалась ни
// разу. То есть наш собственный отчёт об инструменте против тишины сам выдавал незнание за
// чистоту — и автор, читающий такое письмо, сделал бы неверный вывод о чужом проекте.
test("проба не делалась — в отчёте «неизвестно», а не «нет»", () => {
  const text = reportText({ version: "0.15.0", blind: null }).join("\n");
  assert.doesNotMatch(text, /не ловит никто: нет/, "незнание выдано за чистоту");
  assert.match(text, /не ловит никто: неизвестно/, "незнание не названо словом");
});
