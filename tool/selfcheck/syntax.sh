#!/usr/bin/env sh
# Все исходники комплекта разбираются: программа на нескольких файлах и скрипты гейтов.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. `node --check` берёт ровно один файл. Пока программа была одним
# файлом, этого хватало; после разделения проверка точки входа означала бы «семь из восьми не
# проверены» — ровно тот класс, где отсутствие сигнала читается как успех.
#
# Цикл в манифесте вместо скрипта не годится: проверка «объявленный гейт запускается» разбирает
# команду на слова и ищет пути — кусок `for f in $(...)` она читает как несуществующий файл.
set -u
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT" || exit 1
BAD=0

for F in $(git ls-files 'tool/*.mjs' 'tool/**/*.mjs' 2>/dev/null); do
  node --check "$F" || BAD=1
done
for F in $(git ls-files '*.sh' 2>/dev/null); do
  bash -n "$F" || BAD=1
done

[ "$BAD" -eq 0 ] || echo "  почини: файл не разбирается — до него не доедет ни одна другая проверка."
exit $BAD
