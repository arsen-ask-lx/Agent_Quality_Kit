#!/usr/bin/env sh
# Список чужих репозиториев для замера — собирается, а не хранится.
#
# ЗАЧЕМ СКРИПТОМ. Список, записанный файлом, через месяц меряет прошлое: репозитории умирают,
# переименовываются, закрываются. И он же подгоняется под ответ — руками легко выкинуть тот, на
# котором наш гейт опозорился. Собранный заново, он этого не позволяет.
#
# ОТКУДА БЕРЁМ. Поиск кода GitHub по именам файлов, которыми пользуются агенты: свод правил в
# трёх принятых написаниях и настройки Claude Code. Выдача поиска ограничена сверху, поэтому
# берём несколько запросов и объединяем — так выборка шире и меньше зависит от одного порядка.
N="${1:-200}"
for Q in "filename:AGENTS.md" "filename:CLAUDE.md" "filename:.mcp.json" "path:.claude/settings.json"; do
  for P in 1 2 3; do
    gh api "search/code?q=$Q&per_page=100&page=$P" --jq '.items[].repository.full_name' 2>/dev/null
  done
done | sort -u | head -n "$N"
