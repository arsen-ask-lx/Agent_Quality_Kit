#!/usr/bin/env sh
# Поиск НАСТОЯЩИХ находок в чужих репозиториях — сырьё для писем.
#
# ЗАЧЕМ. Единственный работающий у нас канал наружу — письмо с воспроизведением: беда, её
# история в их же коммитах и готовая починка. Ручной перебор сюда не масштабируется, а рассылка
# одинаковых сообщений закрывает дверь навсегда. Значит нужен перебор, который выдаёт КАНДИДАТОВ,
# а решение по каждому принимает человек.
#
# ЧТО ЗДЕСЬ НЕ ЗАПУСКАЕТСЯ И ПОЧЕМУ:
#   · проверки про секреты — НИКОГДА. Находка о чужом секрете не пишется публично и не называет
#     репозиторий: это не помощь, а указание цели;
#   · проверки вкуса (длина файла, сложность, дубли) — там нет «объявлено и не существует», есть
#     наше мнение о чужом коде. Письмо с мнением — спам;
#   · `ci-actually-fails` — замер 2026-09-14 дал на 70 репозиториях одно срабатывание, и то
#     ложное. Дорого по времени, пусто по выходу.
#
# ОСТАЁТСЯ ОДИН КЛАСС, зато проверяемый чужими глазами за минуту: ОБЪЯВЛЕНО ТО, ЧЕГО НЕТ.
GATES="entry-commands-exist entry-links-exist hook-actually-fires no-phantom-package mcp-server-resolves"
KIT="$(cd "$(dirname "$0")/../../kit/gates" && pwd)"
LIST="${1:?дай файл со списком репозиториев, по одному на строку}"

while IFS= read -r REPO; do
  [ -z "$REPO" ] && continue
  case "$REPO" in \#*) continue ;; esac
  D=$(mktemp -d)
  if ! git clone -q --depth 1 "https://github.com/$REPO" "$D" 2>/dev/null; then
    echo "?  $REPO: склонировать не удалось — это НЕ «чисто»"
    rm -rf "$D"; continue
  fi
  HITS=0
  for G in $GATES; do
    OUT=$(sh "$KIT/$G/check.sh" "$D" 2>&1); CODE=$?
    # Три исхода, а не два, — то же правило, что в самом комплекте.
    [ "$CODE" = 2 ] && { echo "?  $REPO  $G: проверка не состоялась"; continue; }
    [ "$CODE" = 0 ] && continue
    HITS=1
    echo "✘  $REPO  $G"
    printf '%s\n' "$OUT" | grep -v '^  почини' | sed "s|$D/||; s|^|     |"
  done
  [ "$HITS" = 0 ] && echo "✔  $REPO"
  rm -rf "$D"
done < "$LIST"
