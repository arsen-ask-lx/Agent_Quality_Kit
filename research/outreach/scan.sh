#!/usr/bin/env sh
# Поиск НАСТОЯЩИХ находок в чужих репозиториях — сырьё для писем.
#
# ЗАЧЕМ. Единственный работающий у нас канал наружу — письмо с воспроизведением: беда, её
# история в их же коммитах и готовая починка. Ручной перебор сюда не масштабируется, а рассылка
# одинаковых сообщений закрывает дверь навсегда. Значит нужен перебор, который выдаёт КАНДИДАТОВ,
# а решение по каждому принимает человек.
#
# ЧТО ЗДЕСЬ НЕ ЗАПУСКАЕТСЯ И ПОЧЕМУ:
#   · проверки про секреты — НИКОГДА. Находка о чужом секрете не пишется публично и не называет
#     репозиторий: это не помощь, а указание цели;
#   · проверки вкуса (длина файла, сложность, дубли) — там нет «объявлено и не существует», есть
#     наше мнение о чужом коде. Письмо с мнением — спам;
#   · `ci-actually-fails` — замер 2026-09-14 дал на 70 репозиториях одно срабатывание, и то
#     ложное. Дорого по времени, пусто по выходу.
#
# ОСТАЁТСЯ ОДИН КЛАСС, зато проверяемый чужими глазами за минуту: ОБЪЯВЛЕНО ТО, ЧЕГО НЕТ.
#   · `mcp-server-resolves` — его находка «версия сервера не закреплена» это СОВЕТ, а не
#     «объявлено то, чего нет». Замер 2026-09-15: три срабатывания из семнадцати, и все три
#     такие. Письмо с мнением о чужом укладе читается как рассылка.
# ТОЛЬКО ГЕЙТЫ, СМОТРЯЩИЕ НА КОНСТРУКЦИЮ, А НЕ ЧИТАЮЩИЕ ТЕКСТ. Решение владельца 2026-09-15 по
# числам из нашего же корпуса: из наших ложных восемь дал разбор разметки и
# четыре — разбор имён пакетов; обе записи 2026-09-15 УДАЛЕНЫ из каталога. Двенадцать из шестнадцати — два гейта, которые пытаются понимать
# свободный текст. Остальные три гейта вместе дали четыре.
#
# Причина известна снаружи: разбор разметки регулярными выражениями — известно плохой приём.
# Автор `linkcheck` описал ровно наш случай (ссылка внутри блока кода, прочитанная как живая) и
# перешёл на настоящий разбор CommonMark; у `remark-validate-links` в описании прямо сказано, что
# работа по дереву разбора даёт меньше ложных.
#
# Письмо, отправленное по такому разбору, ошибается в трёх случаях из четырёх. Здесь остаются
# гейты, опознающие КОНСТРУКЦИЮ: хук без файла, команда, которой нет в манифесте проекта.
GATES="entry-commands-exist hook-actually-fires"
KIT="$(cd "$(dirname "$0")/../../kit/gates" && pwd)"
LIST="${1:?дай файл со списком репозиториев, по одному на строку}"

while IFS= read -r REPO; do
  [ -z "$REPO" ] && continue
  case "$REPO" in \#*) continue ;; esac
  D=$(mktemp -d)
  # ПРЕДЕЛ НА КАЖДЫЙ ШАГ. Замер 2026-09-15 встал на репозитории, где лежит корпус из десятков
  # тысяч файлов умений: `slopcheck` шёл по каждому имени в реестр npm, вывод не пополнялся
  # полчаса, и снаружи это было неотличимо от работы. Ровно тот класс, против которого написан
  # комплект, — в приборе того, кто его пишет. Предел вышел — это «не смогли проверить», а не
  # «чисто», и печатается вопросом.
  if ! timeout 120 git clone -q --depth 1 "https://github.com/$REPO" "$D" 2>/dev/null; then
    echo "?  $REPO: склонировать не удалось — это НЕ «чисто»"
    rm -rf "$D"; continue
  fi
  HITS=0
  for G in $GATES; do
    OUT=$(timeout 180 sh "$KIT/$G/check.sh" "$D" 2>&1); CODE=$?
    # Три исхода, а не два, — то же правило, что в самом комплекте.
    [ "$CODE" = 124 ] && { echo "?  $REPO  $G: предел времени 180с — НЕ ПРОВЕРЕНО"; continue; }
    [ "$CODE" = 2 ] && { echo "?  $REPO  $G: проверка не состоялась"; continue; }
    [ "$CODE" = 0 ] && continue
    HITS=1
    echo "✘  $REPO  $G"
    printf '%s\n' "$OUT" | grep -v '^  почини' | sed "s|$D/||; s|^|     |"
  done
  [ "$HITS" = 0 ] && echo "✔  $REPO"
  rm -rf "$D"
done < "$LIST"
