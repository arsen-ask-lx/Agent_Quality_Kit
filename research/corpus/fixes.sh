#!/usr/bin/env sh
# Сбор ЧУЖИХ ПОЧИНОК: что люди на самом деле ломают и чинят.
#
# ЗАЧЕМ. Гейт, придуманный из головы, меряет наш вкус. Гейт, выросший из чужих починок, меряет
# беду. Решение владельца 2026-09-15: заводить запись только под ошибку, которая ПОВТОРЯЕТСЯ во
# многих репозиториях, — единичный случай это история, а не класс.
#
# ЧТО СОБИРАЕТСЯ. Заголовок коммита-починки и файлы, которые он тронул. Не диф: диф читать
# машиной бессмысленно, а заголовок люди пишут ради того, чтобы объяснить, ЧТО было не так.
#
# ВЫВОД: TSV — репозиторий, SHA, тронутые расширения, заголовок.
LIST="${1:?дай файл со списком репозиториев}"
PER="${2:-100}"
while IFS= read -r REPO; do
  [ -z "$REPO" ] && continue
  case "$REPO" in \#*) continue ;; esac
  gh api "repos/$REPO/commits?per_page=$PER" \
     --jq '.[] | "\(.sha)\t\(.commit.message | split("\n")[0])"' 2>/dev/null \
  | while IFS="$(printf '\t')" read -r SHA MSG; do
      case "$(printf '%s' "$MSG" | tr 'A-Z' 'a-z')" in
        fix*|revert*|hotfix*|bug*) ;;
        *) continue ;;
      esac
      # ПУТИ, А НЕ РАСШИРЕНИЯ. Первый заход писал только расширения, и по ним нельзя отличить
      # починку свода от починки любого текста. Замер 2026-09-15: `md` — самый часто чинимый
      # тип в 15 репозиториях из 38, и без пути это знание бесполезно.
      #
      # Берём только ОБВЯЗКУ — то, про что наши записи: свод правил, настройки агента, конвейер,
      # описание сервера, манифест пакета. Починка в коде продукта нам ничего не говорит: там
      # чинят предметную область, а не то, чем её проверяют.
      PATHS=$(gh api "repos/$REPO/commits/$SHA" --jq '.files[]?.filename' 2>/dev/null \
        | grep -iE '(^|/)(AGENTS|CLAUDE|GEMINI|CONTRIBUTING|README)\.md$|(^|/)\.claude/|(^|/)\.github/workflows/|(^|/)\.mcp\.json$|(^|/)package\.json$|(^|/)\.cursorrules$|(^|/)\.pre-commit-config\.ya?ml$' \
        | head -4 | tr '\n' ',' | sed 's/,$//')
      [ -z "$PATHS" ] && continue
      printf '%s\t%s\t%s\t%s\n' "$REPO" "$SHA" "$PATHS" "$MSG"
    done
done < "$LIST"
